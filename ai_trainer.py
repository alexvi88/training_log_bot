def _clean_program_name(raw: Any, fallback: str) -> tuple[str, bool]:
    """Название (программы или дня), обрезанное до PROGRAM_NAME_LIMIT.

    Возвращает (имя, было ли обрезано) — раньше обрезка была совсем немой
    (см. A11): 48 символов на живом названии почти всегда режут его посреди
    слова, и об этом стоит явно сказать модели, а не только приплюсовывать к
    общему truncated_days/truncated_exercises, которые вообще про другое.
    """
    name = str(raw or "").strip()
    if not name:
        return fallback, False
    return name[:PROGRAM_NAME_LIMIT], len(name) > PROGRAM_NAME_LIMIT


def _unique_day_name(name: str, taken: set[str]) -> str:
    """Имя дня, не повторяющее уже занятые в этом же предложении.

    Дни программы — это кнопки на одном экране (keyboards.program_days_keyboard),
    и два «Дня 1» подряд там неразличимы: какой из них какой, видно только
    открыв оба. Модель их иногда и присылает — забыв переименовать
    сгенерированные по шаблону дни. Разводим суффиксом, а не отбрасыванием:
    состав у них разный, и терять день из-за имени было бы куда хуже.

    Занятое имя пополняется тем, что реально ушло в программу, поэтому «День 1,
    День 1, День 1 (2)» не схлопнется в два одинаковых «День 1 (2)».
    """
    key = name.strip().lower()
    if key not in taken:
        taken.add(key)
        return name
    for suffix in range(2, PROGRAM_MAX_DAYS + 2):
        # Суффикс не должен вытолкнуть имя за общий потолок длины: place под
        # него отрезаем от самого имени, как и _clean_program_name.
        marker = f" ({suffix})"
        candidate = name[: PROGRAM_NAME_LIMIT - len(marker)].rstrip() + marker
        if candidate.strip().lower() not in taken:
            taken.add(candidate.strip().lower())
            return candidate
    taken.add(key)
    return name


def _clean_int(raw: Any, low: int, high: int) -> Optional[int]:
    """Целое из того, что прислала модель, зажатое в границы; None на мусоре."""
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return None
    return max(low, min(value, high))


def _clean_progression(raw: Any) -> Optional[dict[str, Any]]:
    """Правило прогрессии одного упражнения — {"rule", "reps_top"?, "step"?}.

    5.6/3.2: раньше прогрессия существовала только прозой в ответе тренера и
    терялась вместе с чатом (см. PROGRAMS_DEEP_DIVE §3.2) — теперь она едет
    вместе с самим предложением и сохраняется на routine_exercises.progression
    (db.set_routine_exercise_progression). `rule` — закрытый список
    (PROGRESSION_RULES): свободную строку от модели хранить некому
    интерпретировать. Мусор (неизвестное правило, не-объект) — не поле в
    отличие от sets/reps: тут нечего клампить в разумный дефолт, поэтому просто
    отбрасываем прогрессию целиком, а не всё упражнение.
    """
    if not isinstance(raw, dict):
        return None
    rule = str(raw.get("rule") or "").strip()
    if rule not in PROGRESSION_RULES:
        return None
    out: dict[str, Any] = {"rule": rule}
    step = _as_number(raw.get("step"))
    if step is not None:
        out["step"] = max(PROGRESSION_MIN_STEP, min(step, PROGRESSION_MAX_STEP))
    if raw.get("reps_top") is not None:
        reps_top = _clean_int(raw.get("reps_top"), 1, PROGRAM_MAX_REPS)
        if reps_top is not None:
            out["reps_top"] = reps_top
    return out


def _clean_program_item(raw: Any) -> Optional[dict[str, Any]]:
    """Одно упражнение из предложенной программы: имя плюс схема подходов.

    Схема необязательна — тренер может задать только подходы или только
    повторы. Перевёрнутый диапазон («10-5») разворачиваем, а не отбрасываем:
    смысл его очевиден, а терять из-за этого упражнение незачем.

    `clamped` в результате — человекочитаемые пометки о том, что подходы или
    повторы вышли за границы схемы и были зажаты (например «sets 25→10» или
    «reps 100–200→50–50», см. A11) — раньше это происходило молча, и итоговая
    цель «10×50» ничем не отличалась от честно предложенных тренером 10×50.
    """
    if isinstance(raw, str):
        raw = {"name": raw}
    if not isinstance(raw, dict):
        return None
    name = str(raw.get("name") or "").strip()
    if not name:
        return None

    def _raw_int(value: Any) -> Optional[int]:
        try:
            return int(value)
        except (TypeError, ValueError):
            return None

    raw_sets, raw_reps_min, raw_reps_max = (
        _raw_int(raw.get("sets")), _raw_int(raw.get("reps_min")), _raw_int(raw.get("reps_max"))
    )
    sets = _clean_int(raw.get("sets"), 1, PROGRAM_MAX_SETS)
    reps_min = _clean_int(raw.get("reps_min"), 1, PROGRAM_MAX_REPS)
    reps_max = _clean_int(raw.get("reps_max"), 1, PROGRAM_MAX_REPS)
    if reps_min and reps_max and reps_min > reps_max:
        reps_min, reps_max = reps_max, reps_min

    clamped: list[str] = []
    if raw_sets is not None and sets != raw_sets:
        clamped.append(f"sets {raw_sets}→{sets}")
    if raw_reps_min is not None and raw_reps_max is not None and (
        reps_min != raw_reps_min or reps_max != raw_reps_max
    ):
        clamped.append(f"reps {raw_reps_min}–{raw_reps_max}→{reps_min}–{reps_max}")
    elif raw_reps_min is not None and reps_min != raw_reps_min:
        clamped.append(f"reps_min {raw_reps_min}→{reps_min}")
    elif raw_reps_max is not None and reps_max != raw_reps_max:
        clamped.append(f"reps_max {raw_reps_max}→{reps_max}")

    progression = _clean_progression(raw.get("progression"))
    if progression is not None:
        rule = progression["rule"]
        if rule == "double_progression" and reps_max is not None:
            # reps_top живёт отдельным полем от схемы, и модель их регулярно
            # рассинхронизирует (target 5-12, reps_top=8), а без reps_top
            # подсказка веса падала на глобальный REP_RANGE_MAX вместо
            # диапазона этого упражнения. Верх диапазона — единственное
            # осмысленное значение, поэтому подставляем его, а не отбрасываем
            # правило; пометка в clamped — чтобы модель узнала о подмене.
            reps_top = progression.get("reps_top")
            if reps_top != reps_max:
                progression["reps_top"] = reps_max
                clamped.append(
                    f"reps_top {reps_top if reps_top is not None else '(не задан)'}→{reps_max}"
                )
        if rule == "linear_load" and "step" not in progression:
            # linear_load без step — правило-пустышка: валидацию оно проходило,
            # а подсказка веса молча деградировала в дефолт. Клампить нечем
            # (осмысленный шаг зависит от железа), так что честнее отбросить
            # и сказать об этом модели, чем хранить неработающее правило.
            progression = None
            clamped.append("progression linear_load без step — отброшена")

    return {
        "name": name,
        "sets": sets,
        "reps_min": reps_min,
        "reps_max": reps_max,
        "clamped": clamped,
        "progression": progression,
    }


async def _resolve_replaced_program(
    user_id: int, raw_name: Any
) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    """Какую сохранённую программу заменяет предложение. Возвращает (цель, ошибка).

    A4: раньше совпадение искалось вручную по `row["program_name"].lower()` над
    `db.list_programs`, а таблица `programs` дедуплицирует имена по Python-
    свёрнутому `name_key` (см. db._program_key) — «Сплит» и «сплит» были для
    резолвера одной программой, а для SQLite-сравнения в другом месте — разными,
    и промах удалял программу, которую пользователь не упоминал. Теперь ровно
    та же свёртка, что и в уникальном индексе: db.find_program_by_name.

    Совпадение только точное (с точностью до регистра и пробелов): промах здесь
    стоит пользователю удалённой программы, так что «похожее» имя лучше вернуть
    модели ошибкой, чем угадывать. `id` программы (или одиночной routine)
    сохраняется в результате и переживает до сохранения — по нему, а не по
    имени, происходит правка в момент тапа (см. handlers.ai_trainer, A7):
    имя к тому моменту могло смениться руками, программу могли переименовать
    или удалить, а id остаётся однозначной ссылкой. `routine_ids`, снятые здесь,
    — то же самое, зафиксированное на момент предложения, для обратной
    совместимости со старым форматом диффа; актуальный список на момент
    сохранения перечитывается по id заново.

    `kind` различает многодневку и одиночную программу (см. _saved_programs) —
    раньше резолвер сначала проверял многодневки, потом одиночные, и при
    совпадении имён между ними правилась не та программа, на которую
    рассчитывал пользователь.

    Вместе с id забираем и текущий состав: превью показывает не только итог, но
    и что именно меняется (formatting.build_ai_program_preview), а после
    удаления старых дней сравнивать было бы уже не с чем.
    """
    name = str(raw_name or "").strip()
    if not name:
        return None, None

    async def _snapshot(routines: list[Any]) -> list[dict[str, Any]]:
        return [
            {
                "name": routine["name"],
                "items": [
                    {
                        "name": ex["display_name"],
                        "target": ex["target"],
                        "progression": _stored_progression(ex["progression"]),
                    }
                    for ex in await db.list_routine_exercises(routine["id"])
                ],
            }
            for routine in routines
        ]

    program = await db.find_program_by_name(user_id, name)
    if program is not None:
        days = await db.list_program_days_by_id(program["id"])
        return (
            {
                "kind": "program",
                "id": program["id"],
                "name": program["name"],
                "routine_ids": [d["id"] for d in days],
                "days": await _snapshot(days),
            },
            None,
        )
    # Многодневки с таким именем нет — может, это одиночная программа (день без
    # program_id). Имена одиночных routines живут в другом пространстве
    # (routines.name, не programs.name), собственного «свёрнутого» индекса у
    # них нет, поэтому сверяем как раньше — Python str.lower() уже свёртывает
    # юникод корректно (в отличие от SQL LOWER(), см. db._program_key).
    for routine in await db.list_standalone_routines(user_id):
        if routine["name"].strip().lower() == name.lower():
            return (
                {
                    "kind": "routine",
                    "id": routine["id"],
                    "name": routine["name"],
                    "routine_ids": [routine["id"]],
                    "days": await _snapshot([routine]),
                },
                None,
            )
    return None, (
        f"программы «{name}» у пользователя нет — replaces_program проигнорирован, "
        "предложение показано как НОВАЯ программа. Возьми точное имя из "
        "get_saved_programs и вызови инструмент ещё раз, если хотел править существующую."
    )


async def _delete_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Разобрать просьбу удалить программу — и ничего не удалить.

    Возвращает (payload для модели, цель для кнопки). Резолвится тем же
    _resolve_replaced_program, что и правка: та же точная сверка имени (промах
    здесь стоил бы пользователю чужой программы), то же различение многодневки
    и одиночного дня.

    Удаление — единственное необратимое, о чём тренера можно попросить, поэтому
    оно устроено как propose_program, а не как save_athlete_profile: инструмент
    только называет цель, сносит её тап пользователя на обычном экране
    подтверждения (см. keyboards.ai_program_delete_cb). Модель, которая
    неправильно поняла «убери сведения из дня ног» и потянулась удалять
    программу целиком, стоит человеку одного «❌ Отмена», а не программы.
    """
    name = str(tool_input.get("name") or "").strip()
    if not name:
        return {"error": "нужно имя программы — возьми точное из get_saved_programs"}, None
    target, error = await _resolve_replaced_program(user_id, name)
    if target is None:
        saved = [p["name"] for p in (await _saved_programs(user_id))["programs"]]
        return (
            {
                "error": f"программы «{name}» у пользователя нет, ничего не предложено",
                "saved_programs": saved,
                "note": "Возьми точное имя из этого списка и вызови ещё раз." if saved
                        else "Сохранённых программ нет вообще — удалять нечего.",
            },
            None,
        )
    return (
        {
            "ok": True,
            "proposed": {"name": target["name"], "kind": target["kind"], "days": len(target["days"])},
            "note": (
                "НЕ УДАЛЕНО. Под твоим ответом появилась кнопка «🗑 Удалить: "
                f"{target['name']}» — программа исчезнет, только когда пользователь "
                "нажмёт её и подтвердит. Так и скажи: удалить готов, кнопка ниже."
            ),
        },
        {
            # Кнопку под ответом видит человек — переводим через каталог
            # (ai.action.*), имя программы подставляем как есть (данные
            # пользователя, не текст интерфейса). Note чуть ниже нарочно не
            # трогаем: это подсказка модели, а не то, что рисуется кнопкой.
            "label": i18n.t("ai.action.delete_program", name=target["name"]),
            # Тот же экран подтверждения, что и удаление руками, — с проверкой
            # владельца и «точно?». Тренер сам ничего не сносит.
            "callback": (
                f"rt:pgmdelask:{target['id']}" if target["kind"] == "program"
                else f"rt:delask:{target['id']}"
            ),
        },
    )


# ---------- программы: переименовать, скопировать, объединить, поделиться ----------
#
# Граница между «инструмент делает сам» и «инструмент только предлагает кнопку»
# проходит по обратимости, а не по важности. Переименование и копия ничего не
# разрушают: имя возвращается тем же инструментом, лишняя копия удаляется
# кнопкой. Объединение, удаление и «поделиться» — нет: два сплита обратно не
# разъединить (UI не умеет вынимать день из программы), а визитка, однажды
# отправленная в чат, уже отправлена. Ровно то же различение действует и в
# ручном UI — «📄 Дублировать» там без вопросов, «🔗 Объединить» с «точно?».


# Что тренер говорит пользователю про сделанную запись. Раньше почти во всех
# этих инструментах стояло «уже сделано, подтверждать нечего» — из-за чего
# модель бодро сообщала о записи и на этом успокаивалась. Теперь под ответом
# висит кнопка отката, и о ней надо сказать: молчаливая правка, о которой
# человек узнаёт постфактум, — ровно то, чего он и боится.
_UNDO_NOTE = (
    "Уже сделано. Под твоим ответом стоит кнопка отката — скажи об этом одной "
    "короткой фразой, чтобы человек знал, что это отменяется одним тапом. "
    "Если правок в этом ходе несколько, кнопка на них одна общая: не обещай "
    "кнопку на каждую запись."
)


async def _rename_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Переименовать сохранённую программу — сразу, с кнопкой отката.

    «Откатывается тем же вызовом» — так это было устроено раньше, и это
    неправда с точки зрения человека: чтобы попросить вернуть старое имя, его
    надо помнить, а в ответе тренера оно могло и не прозвучать. Старое имя
    знает вот этот код — он его и кладёт в кнопку.
    """
    name = str(tool_input.get("name") or "").strip()
    new_name = str(tool_input.get("new_name") or "").strip()
    if not new_name:
        return {"error": "нужно новое имя (new_name)"}, None
    target, _ = await _resolve_replaced_program(user_id, name)
    if target is None:
        return await _no_such_program(user_id, name), None
    if target["kind"] == "program":
        renamed = await db.rename_program_by_id(target["id"], new_name)
    else:
        # У одиночных программ имя живёт в routines.name — уникального индекса
        # на нём нет, отказать тут нечему.
        await db.rename_routine(target["id"], new_name)
        renamed = True
    if not renamed:
        return {
            "error": f"«{new_name}» уже занято другой программой",
            "note": "Предложи другое имя или спроси, не объединить ли их (merge_programs).",
        }, None
    return (
        {
            "ok": True,
            "renamed": {"from": target["name"], "to": new_name},
            "note": _UNDO_NOTE,
        },
        {
            "label": i18n.t("ai.action.revert_name", name=target["name"]),
            "undo": {
                "kind": "program_name" if target["kind"] == "program" else "routine_name",
                "id": target["id"],
                "name": target["name"],
            },
        },
    )


async def _copy_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Дубликат программы со всеми днями и схемами — сразу, как «📄 Дублировать»
    в ручном UI: копия ничего не портит. Но и убирать её вручную незачем —
    кнопка отката сносит ровно ту копию, которую только что создали."""
    name = str(tool_input.get("name") or "").strip()
    target, _ = await _resolve_replaced_program(user_id, name)
    if target is None:
        return await _no_such_program(user_id, name), None
    if target["kind"] != "program":
        source_days = [await db.get_routine(target["id"])]
    else:
        source_days = list(await db.list_program_days_by_id(target["id"]))
    over_budget = await db.routine_budget(user_id, len(source_days))
    if over_budget:
        return {"error": over_budget}, None
    wanted = str(tool_input.get("new_name") or "").strip() or target["name"]
    copy_name = await db.unique_program_name(user_id, wanted)
    # Копия наследует описание оригинала: у многодневки оно лежит в programs, у
    # одиночного дня программы нет вовсе — брать неоткуда.
    source_program = await db.get_program(target["id"]) if target["kind"] == "program" else None
    copy_id = await db.create_program(
        user_id, copy_name,
        description=source_program["description"] if source_program else None,
    )
    if copy_id is None:  # разошлись с параллельной вставкой — имени уже нет
        return {"error": f"«{copy_name}» успели занять, попробуй другое имя"}, None
    for day in source_days:
        day_id = await db.create_routine(user_id, day["name"], program_id=copy_id)
        for ex in await db.list_routine_exercises(day["id"]):
            await db.append_routine_exercise(day_id, ex["exercise_id"], ex["target"])
            if ex["progression"]:
                entry = (await db.list_routine_exercises(day_id))[-1]
                await db.set_routine_exercise_progression(entry["id"], ex["progression"])
    return (
        {
            "ok": True,
            "copied": {"from": target["name"], "to": copy_name, "days": len(source_days)},
            "note": f"Копия «{copy_name}» создана. {_UNDO_NOTE}",
        },
        {
            "label": i18n.t("ai.action.remove_copy", name=copy_name),
            "undo": {"kind": "program_new", "id": copy_id, "name": copy_name},
        },
    )


async def _merge_programs(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Слить две многодневки в одну — только предложением: обратно UI дни не
    разбирает, так что промах стоил бы человеку структуры обеих программ."""
    name = str(tool_input.get("name") or "").strip()
    into = str(tool_input.get("into") or "").strip()
    source, _ = await _resolve_replaced_program(user_id, name)
    if source is None:
        return await _no_such_program(user_id, name), None
    target, _ = await _resolve_replaced_program(user_id, into)
    if target is None:
        return await _no_such_program(user_id, into), None
    if source["id"] == target["id"] and source["kind"] == target["kind"]:
        return {"error": "это одна и та же программа"}, None
    if source["kind"] != "program" or target["kind"] != "program":
        return (
            {
                "error": "объединять умею только многодневки",
                "note": "Одиночная программа — это один день; чтобы добавить его к "
                        "многодневке, собери её заново через propose_program с "
                        "replaces_program.",
            },
            None,
        )
    return (
        {
            "ok": True,
            "proposed": {"from": source["name"], "into": target["name"]},
            "note": (
                f"НЕ ОБЪЕДИНЕНО. Под ответом кнопка «🔗 Объединить: {source['name']} → "
                f"{target['name']}» — дни переедут, только когда пользователь нажмёт "
                "её и подтвердит. Скажи, что готов, кнопка ниже."
            ),
        },
        {
            "label": i18n.t("ai.action.merge_programs", source=source["name"], target=target["name"]),
            "callback": f"ai:pgmmergeask:{source['id']}:{target['id']}",
        },
    )


async def _share_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Визитка программы, которую можно переслать кому угодно. Кнопкой, а не
    сразу: сообщение уходит в чат, и отправлять его должен человек."""
    name = str(tool_input.get("name") or "").strip()
    target, _ = await _resolve_replaced_program(user_id, name)
    if target is None:
        return await _no_such_program(user_id, name), None
    callback = (
        f"share:prg:{target['id']}" if target["kind"] == "program"
        else f"share:rt:{target['id']}"
    )
    return (
        {
            "ok": True,
            "proposed": {"name": target["name"], "kind": target["kind"]},
            "note": (
                f"Под ответом кнопка «📤 Поделиться: {target['name']}» — она пришлёт "
                "визитку со ссылкой, которую можно переслать кому угодно. Пока "
                "пользователь не нажал, ничего не отправлено."
            ),
        },
        {"label": i18n.t("ai.action.share", name=target["name"]), "callback": callback},
    )


