async def _resolve_own_exercise(user_id: int, name: str) -> Optional[Any]:
    """Своё упражнение по имени — точно, как его резолвят программы и импорт.

    Только своё и только не архивное: «переименуй жим» про шаблон каталога
    означало бы переименование у всех, а про архивное — правку того, чего
    пользователь у себя уже не видит.
    """
    name = name.strip()
    if not name:
        return None
    found = await db.find_exercise_by_name(user_id, name)
    if found is not None and found["user_id"] == user_id and not found["is_template"]:
        return found
    return None


async def _no_such_exercise(user_id: int, name: str) -> dict[str, Any]:
    return {
        "error": f"упражнения «{name}» у пользователя нет",
        "note": "Возьми точный display_name из get_training_overview и вызови ещё раз. "
                "Если упражнения действительно нет, а нужно — create_exercise.",
    }


async def _resolve_group_id(user_id: int, name: str) -> Optional[int]:
    """Группа по имени — как дали, или как ПОКАЗАННОЕ имя.

    Имя группы в базе русское навсегда (группы глобальные, не форкаются), а
    модель видит их на языке атлета — из get_training_overview и из наших же
    экранов. Пока обратного хода не было, тренер звал create_exercise с
    group="Chest", получал «такой группы нет» со списком русских имён, а потом
    называл по-русски и само упражнение: так у англоязычного и появлялись
    «Приседания с собственным весом».
    """
    wanted = name.strip().casefold()
    canonical = canonical_muscle_group_name(name)
    for group in await db.list_muscle_groups(user_id):
        own = group["name"].strip()
        if own.casefold() == wanted or (canonical and own == canonical):
            return group["id"]
    return None


async def _create_exercise(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Завести своё упражнение — сразу: добавление ничего не разрушает.

    Откат сносит его целиком (db.delete_exercise_if_unused), а не архивирует:
    в архиве копился бы мусор, которого пользователь не заводил.
    """
    name = str(tool_input.get("name") or "").strip()
    group_name = str(tool_input.get("group") or "").strip()
    if not name:
        return {"error": "нужно название упражнения"}, None
    existing = await _resolve_own_exercise(user_id, name)
    if existing is not None:
        return {
            "ok": True,
            "already_exists": existing["display_name"],
            "note": "Такое упражнение у пользователя уже есть — ничего не создавал.",
        }, None
    groups = await db.list_muscle_groups(user_id)
    group_id = await _resolve_group_id(user_id, group_name) if group_name else None
    if group_id is None:
        return {
            "error": f"группы «{group_name}» нет" if group_name else "нужна группа мышц",
            "muscle_groups": [g["name"] for g in groups],
            "note": "Выбери группу из этого списка и вызови ещё раз.",
        }, None
    if len(name) > config.MAX_EXERCISE_NAME_LENGTH:
        return {"error": f"название длиннее {config.MAX_EXERCISE_NAME_LENGTH} символов"}, None
    exercise_id = await db.create_exercise(user_id, name, group_id)
    created = await db.get_exercise(exercise_id)
    return (
        {
            "ok": True,
            "created": {"name": created["display_name"], "group": group_name},
            "note": _UNDO_NOTE,
        },
        {
            "label": i18n.t("ai.action.remove_created", name=created["display_name"]),
            "undo": {
                "kind": "exercise_new",
                "id": exercise_id,
                "name": created["display_name"],
            },
        },
    )


async def _rename_exercise(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Переименовать в том же ряду (id не меняется), поэтому вся история,
    рекорды и место в программах остаются на нём.

    Старое имя уезжает в кнопку отката: «откатывается тем же вызовом» верно
    только для того, кто это имя ещё помнит.
    """
    name = str(tool_input.get("name") or "").strip()
    new_name = str(tool_input.get("new_name") or "").strip()
    if not new_name:
        return {"error": "нужно новое имя (new_name)"}, None
    if len(new_name) > config.MAX_EXERCISE_NAME_LENGTH:
        return {"error": f"название длиннее {config.MAX_EXERCISE_NAME_LENGTH} символов"}, None
    exercise = await _resolve_own_exercise(user_id, name)
    if exercise is None:
        return await _no_such_exercise(user_id, name), None
    if not await db.update_exercise_name(exercise["id"], new_name):
        return {"error": f"упражнение «{new_name}» у пользователя уже есть"}, None
    renamed = await db.get_exercise(exercise["id"])
    return (
        {
            "ok": True,
            "renamed": {"from": exercise["display_name"], "to": renamed["display_name"]},
            "note": f"История и рекорды остались на нём. {_UNDO_NOTE}",
        },
        {
            "label": i18n.t("ai.action.revert_name", name=exercise["display_name"]),
            "undo": {
                "kind": "exercise_name",
                "id": exercise["id"],
                "name": exercise["display_name"],
            },
        },
    )


async def _move_exercise(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Сменить группу мышц — сразу: подходы и история привязаны к упражнению,
    а не к группе, так что терять нечего. Но недельный объём по группам после
    этого считается иначе, поэтому прежняя группа уезжает в кнопку отката."""
    name = str(tool_input.get("name") or "").strip()
    group_name = str(tool_input.get("group") or "").strip()
    exercise = await _resolve_own_exercise(user_id, name)
    if exercise is None:
        return await _no_such_exercise(user_id, name), None
    group_id = await _resolve_group_id(user_id, group_name)
    if group_id is None:
        return {
            "error": f"группы «{group_name}» нет",
            "muscle_groups": [g["name"] for g in await db.list_muscle_groups(user_id)],
        }, None
    was_group_id = exercise["primary_group_id"]
    was_group = next(
        (g["name"] for g in await db.list_muscle_groups(user_id) if g["id"] == was_group_id),
        None,
    )
    await db.update_exercise_group(exercise["id"], group_id)
    # Группы у упражнения могло не быть вовсе — возвращать тогда не к чему,
    # и кнопки не будет.
    undo = None
    if was_group_id is not None:
        undo = {
            "label": (
                i18n.t("ai.action.revert_group_named", group=was_group) if was_group
                else i18n.t("ai.action.revert_group")
            ),
            "undo": {
                "kind": "exercise_group",
                "id": exercise["id"],
                "group_id": was_group_id,
                "name": was_group or "",
            },
        }
    return (
        {
            "ok": True,
            "moved": {"exercise": exercise["display_name"], "group": group_name},
            "note": f"Недельный объём пересчитается по ней. {_UNDO_NOTE}" if undo
                    else "Группа уже поменялась. Недельный объём пересчитается по ней.",
        },
        undo,
    )


async def _archive_exercise(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Убрать упражнение из списков — только предложением.

    Архив обратим (в ⚙️ Упражнения → 🗄 Архив), но упражнение исчезает из
    выбора, из программ его не выкинешь, и «убери сведения» модель одинаково
    легко понимает и как «из моего списка», и как «из программы». Кнопка
    делает эту разницу видимой до того, как что-то пропадёт.
    """
    name = str(tool_input.get("name") or "").strip()
    exercise = await _resolve_own_exercise(user_id, name)
    if exercise is None:
        return await _no_such_exercise(user_id, name), None
    return (
        {
            "ok": True,
            "proposed": {"name": exercise["display_name"]},
            "note": (
                f"НЕ АРХИВИРОВАНО. Под ответом кнопка «🗄 В архив: "
                f"{exercise['display_name']}». История упражнения при архивации не "
                "пропадает, вернуть его можно в ⚙️ Упражнения → 🗄 Архив."
            ),
        },
        {
            "label": i18n.t("ai.action.archive_one", name=exercise["display_name"]),
            "callback": f"ai:exarchask:{exercise['id']}",
        },
    )


async def _archive_exercises(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Как _archive_exercise, но несколько сразу — одна кнопка на все, а не
    одна на каждое (иначе «заархивируй 23 неиспользуемых» кладёт под ответом
    23 одинаковые кнопки подряд). Список id уходит через action["archive_ids"]
    — handlers.ai_trainer._register_actions прячет его в FSM за коротким
    ключом, потому что в 64 байта callback_data два десятка id не влезают."""
    names = [str(n).strip() for n in (tool_input.get("names") or []) if str(n).strip()]
    resolved = []
    missing = []
    for name in names:
        exercise = await _resolve_own_exercise(user_id, name)
        if exercise is None:
            missing.append(name)
        else:
            resolved.append(exercise)
    if not resolved:
        return await _no_such_exercise(user_id, names[0] if names else ""), None
    listed = ", ".join(ex["display_name"] for ex in resolved)
    note = (
        f"НЕ АРХИВИРОВАНО. Под ответом кнопка «🗄 В архив всё ({len(resolved)})» "
        f"— архивирует разом: {listed}."
    )
    if missing:
        note += f" Не нашёл: {', '.join(missing)}."
    return (
        {
            "ok": True,
            "proposed": {"names": [ex["display_name"] for ex in resolved]},
            "note": note,
        },
        {
            "label": i18n.t("ai.action.archive_all", n=len(resolved)),
            "archive_ids": [ex["id"] for ex in resolved],
        },
    )


