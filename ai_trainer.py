async def _send_feedback(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Жалоба на бот, идея или спасибо — тем же маршрутом, что и /feedback.

    Кнопкой, а не сразу: сообщение уходит наружу, живому человеку, и решать,
    отправлять ли его, должен тот, чьими словами оно написано. Заодно человек
    видит, что именно уедет, — тренер пересказывает своими словами, и пересказ
    бывает не тот.

    Команда /feedback никуда не девается: она принимает фото и скриншоты, а сюда
    попадает то, что человек и не собирался никуда сообщать, — просто сказал
    тренеру между делом, что что-то не работает.
    """
    text = " ".join(str(tool_input.get("message") or "").split())
    if not text:
        return {"error": "нечего передавать: в message нужен текст письма"}, None
    if config.ADMIN_ID is None:
        return (
            {
                "error": "передать некому",
                "note": (
                    "Скажи, что записать-то записал, но передать сейчас не выйдет — "
                    "пусть повторит позже через /feedback. Причину не объясняй."
                ),
            },
            None,
        )
    kind = str(tool_input.get("kind") or "").strip()
    label = FEEDBACK_KIND_LABELS.get(kind, "📬 Фидбек")
    text = text[:FEEDBACK_MAX_LEN]
    return (
        {
            "ok": True,
            "proposed": {"kind": kind or "feedback", "message": text},
            "note": (
                "НЕ ОТПРАВЛЕНО. Под ответом кнопка «📬 Передать разработчику» — "
                "письмо уйдёт от тапа пользователя. Скажи коротко, что именно "
                "передашь, и что дело за кнопкой."
            ),
        },
        {
            # Кнопка — атлету, переводим. А вот "label" внутри "feedback" ниже
            # (FEEDBACK_KIND_LABELS) — это шапка письма АДМИНУ (см.
            # handlers/ai_trainer.py.ai_send_feedback → ai.screen.feedback_header),
            # не кнопка на экране: админ читает по-русски независимо от языка
            # атлета, как и весь остальной админский текст (см. CLAUDE.md/
            # i18n_coverage.NEVER_LOCALIZED).
            "label": i18n.t("ai.action.send_feedback"),
            "feedback": {"text": text, "label": label},
        },
    )


