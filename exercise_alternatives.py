def _fold(name: str) -> str:
    return (name or "").strip().casefold().replace("ё", "е")


def alternatives_for(canonical_name: str) -> list[str]:
    """Канонические имена замен для шаблона `canonical_name`, пусто — если
    упражнения нет ни в одном семействе (или оно вовсе не из каталога)."""
    needle = _fold(canonical_name)
    result: list[str] = []
    seen = {needle}
    for family in FAMILIES:
        if needle not in {_fold(n) for n in family}:
            continue
        for name in family:
            if _fold(name) not in seen:
                seen.add(_fold(name))
                result.append(name)
    return result[:MAX_ALTERNATIVES]


async def for_exercise(user_id: int, ex, lang: Optional[str] = None) -> list[dict[str, Any]]:
    """Альтернативы упражнению `ex` (своему форку или шаблону каталога) для
    показа атлету `user_id`.

    Каждая строка — `{"name", "template_id", "exercise_id", "thumb"}`: если у
    атлета уже есть живая (не в архиве) копия этого шаблона, `exercise_id` —
    её id и открывать надо её карточку, со своей историей; иначе `None`, и
    показывать превью шаблона с «Добавить». Имя — то, что атлет видит: своё
    переименование у форка, перевод у шаблона.
    """
    names = alternatives_for(exercise_media.catalog_key(ex))
    if not names:
        return []
    lang = lang or i18n.get_lang()
    templates = await db.find_global_templates_by_names(names)
    owned = {
        _fold(r["original_name"]): r
        for r in await db.list_active_exercises_with_identity(user_id)
    }
    result = []
    for name in names:
        template = templates.get(name)
        if template is None:
            continue
        own = owned.get(_fold(name))
        result.append({
            "name": own["display_name"] if own else seed_data.localized_exercise_name(name, lang),
            "template_id": template["id"],
            "exercise_id": own["id"] if own else None,
            "thumb": exercise_media.thumb_url_for(template),
        })
    return result
