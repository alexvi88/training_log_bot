"""Общий примитив «занято» для платных AI-шагов — атомарный check-and-reserve
над `set[int]`, без единого `await` между проверкой членства и записью.

Почему это отдельный модуль, а не третья копия одного и того же кода: и у
бота (`handlers/ai_trainer._busy`, `handlers/factcheck._busy` — свой,
отдельный набор), и у REST (`/v1`, `api_v1_ai.py`/`api_v1_food.py`) один и
тот же критический разрыв. asyncio даёт кооперативную многозадачность —
переключение между задачами возможно только на `await` — поэтому ДВА
синхронных выражения подряд гарантированно не прерываются другой задачей
того же пользователя, а два выражения, разделённые хотя бы одним `await`
(например, чтение лимита из БД между ними), — уже нет.

Ровно этот разрыв и стоил денег: `_busy` появился после того, как два
быстрых сообщения одного человека оба проходили проверку дневного лимита до
того, как первое успевало отметиться где-либо — оба уходили в модель
(двойной платёж), а дневная квота, которая списывается только после
успешного ответа, могла быть превышена на число проскочивших так запросов.
См. `handlers/ai_trainer._try_claim_busy` — там разобран тот инцидент
подробно.

**Инвариант, без которого всё это бесполезно.** `set[int]` живёт в памяти
ОДНОГО процесса. Гарантия «на пользователя не больше одного платного шага в
полёте» верна только пока на аккаунт отвечает ровно один воркер — см.
`amvera.yaml`, где это закреплено комментарием у команды запуска. Если
процессов/реплик когда-нибудь станет больше одного, этот примитив
перестанет защищать хоть что-то, причём молча — ни один тест в этом файле
такое не поймает, потому что тесты запускаются в одном процессе.

**Один набор — один платёжный сценарий.** Разбор еды в приложении не должен
блокировать человеку чат тренера в тот же момент, поэтому каждый вызывающий
модуль держит СВОЙ набор (у бота их уже несколько — см. выше), а не единый
набор на все деньги сразу. Этот модуль умышленно не хранит ни одного набора
сам — только функцию, которая работает с набором, переданным вызывающим
кодом, чтобы `user_id in _busy`/`_busy.discard(user_id)`, уже читаемые
тестами (`ai_trainer._busy`, `factcheck._busy`), продолжали работать как
раньше.
"""

from __future__ import annotations


def try_claim(busy: set[int], user_id: int) -> bool:
    """Атомарно проверить и застолбить `user_id` в `busy`. True — застолбили
    (можно идти к модели), False — там уже кто-то есть (значит, тот же
    человек уже в полёте — второй платный вызов не нужен и не должен
    случиться).

    Вызывающая сторона обязана снять бронь в `finally`
    (`busy.discard(user_id)`) независимо от исхода — исключение, таймаут или
    ранний `return` внутри `try` не должны оставлять человека заблокированным
    до конца жизни процесса (в боте такой баг уже был на устаревшей кнопке
    Telegram, см. `handlers/ai_trainer.ai_build_program`)."""
    if user_id in busy:
        return False
    busy.add(user_id)
    return True
