"""Приведение слов к основе, чтобы поиск упражнений находил словоформы.

«Приседания со штангой» должно находить «Присед со штангой», «жимы» — «Жим»,
«тяги» — «Тяга». Раньше поиск был одной подстрокой целиком (`LIKE '%запрос%'`),
и любая другая форма слова — или лишнее слово посередине названия — давала
«ничего не нашлось» при полном каталоге.

Полноценный стеммер тут избыточен: названия упражнений — короткие именные
группы из десятка знакомых слов. Хватает отсечения самых частых окончаний, но с
одним важным свойством: **основа только укорачивает слово и никогда не меняет
его начало**. Поэтому основа запроса всегда остаётся префиксом искомого слова, и
поиск подстрокой по основе работает в обе стороны — «присед» и «приседания» оба
дают `присед`, который лежит внутри и «Приседа», и «Приседаний».

Второе: запрос режется на слова, и каждое слово ищется отдельно. «жим лёжа»
находит «Жим штанги лёжа», хотя целиком такой подстроки в названии нет.
"""

from __future__ import annotations

import re

# Ниже этой длины основу не режем: «тяг» ещё осмысленно, «т» уже совпадёт с
# доброй половиной каталога.
_MIN_STEM = 3

# Отглагольное существительное — самый частый источник расхождения с каталогом:
# «Присед» против «Приседаний», «Сгибание» против «Сгибаний». Суффикс и падежное
# окончание срезаются одним куском: если сначала снять «-ия», то от «приседания»
# останется «приседан», а такого куска в «Приседе» нет.
_NOUN_SUFFIXES = (
    "аниями", "ениями", "аниях", "ениях", "аниям", "ениям", "анием", "ением",
    "ания", "ании", "аний", "анию", "ения", "ении", "ений", "ению",
    "ание", "ение", "ани", "ени",
)

# Падежные и родовые окончания.
_ENDINGS = (
    "ыми", "ими", "ого", "его", "ому", "ему", "ями", "ами", "иях", "ыях",
    "ах", "ях", "ев", "ов", "ым", "им", "ом", "ем", "ам", "ям", "их", "ых",
    "ий", "ый", "ой", "ей", "ая", "яя", "ое", "ее", "ые", "ие", "ию", "ья",
    "ии", "ия", "ье", "ью",
    "а", "е", "и", "й", "о", "у", "ы", "ь", "э", "ю", "я",
)

# Порядок важен: длинный хвост проверяется раньше короткого, иначе «ями» в
# «гантелями» срезалось бы как «и» и оставляло «гантеля».
_SUFFIXES = tuple(sorted(_NOUN_SUFFIXES + _ENDINGS, key=len, reverse=True))

_CYRILLIC_RE = re.compile(r"[а-яё]", re.IGNORECASE)
_WORD_RE = re.compile(r"[^\W_]+", re.UNICODE)


def fold(text: str) -> str:
    """Регистр и ё→е — «лежа» и «лёжа» должны быть одним словом."""
    return text.lower().replace("ё", "е")


def stem(word: str) -> str:
    """Основа одного слова. Латиница, цифры и аббревиатуры остаются как есть."""
    folded = fold(word)
    if not _CYRILLIC_RE.search(folded):
        return folded
    for suffix in _SUFFIXES:
        if folded.endswith(suffix):
            candidate = folded[: -len(suffix)]
            # Слишком короткий остаток — значит хвост был частью корня («жа» из
            # «лёжа» оставила бы «л»), и слово берём целиком.
            return candidate if len(candidate) >= _MIN_STEM else folded
    return folded


def query_stems(query: str) -> list[str]:
    """Основы всех слов запроса — условия поиска, которые должны выполниться все
    сразу. Пустой список означает, что искать не по чему (пробелы, пунктуация)."""
    return [stem(word) for word in _WORD_RE.findall(query)]


# Синонимы: человек называет упражнение или мышцу своим словом, а в каталоге
# стоит другое. Стемминг тут бессилен по определению — «махи» и «разведение»
# не однокоренные, сколько окончаний ни срезай.
#
# Проверено прогоном человеческих запросов по каталогу: морфология работает
# («приседания» находят «Присед», «жим лёжа гантели» — «Жим гантелей лёжа»), а
# спотыкались ровно синонимы — «махи в стороны», «разводка», «икры».
#
# Ключ — основа слова из запроса, значения — основы, любая из которых
# засчитывается. Отношение НЕ симметричное: «икры» должны находить «Подъём на носки», а
# запрос «носки» незачем расширять до икр — он и так точен. Поэтому таблица
# односторонняя, и обратные пары добавляются только там, где обе формулировки
# ходовые.
#
# Осторожно с широкими словами: «спина» ушла бы в «Тягу», «Гиперэкстензию» и
# «Становую» разом, то есть в треть каталога, — названия групп мышц уже есть на
# экране выбора группы, и дублировать их поиском смысла нет. Здесь только те
# случаи, где иначе НЕ НАХОДИТСЯ НИЧЕГО.
_SYNONYMS: dict[str, tuple[str, ...]] = {
    # Движение названо другим словом
    "мах": ("мах", "развед"),           # «махи в стороны» → Разведение гантелей в стороны
    "разводк": ("развед",),             # «разводка» → Разведение
    "разведен": ("развед",),
    "сведен": ("свед",),
    "бабочк": ("бабочк", "свед"),       # тренажёр «бабочка» = Сведение рук
    "пек": ("бабочк", "свед"),          # pec-deck
    "брус": ("брус", "отжиман"),
    "турник": ("подтягиван",),
    "качел": ("мах", "развед"),
    # Мышца вместо движения
    "икр": ("носк",),                   # «икры» → Подъём на носки
    "голен": ("носк",),
    "пресс": ("пресс", "скручиван", "планк", "подъем ног"),
    "кор": ("планк", "скручиван"),
    "трапец": ("шраг",),
    "ягодиц": ("ягодичн", "мостик", "присед", "выпад"),
    "квадрицепс": ("присед", "разгибание ног", "жим ногами"),
    # Ключ — ОДНО слово: запрос режется по словам, и составной ключ вроде
    # «бицепс бедра» не сработал бы никогда.
    "бедр": ("сгибание ног", "румынск", "бедр"),
    "поясниц": ("гиперэкстенз",),
    "предплеч": ("запяст",),
    # Разговорные названия снаряда и хвата
    "жимовой": ("жим",),
    "штанг": ("штанг", "ez"),
    "гантел": ("гантел",),
    "блок": ("блок", "кроссовер"),
    "кроссовер": ("кроссовер", "блок"),
    "смит": ("смит",),
}


def expand(stem_value: str) -> tuple[str, ...]:
    """Во что может превратиться основа запроса. Сама основа всегда в списке —
    синонимы ДОБАВЛЯЮТ варианты, а не подменяют исходное слово."""
    alts = _SYNONYMS.get(stem_value)
    if not alts:
        return (stem_value,)
    return tuple(dict.fromkeys((stem_value, *alts)))


# Устойчивые сочетания из двух слов. По словам они не ловятся: «бицепс бедра»
# требовал бы и «бицепс», и «бедро» в одном названии, а в каталоге лежит
# «Сгибание ног» — ни одного из этих слов. Проверяется до разбиения на слова.
_PHRASES: dict[str, tuple[str, ...]] = {
    "бицепс бедра": ("сгибание ног", "румынск", "тяга на прямых"),
    "задняя поверхность бедра": ("сгибание ног", "румынск"),
    "низ спины": ("гиперэкстенз",),
}
# Пучки дельт и «верх груди» сюда НЕ попали намеренно. Поиск идёт подстрокой, и
# «задняя дельта» → «наклон» вытаскивала жимы на наклонной скамье, то есть
# грудь вместо плеч. Неверный ответ первым в выдаче хуже, чем отсутствие
# синонима: во втором случае человек переформулирует, в первом — добавит не то
# упражнение и заметит это через месяц в статистике.


def query_groups(query: str) -> list[tuple[str, ...]]:
    """Запрос → группы вариантов. Внутри группы достаточно любого совпадения,
    но выполниться должны ВСЕ группы: «жим лёжа» это и «жим», и «лёжа»."""
    folded = " ".join(_WORD_RE.findall(fold(query)))
    for phrase, alts in _PHRASES.items():
        if phrase in folded:
            rest = folded.replace(phrase, " ")
            return [alts, *(expand(s) for s in query_stems(rest))]
    return [expand(s) for s in query_stems(query)]
