def _localized_verdict_mark(verdict: Optional[str]) -> str:
    """«норма»/«отклонение»/что угодно ещё → «чисто»/«ОТКЛОНЕНИЕ»/«не смотрели»
    на языке ответа. Незнакомое значение (модель нарушила протокол) тоже
    получает «не смотрели» — то же поведение, что было раньше без i18n."""
    key = _VERDICT_MARK_KEYS.get(verdict, "ai.video.verdict_skipped")
    return i18n.t(key)


def _localized_enum(value: Optional[str], keys: dict[str, str]) -> Optional[str]:
    """confidence/severity → перевод на язык ответа, если значение из протокола
    известно; неизвестное или пустое значение возвращаем как есть — лучше
    показать сырую строку модели, чем молча её проглотить."""
    if not value:
        return value
    return i18n.t(keys[value]) if value in keys else value

# Thinking-модель печатает цепочку рассуждений в тот же content, что и ответ, и
# заворачивает её в <think>…</think>. json.loads на таком тексте падает, и весь
# разбор уходит в None — то есть переключение на thinking без этой чистки просто
# выключило бы фичу целиком.
_THINK_BLOCK_RE = re.compile(r"<think>.*?</think>", re.DOTALL | re.IGNORECASE)
# Незакрытый <think> — обрыв по потолку токенов посреди рассуждения. JSON в этом
# случае не начинался, спасать нечего, но отличать это в логах нужно.
_UNCLOSED_THINK_RE = re.compile(r"<think>", re.IGNORECASE)


def _strip_reasoning(raw: str) -> str:
    """Убрать цепочку рассуждений, оставив JSON.

    Модель иногда печатает <think> вокруг рассуждения, иногда обрамляет ответ
    ```json … ```, а иногда делает и то и другое. Режем оба слоя и на всякий
    случай берём текст от первой { до последней } — лишняя болтовня до или
    после объекта встречается и без всяких маркеров.
    """
    text = _THINK_BLOCK_RE.sub("", raw).strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[-1] if "\n" in text else text
        text = text.rsplit("```", 1)[0]
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        return text[start : end + 1]
    return text.strip()


def _is_unobservable(text: str) -> bool:
    low = text.lower()
    return any(marker in low for marker in _UNOBSERVABLE_MARKERS)


def _frame_list(raw: Any) -> list[int]:
    """Номера кадров из ответа модели: числа или строки с числом, без повторов."""
    out: list[int] = []
    for value in raw if isinstance(raw, list) else []:
        if isinstance(value, bool):
            continue
        if isinstance(value, str) and value.strip().isdigit():
            value = int(value.strip())
        if isinstance(value, int) and value not in out:
            out.append(value)
    return out


def _clean_checklist(raw: Any) -> list[dict[str, Any]]:
    """Контрольные точки от модели → то, за что она отчиталась на самом деле.

    Одно правило и одна причина. «Норма» без описания увиденного — это не
    результат осмотра, а проставленная галочка, и стоит она дороже любой другой
    ошибки: тренер поверит и посоветует грузить кривой паттерн (ровно так он и
    сказал «наращивай нагрузку» на круглой спине). Поэтому такая точка
    понижается до «не видно» — честного «мы не знаем», — а не выбрасывается:
    исчезнувшая точка выглядела бы как непройденная, и мы бы не отличили её от
    той, что модель забыла вовсе.
    """
    cleaned: list[dict[str, Any]] = []
    for item in raw or []:
        if not isinstance(item, dict):
            continue
        point = str(item.get("point") or "").strip().lower()
        if point not in CHECKPOINTS:
            continue
        verdict = str(item.get("verdict") or "").strip().lower()
        if verdict not in _VERDICTS:
            verdict = "не видно"
        seen = str(item.get("what_i_see") or "").strip()
        if verdict != "не видно" and not seen:
            logger.info("video sanitize: точка «%s» без описания → «не видно»", point)
            verdict = "не видно"
        cleaned.append({
            "point": point, "verdict": verdict, "what_i_see": seen, "when": item.get("when"),
            "frames": _frame_list(item.get("frames")),
        })

    by_point = {item["point"]: item for item in cleaned}
    missing = [p for p in CHECKPOINTS if p not in by_point]
    if missing:
        # Не достраиваем: пункт, который модель не прошла, так и остаётся
        # непройденным. Тренеру он приедет как «не смотрели» — это правда, а
        # выдуманная за модель «норма» была бы той самой галочкой.
        logger.warning("video sanitize: модель пропустила точки %s", missing)
    return [by_point[p] for p in CHECKPOINTS if p in by_point]


# Противоречие между точками: одно и то же место тела на одном и том же кадре
# одна точка описывает как отклонение, другая — как норму. Живой случай (тяга в
# тренажёре): «спина — отклонение: в пиковой точке (0:02) … уводя лопатки от
# позвоночника» и «амплитуда — норма: полное сведение лопаток в верхней точке
# (0:02)». Тренер взял первое и сказал атлету как факт. Какая из двух правда —
# по тексту не узнать, а обвинять атлета в том, чего модель сама не уверена,
# хуже, чем промолчать: спорное отклонение понижается до «не видно».
_BODY_PARTS: dict[str, tuple[str, ...]] = {
    "лопатки": ("лопат",),
    "спина": ("спин", "грудн", "поясниц"),
}
# Пары противоположных описаний: (как у отклонения, как у нормы) — в обе стороны.
_OPPOSITES: tuple[tuple[tuple[str, ...], tuple[str, ...]], ...] = (
    (("свед", "свод"), ("развед", "разъезж", "от позвоночника")),
    (("округл", "сутул", "горб"), ("прям", "нейтрал", "ровн")),
)
_TIMESTAMP_RE = re.compile(r"\b(\d{1,2}:\d{2})\b")
# Путь по кадрам ссылается не на 0:02, а на «кадр 5» / «кадры 5–6».
_FRAME_REF_RE = re.compile(r"кадр\w*\s+(\d+)")


def _claims(text: str) -> list[tuple[frozenset[str], str, int, int]]:
    """Утверждения текста: (кадры, часть тела, номер пары, сторона пары).

    Текст режется на предложения: в одном описании точки бывает и «в начале
    спина прямая», и «в пиковой точке округляет» — сравнивать надо предложение
    с предложением, а не всё со всем."""
    out = []
    for sentence in re.split(r"(?<=[.!?;])\s+", text.lower()):
        stamps = frozenset(
            _TIMESTAMP_RE.findall(sentence) + [f"#{n}" for n in _FRAME_REF_RE.findall(sentence)]
        )
        if not stamps:
            continue
        for part, markers in _BODY_PARTS.items():
            if not any(m in sentence for m in markers):
                continue
            for pair_no, sides in enumerate(_OPPOSITES):
                for side_no, words in enumerate(sides):
                    if any(w in sentence for w in words):
                        out.append((stamps, part, pair_no, side_no))
    return out


def _drop_contradictions(
    checklist: list[dict[str, Any]], observations: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Отклонение, которое на том же кадре про ту же часть тела спорит с нормой
    другой точки, → «не видно»; наблюдения с тем же утверждением — вон."""
    norms = [(item, _claims(item.get("what_i_see") or "")) for item in checklist if item["verdict"] == "норма"]
    disputed: list[tuple[str, int, int]] = []
    for item in checklist:
        if item["verdict"] != "отклонение":
            continue
        clash = None
        for stamps, part, pair_no, side_no in _claims(item.get("what_i_see") or ""):
            for norm_item, norm_claims in norms:
                for n_stamps, n_part, n_pair, n_side in norm_claims:
                    if n_part == part and n_pair == pair_no and n_side != side_no and stamps & n_stamps:
                        clash = norm_item["point"]
                        disputed.append((part, pair_no, side_no))
        if clash:
            logger.warning(
                "video sanitize: «%s» (отклонение) спорит с «%s» (норма) на том же кадре → «не видно»",
                item["point"], clash,
            )
            item["verdict"] = "не видно"
            item["what_i_see"] = (
                f"описание этой точки противоречит точке «{clash}» на том же кадре — "
                "по видео не судим"
            )
    if not disputed:
        return checklist, observations
    kept = []
    for obs in observations:
        text = f"{obs.get('what') or ''} {obs.get('evidence') or ''}".lower()
        hit = any(
            any(m in text for m in _BODY_PARTS[part]) and any(w in text for w in _OPPOSITES[pair_no][side_no])
            for part, pair_no, side_no in disputed
        )
        if hit:
            logger.warning("video sanitize: наблюдение «%s» снято как спорное", obs.get("what"))
        else:
            kept.append(obs)
    return checklist, kept


# Жим лёжа: модель упорно путает направление дуги. Живой провал (свободная
# штанга, камера сбоку со стороны головы): гриф вверху над плечами, касание
# на низе груди, на подъёме уходит обратно к голове — учебная дуга, а разбор
# написал «гриф уходит к лицу вместо плеч», и тренер выдал норму за ошибку.
# Правило в промпте про это уже было, и модель всё равно перепутала —
# словами не лечится. Поэтому модель отдельно называет две точки по телу
# (`bar_path`), а решение о дуге принимает код: верх над плечами и касание
# на низе или середине груди — траектория в норме, а утверждения о
# направлении снаряда снимаются.
_LYING_PRESS_MARKERS = (
    ("жим", "лёж"), ("жим", "леж"), ("жим", "скамь"), ("жим", "горизонт"), ("bench",),
)
_BAR_WORDS = ("гриф", "штанг", "снаряд", "гантел", "рукоят", "траектор", "bar", "dumbbell")
# Только слова о направлении дуги: перекос грифа или неровный темп — другие
# ошибки, и их код не трогает. «За голову» и «назад» — из живого провала
# 2.11.2026 (съёмка со стороны ног): без них наблюдение «на подъёме уходит
# назад за голову» пережило бы даже сработавшую проверку и доехало до тренера.
_DIRECTION_WORDS = (
    "к лицу", "от лица", "к голове", "за голов", "к шее", "к плечам", "к ногам", "к животу",
    "к поясу", "назад", "вперёд", "вперед", "дуг",
    "toward the face", "towards the face", "toward the head", "towards the head",
    "behind the head", "toward the feet", "towards the feet", "arc",
)


def _is_lying_press(*names: Optional[str]) -> bool:
    for name in names:
        low = (name or "").lower()
        if any(all(m in low for m in group) for group in _LYING_PRESS_MARKERS):
            return True
    return False


def _top_over_shoulders(text: str) -> bool:
    """«над плечами», «над плечевыми суставами», «over the shoulders» — да;
    над лицом, шеей, за плечами, «не видно» — нет."""
    low = text.lower()
    if any(bad in low for bad in ("лиц", "шея", "шеи", "шее", "шею", "голов", "за плеч", "не видно", "face", "neck", "head", "behind", "not visible")):
        return False
    return "плеч" in low or "shoulder" in low


def _touch_on_lower_chest(text: str) -> bool:
    """Касание на низе или середине груди (грудины, на уровне сосков) — да;
    верх груди, ключицы, шея, живот — нет."""
    low = text.lower()
    if any(bad in low for bad in ("верх", "ключиц", "шея", "шеи", "шее", "шею", "живот", "не видно", "upper", "collarbone", "neck", "belly", "not visible")):
        return False
    on_chest = any(w in low for w in ("груд", "сосок", "соск", "chest", "sternum", "nipple"))
    low_or_mid = any(w in low for w in ("низ", "нижн", "середин", "сосок", "соск", "lower", "bottom", "mid", "nipple"))
    return on_chest and low_or_mid


def _bar_path_points(bar_path: Any, reps: Any) -> Optional[tuple[str, str]]:
    """Две точки дуги, подтверждающие норму, — из bar_path, а если там пусто или
    мимо — из повторов шага 0, когда ВСЕ описанные повторы сходятся."""
    if isinstance(bar_path, dict):
        top = str(bar_path.get("top") or "").strip()
        touch = str(bar_path.get("touch") or "").strip()
        if _top_over_shoulders(top) and _touch_on_lower_chest(touch):
            return top, touch
    described = [
        (str(r.get("bar_at_top") or "").strip(), str(r.get("bar_at_bottom") or "").strip())
        for r in (reps if isinstance(reps, list) else [])
        if isinstance(r, dict) and r.get("bar_at_top") and r.get("bar_at_bottom")
    ]
    if described and all(_top_over_shoulders(t) and _touch_on_lower_chest(b) for t, b in described):
        return described[0]
    return None


def _apply_bar_path(
    exercise: str,
    bar_path: Any,
    checklist: list[dict[str, Any]],
    observations: list[dict[str, Any]],
    *,
    hint: Optional[str] = None,
    reps: Any = None,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Дуга жима лёжа по двум точкам модели — решает код, а не её вердикт.

    Почему не сработало 2.11.2026 (жим лёжа со стороны ног, англоязычный
    атлет): сверка шла точным совпадением с «над плечами» / «низ груди», а
    модель пишет то «над плечевыми суставами», то «нижняя часть груди»; и
    даже сработав, проверка не сняла бы наблюдение «уходит назад за голову» —
    «за голову» не было в словах направления. Плюс строка «video checkpoint»
    в логе печатается ДО чистки, так что по ней не видно, сработала ли
    подмена: исход смотри в строке «video sanitize: жим лёжа …»."""
    if not _is_lying_press(exercise, hint):
        return checklist, observations
    points = _bar_path_points(bar_path, reps)
    if points is None:
        logger.info("video sanitize: жим лёжа, точки дуги норму не подтвердили: %r", bar_path)
        return checklist, observations
    top, touch = points
    for item in checklist:
        if item["point"] == "траектория снаряда" and item["verdict"] != "норма":
            logger.warning(
                "video sanitize: жим лёжа, верх %r, касание %r — траектория «%s» → «норма»",
                top, touch, item["verdict"],
            )
            item["verdict"] = "норма"
            item["what_i_see"] = (
                f"вверху снаряд {top}, касание — {touch}: на опускании уходит к ногам, "
                "на подъёме обратно к голове — обычная дуга жима"
            )
    kept = []
    for obs in observations:
        text = f"{obs.get('what') or ''} {obs.get('evidence') or ''}".lower()
        if any(w in text for w in _BAR_WORDS) and any(w in text for w in _DIRECTION_WORDS):
            logger.warning("video sanitize: жим лёжа, дуга в норме — снято «%s»", obs.get("what"))
        else:
            kept.append(obs)
    return checklist, kept


# Сравнение повторов: «второй повтор не доходит на 5 см», «к третьему таз
# уходит раньше». Живой провал — ровно такое выдумали на ролике из двух
# одинаковых повторов. Принимаем, только если названы кадры ОБОИХ повторов.
_REP_COMPARE_RE = re.compile(
    r"(перв|втор|трет|четв|пят|шест|последн|следующ|предыдущ|друг|остальн)\w*\s+(повтор|раз)"
    r"|от повтора к повтору|в отличие от|по сравнению с"
    r"|\brep\s*\d|\b(first|second|third|last|other|later)\s+reps?\b|from rep to rep",
    re.IGNORECASE,
)


# Амплитуда и сравнение повторов — только через тело. Живой провал 2.11.2026
# (тот же жим): «верхняя точка в кадре 11 ниже, чем в кадрах 1 и 15» — высота
# грифа на экране, а камера в руке плывёт. Отклонение по амплитуде честно
# только в двух видах: нет замка (суставы явно согнуты вверху) или нет
# касания / неполная глубина внизу. Текст без такой опоры снимается.
_AMPLITUDE_POINTS = ("амплитуда", "повторы между собой")
_AMPLITUDE_RE = re.compile(
    r"амплитуд|(верхн|нижн)\w*\s+(точк|положен)|недожим|не\s+дож|не\s+доход|недоход"
    r"|top position|range of motion|short of|lower than|higher than|ниже\s+верхн|выше\s+верхн",
    re.IGNORECASE,
)
_BODY_FAULT_MARKERS = (
    # нет замка вверху
    "локт", "локот", "elbow", "lockout", "замок", "замка", "не выпрям", "не разгиб",
    "согнут", "bent",
    # нет касания / неполная глубина внизу
    "не каса", "без касан", "полповтор", "половин", "half rep", "partial",
    "not touch", "doesn't touch", "does not touch", "above the chest", "над грудью",
    "не доходит до груд", "не доходя до груд", "не опускается до груд",
    "short of the chest", "reach the chest", "reach his chest", "reach her chest",
    "параллел", "parallel", "глубин", "depth",
)


def _has_body_fault(text: str) -> bool:
    low = text.lower()
    return any(m in low for m in _BODY_FAULT_MARKERS)


def _is_rep_comparison(obs: dict[str, Any]) -> bool:
    text = f"{obs.get('what') or ''} {obs.get('evidence') or ''}"
    return obs.get("point") == "повторы между собой" or bool(_REP_COMPARE_RE.search(text))


def _require_body_landmarks(
    checklist: list[dict[str, Any]], observations: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Амплитуда и сравнения повторов без опоры на тело (замок, касание,
    глубина) → «не видно» / вон."""
    for item in checklist:
        if (
            item["point"] in _AMPLITUDE_POINTS
            and item["verdict"] == "отклонение"
            and not _has_body_fault(item.get("what_i_see") or "")
        ):
            logger.warning(
                "video sanitize: «%s» (отклонение) без опоры на тело → «не видно»: %s",
                item["point"], (item.get("what_i_see") or "")[:200],
            )
            item["verdict"] = "не видно"
            item["what_i_see"] = (
                "сравнение по высоте снаряда в кадре, без замка или касания — "
                "камера могла сдвинуться, по кадрам не судим"
            )
    kept = []
    for obs in observations:
        text = f"{obs.get('what') or ''} {obs.get('evidence') or ''}"
        about_range = (
            obs.get("point") in _AMPLITUDE_POINTS
            or _is_rep_comparison(obs)
            or bool(_AMPLITUDE_RE.search(text))
        )
        if about_range and not _has_body_fault(text):
            logger.warning("video sanitize: наблюдение «%s» без опоры на тело — снято", obs.get("what"))
        else:
            kept.append(obs)
    return checklist, kept


def _rep_by_frame(reps: Any) -> dict[int, int]:
    """Кадр → номер повтора по разметке шага 0 (from_frame..to_frame)."""
    out: dict[int, int] = {}
    for i, item in enumerate(reps if isinstance(reps, list) else [], start=1):
        if not isinstance(item, dict):
            continue
        number = item.get("rep") if isinstance(item.get("rep"), int) else i
        lo, hi = item.get("from_frame"), item.get("to_frame")
        if isinstance(lo, int) and isinstance(hi, int) and lo <= hi:
            for f in range(lo, hi + 1):
                out.setdefault(f, number)
        for key in ("top_frame", "bottom_frame"):
            if isinstance(item.get(key), int):
                out.setdefault(item[key], number)
    return out


def _check_frame_evidence(
    checklist: list[dict[str, Any]],
    observations: list[dict[str, Any]],
    reps: Any,
    frame_count: int,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """«Не показал — не видел». Отклонение без настоящих номеров кадров (1..N)
    снимается: в checklist — до «не видно», из observations — вон. Сравнение
    повторов без кадров двух разных повторов — туда же."""
    rep_of = _rep_by_frame(reps)

    def valid(frames: Any) -> list[int]:
        return [f for f in _frame_list(frames) if 1 <= f <= frame_count]

    def two_reps(frames: list[int]) -> bool:
        return len({rep_of[f] for f in frames if f in rep_of}) >= 2

    for item in checklist:
        if item["verdict"] != "отклонение":
            continue
        frames = valid(item.get("frames"))
        item["frames"] = frames
        reason = None
        if not frames:
            reason = "не назвала кадров, где это видно"
        elif item["point"] == "повторы между собой" and not two_reps(frames):
            reason = "сравнивает повторы, не назвав кадров обоих"
        if reason:
            logger.warning("video sanitize: «%s» (отклонение) %s → «не видно»", item["point"], reason)
            item["verdict"] = "не видно"
            item["what_i_see"] = f"модель {reason} — по кадрам не судим"
    kept = []
    for obs in observations:
        frames = valid(obs.get("frames"))
        text = f"{obs.get('what') or ''} {obs.get('evidence') or ''}"
        compare = obs.get("point") == "повторы между собой" or bool(_REP_COMPARE_RE.search(text))
        if not frames:
            logger.warning("video sanitize: наблюдение «%s» без кадров — снято", obs.get("what"))
        elif compare and not two_reps(frames):
            logger.warning(
                "video sanitize: наблюдение «%s» сравнивает повторы без кадров обоих — снято",
                obs.get("what"),
            )
        else:
            kept.append({**obs, "frames": frames})
    return checklist, kept


def _sanitize(
    data: dict[str, Any],
    *,
    frame_count: Optional[int] = None,
    exercise_hint: Optional[str] = None,
) -> dict[str, Any]:
    """Убрать из ответа модели то, что она обещала не писать.

    Чинит ровно те отклонения, которые видели живьём, и ничего не достраивает:
    пустой разбор так и остаётся пустым — это честный исход.

    frame_count — сколько кадров видела модель (путь "openai"): тогда каждое
    отклонение обязано ссылаться на настоящие кадры. У пути "novita" номеров
    кадров нет, и эта проверка не делается.
    """
    view = data.get("view") or {}
    usable = bool(view.get("usable", True))
    problem = (view.get("problem") or "").strip()

    # Наблюдение без доказательства — то самое «дописал, а не увидел», ради
    # чего поле evidence и заведено. Нет его — нет наблюдения.
    raw_observations = data.get("observations") or []
    observations = [
        obs for obs in raw_observations
        if isinstance(obs, dict) and (obs.get("evidence") or "").strip()
    ]
    # Логируем, что модель нашла и что из этого выжило. Без этой строки нельзя
    # отличить «Qwen не увидел ошибок» от «Qwen увидел, а фильтр выбросил», а
    # разница принципиальная: первое — честный разбор, второе — наш баг, из-за
    # которого тренер молчит о реальных косяках.
    dropped = [
        (obs.get("what") if isinstance(obs, dict) else repr(obs)[:60])
        for obs in raw_observations
        if not (isinstance(obs, dict) and (obs.get("evidence") or "").strip())
    ]
    logger.info(
        "video sanitize: наблюдений от модели %s, осталось %s%s",
        len(raw_observations), len(observations),
        f", выброшено без evidence: {dropped}" if dropped else "",
    )
    observations.sort(key=lambda o: _SEVERITY_ORDER.get(o.get("severity"), 3))

    raw_not_visible = data.get("not_visible") or []
    not_visible = [
        item for item in raw_not_visible
        if isinstance(item, dict) and not _is_unobservable(str(item.get("what", "")))
    ]
    if len(not_visible) != len(raw_not_visible):
        logger.info(
            "video sanitize: «не видно» %s → %s (убрано ненаблюдаемое в принципе)",
            len(raw_not_visible), len(not_visible),
        )
    # Непротиворечивость, которую промпт просит, а модель соблюдает не всегда:
    # «ракурс хороший, помех нет» и длинный список «судить нельзя» вместе не
    # живут. Верим первому — оно проверяемо, а список был отпиской.
    if usable and not problem:
        not_visible = not_visible[:2]

    checklist = _clean_checklist(data.get("checklist"))
    if frame_count:
        checklist, observations = _check_frame_evidence(
            checklist, observations, data.get("reps"), frame_count
        )
    checklist, observations = _require_body_landmarks(checklist, observations)
    checklist, observations = _drop_contradictions(checklist, observations)
    checklist, observations = _apply_bar_path(
        str(data.get("exercise") or ""), data.get("bar_path"), checklist, observations,
        hint=exercise_hint, reps=data.get("reps"),
    )
    # Точка помечена отклонением, а в observations его нет — модель потеряла своё
    # же наблюдение по дороге со шага 1 на шаг 2. Ничего не достраиваем: весь
    # checklist едет тренеру целиком (см. to_context_block), так что отклонение
    # до него доедет и так. Но в лог это надо, иначе молчание тренера про
    # реальный косяк снова будет неотличимо от честного «не нашли».
    flagged = [item["point"] for item in checklist if item["verdict"] == "отклонение"]
    # Раньше здесь наблюдение сопоставлялось с точкой по вхождению её названия в
    # текст — и на живом прогоне это дало ложную тревогу: модель нашла «таз
    # поднимается раньше плеч», слов «порядок движения» там, разумеется, нет.
    # Формулировки наблюдений свободные, названия точек наши, и совпадать они не
    # обязаны. Лог, срабатывающий на каждом втором ролике, хуже отсутствия лога:
    # он приучает не смотреть. Поэтому кричим только про случай, где тренер
    # действительно останется без слов, — отклонения есть, наблюдений ноль.
    if flagged and not observations:
        logger.warning(
            "video sanitize: отклонения по точкам %s есть, а observations пуст — "
            "тренер узнает о них только из checklist",
            flagged,
        )
    elif flagged:
        logger.info(
            "video sanitize: отклонений по точкам %s, наблюдений %s",
            len(flagged), len(observations),
        )

    return {
        "exercise": (data.get("exercise") or "не определил"),
        "exercise_confidence": (data.get("exercise_confidence") or "").strip().lower(),
        "reps_seen": data.get("reps_seen"),
        "view": {
            "angle": view.get("angle"), "usable": usable, "problem": problem,
            **{k: view[k] for k in ("head_side", "feet_side") if view.get(k)},
        },
        "checklist": checklist,
        "observations": observations,
        "not_visible": not_visible,
        "camera_advice": (data.get("camera_advice") or "").strip(),
    }


# Сводка замеров позы, которую присылает iOS-приложение (Apple Vision на
# телефоне атлета: ключевые точки тела по кадрам → повторы, углы, темп). Текст
# машинный, по-английски, собирает клиент (`PoseSummary` в
# training_log_bot_ios). Потолок — чтобы чужой клиент не раздул промпт.
POSE_SUMMARY_MAX_CHARS = 1500


def pose_summary_block(pose_summary: str) -> str:
    """Замеры с телефона — как показания прибора, а не истина: точки плывут
    при плохом ракурсе и перекрытии снарядом. Один и тот же блок уходит и
    глазам (Qwen), и голосу (тренеру), чтобы оба знали, откуда цифры."""
    return (
        "Замеры позы, сделанные на телефоне атлета (Apple Vision по ключевым "
        "точкам тела; углы в градусах; при плохом ракурсе или перекрытии "
        "снарядом могут врать). Опирайся на них в амплитуде, темпе и том, как "
        "меняются повторы, но если кадр им противоречит — верь кадру:\n"
        + pose_summary[:POSE_SUMMARY_MAX_CHARS]
    )


async def _count_attempt(user_id: Optional[int], *, ok: bool) -> None:
    """Учёт попытки после ОТВЕТА провайдера (деньги уже ушли).

    Валидный разбор тратит основную квоту видео. Провал (мусор вместо JSON,
    оборванное рассуждение) основную квоту не наказывает, а считается отдельным
    мягким счётчиком (`ai_limits.KIND_VIDEO_FAIL`, config.AI_VIDEO_FAIL_DAILY_LIMIT):
    без него ролики можно было бы гонять за наш счёт бесконечно. Сбой ДО ответа
    провайдера (сеть, 4xx) сюда не доезжает и ничего не тратит.
    """
    if user_id is None:
        return
    try:
        if ok:
            await db.increment_ai_video_count(user_id)
        else:
            await db.increment_ai_usage(user_id, ai_limits.KIND_VIDEO_FAIL)
    except Exception:
        logger.exception("failed to count video analysis attempt")


# Модели, на которые провайдер ответил 404, — до перезапуска процесса.
_gone_models: set[str] = set()


def _video_models() -> list[str]:
    """Основная модель разбора видео и запасные, без снятых провайдером. Все
    сняты — пробуем основную снова: вдруг вернули, а молчать до перезапуска
    хуже лишнего 404."""
    ordered = list(dict.fromkeys([config.NOVITA_VIDEO_MODEL, *config.NOVITA_VIDEO_FALLBACK_MODELS]))
    alive = [m for m in ordered if m not in _gone_models]
    return alive or ordered[:1]


def _user_prompt(base: str, exercise_hint: Optional[str], pose_summary: Optional[str]) -> str:
    # Подпись к ролику — единственный надёжный источник упражнения, и он важнее
    # глаз модели. Живой провал: тягу штанги к поясу она приняла за становую и
    # выдала три классические ошибки становой (круглая поясница, таз раньше
    # плеч, гриф от голени) — не потому, что видела их, а потому, что для
    # становой это самый частый набор. Названное упражнение эту подгонку
    # обрывает. Дописывается к пользовательской части, а не к системной:
    # системный промпт обязан оставаться неизменным, иначе кэш промахивается
    # на каждом ролике.
    user_prompt = base
    if exercise_hint:
        user_prompt = (
            f"Атлет подписал ролик так: «{exercise_hint}». Если там названо "
            f"упражнение — это оно и есть, верь подписи, а не своим глазам, и "
            f"поставь exercise_confidence «высокая».\n\n" + base
        )
    # Цифры с телефона — тоже в пользовательскую часть, по той же причине.
    if pose_summary:
        user_prompt = pose_summary_block(pose_summary) + "\n\n" + user_prompt
    return user_prompt


async def analyze(
    video_bytes: bytes,
    user_id: Optional[int],
    mime_type: str = "video/mp4",
    exercise_hint: Optional[str] = None,
    pose_summary: Optional[str] = None,
    *,
    backend: Optional[str] = None,
) -> Optional[dict[str, Any]]:
    """Видео → структура наблюдений, или None если разобрать не удалось.

    None означает ровно «наблюдений нет»: тренер в этом случае отвечает без
    видео, а не извиняется за чужую поломку.

    backend — "openai" | "novita"; по умолчанию config.video_analysis_backend()
    (явный выбор нужен скрипту сравнения, scripts/video_eval.py).

    Квоту видео списывает сам (_count_attempt) — за каждый состоявшийся
    платный вызов; проверку ai_limits KIND_VIDEO до вызова делают хендлеры.
    """
    if backend == "openai":
        return await _analyze_frames(video_bytes, user_id, exercise_hint, pose_summary)
    if backend == "novita":
        return await _analyze_novita(video_bytes, user_id, mime_type, exercise_hint, pose_summary)
    chosen = config.video_analysis_backend()
    if chosen == "openai":
        return await _analyze_frames(video_bytes, user_id, exercise_hint, pose_summary)
    # Основной — Qwen (владелец, 2026-11-02: «вернём разбор от квен, а фолбек
    # оставим на схему с кадрами и основной моделью»). Qwen не ответил, ответил
    # не JSON или нечего разбирать — тот же ролик идёт кадрами в модель тренера.
    # Неудача Qwen при этом в счётчик неудач не пишется: попытку решает запасной.
    fallback = config.video_frames_fallback_available()
    result = await _analyze_novita(
        video_bytes, user_id, mime_type, exercise_hint, pose_summary, count_failure=not fallback
    )
    if result is None and fallback:
        logger.warning("video analysis: novita gave nothing for user %s, falling back to frames", user_id)
        return await _analyze_frames(video_bytes, user_id, exercise_hint, pose_summary)
    return result


# Оценка входа на кадр для оборванного вызова (usage тогда не приходит): две
# плитки 512 на detail=high — 85 + 2×170. Настоящую цену пишет usage ответа.
_ABORT_TOKENS_PER_FRAME = 425


def _response_schema() -> dict[str, Any]:
    """Строгая JSON-схема ответа (как у машинных вызовов тренера). Порядок
    свойств — порядок генерации: ракурс и повторы раньше вердиктов."""
    s, i = {"type": "string"}, {"type": "integer"}

    def obj(props: dict[str, Any]) -> dict[str, Any]:
        return {
            "type": "object", "properties": props,
            "required": list(props), "additionalProperties": False,
        }

    def enum(*values: str) -> dict[str, Any]:
        return {"type": "string", "enum": list(values)}

    sides = enum("слева", "справа", "сверху", "снизу", "не видно")
    frames = {"type": "array", "items": i}
    level = enum("высокая", "средняя", "низкая")
    schema = obj({
        "view": obj({
            "angle": enum("сбоку", "спереди", "сзади", "три четверти", "не определить"),
            "head_side": sides,
            "feet_side": sides,
            "usable": {"type": "boolean"},
            "problem": s,
        }),
        "exercise": s,
        "exercise_confidence": level,
        "reps": {"type": "array", "items": obj({
            "rep": i, "from_frame": i, "to_frame": i,
            "top_frame": i, "bar_at_top": s,
            "bottom_frame": i, "bar_at_bottom": s,
            "note": s,
        })},
        "reps_seen": i,
        "bar_path": obj({
            "top": enum("над плечами", "над лицом или шеей", "над грудью", "не видно"),
            "touch": enum("низ груди", "середина груди", "верх груди или шея", "не видно"),
        }),
        "checklist": {"type": "array", "items": obj({
            "point": enum(*CHECKPOINTS),
            "verdict": enum(*_VERDICTS),
            "what_i_see": s,
            "frames": frames,
            "when": s,
        })},
        "observations": {"type": "array", "items": obj({
            "point": enum(*CHECKPOINTS),
            "what": s,
            "phase": s,
            "frames": frames,
            "when": s,
            "reps": {"type": "array", "items": i},
            "evidence": s,
            "severity": enum(*_SEVERITY_ORDER),
            "confidence": level,
        })},
        "not_visible": {"type": "array", "items": obj({"what": s, "why": s})},
        "camera_advice": s,
    })
    return {
        "type": "json_schema",
        "json_schema": {"name": "video_review", "strict": True, "schema": schema},
    }


def _frames_content(frames: list[Frame], duration: Optional[float], user_prompt: str) -> list[dict[str, Any]]:
    total = len(frames)
    head = (
        f"Кадров: {total}"
        + (f", ролик {duration:.1f} с" if duration else "")
        + ", по порядку времени.\n\n" + user_prompt
    )
    content: list[dict[str, Any]] = [{"type": "text", "text": head}]
    for frame in frames:
        content.append({"type": "text", "text": f"кадр {frame.index} из {total}, {frame.seconds:.1f} с"})
        content.append({
            "type": "image_url",
            "image_url": {
                "url": "data:image/jpeg;base64," + base64.b64encode(frame.jpeg).decode(),
                "detail": config.VIDEO_FRAME_DETAIL,
            },
        })
    return content


def _vote_phases(votes: int) -> list[float]:
    """Сдвиг первого кадра (в долях шага) у каждого голоса: 1 → [0.5],
    2 → [0.25, 0.75], 3 → [1/6, 1/2, 5/6] — наборы кадров не пересекаются."""
    return [(2 * k + 1) / (2 * votes) for k in range(votes)]


async def _analyze_frames(
    video_bytes: bytes,
    user_id: Optional[int],
    exercise_hint: Optional[str],
    pose_summary: Optional[str],
) -> Optional[dict[str, Any]]:
    """Путь "openai": свои кадры → модель зрения тренера → та же структура.

    Голосов VIDEO_ANALYSIS_VOTES (по умолчанию 2), параллельно — по времени
    это один вызов. У каждого голоса СВОЙ набор кадров, сдвинутый на полшага
    (_vote_phases), а не те же кадры дважды. Почему так: выдуманные отклонения
    рождаются из конкретных кадров — гриф пойман на полпути к замку, камера
    дёрнулась между повторами. Те же кадры дважды дают ту же иллюзию дважды
    (при низкой случайности ответы у одной модели коррелируют), а сдвинутые
    кадры ловят верх и низ в другие моменты: настоящая ошибка видна в обоих
    наборах, артефакт кадра — только в одном. Отклонение остаётся, только если
    его подтвердили все голоса (_consensus). Платит каждый вызов (cost-событие
    у каждого), квота видео списывается один раз.
    """
    import ai_trainer  # тяжёлый модуль; здесь, а не наверху — разбор видео ему не нужен до вызова

    votes = max(1, config.VIDEO_ANALYSIS_VOTES)
    # ffmpeg — subprocess на сотни миллисекунд: в поток, не в цикл событий.
    extracted = await asyncio.gather(
        *(asyncio.to_thread(extract_frames, video_bytes, phase) for phase in _vote_phases(votes))
    )
    sets = [e for e in extracted if e]
    if not sets:
        # Денег не ушло — и квоту не трогаем, как при сбое сети до ответа.
        logger.warning("video analysis: no frames extracted for user %s", user_id)
        return None
    backend = ai_trainer.vision_backend()._replace(effort=config.VIDEO_ANALYSIS_REASONING_EFFORT)
    user_prompt = _user_prompt(USER_PROMPT, exercise_hint, pose_summary)
    kwargs = ai_trainer._model_kwargs(
        backend, user_id, max_tokens=config.VIDEO_ANALYSIS_MAX_TOKENS, quick=False, scope="video"
    )

    async def one_vote(frames: list[Frame], duration: Optional[float]) -> tuple[bool, Optional[dict], Optional[dict]]:
        """(вызов состоялся — деньги ушли, сырой ответ, вычищенный ответ)."""
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": _frames_content(frames, duration, user_prompt)},
        ]
        try:
            # paid_call: cost-событие по настоящему usage в finally, оборванный
            # таймаутом — по оценке. Квоты тут нет (kind=None): KIND_VIDEO
            # проверил хендлер, а списывает _count_attempt ниже, по исходу.
            response = await ai_trainer.paid_call(
                user_id, None,
                lambda: backend.client.chat.completions.create(
                    **kwargs,
                    messages=messages,
                    response_format=_response_schema(),
                    timeout=config.VIDEO_ANALYSIS_TIMEOUT_SECONDS,
                ),
                model=backend.model,
                abort_prompt_tokens=len(frames) * _ABORT_TOKENS_PER_FRAME + len(SYSTEM_PROMPT) // 3,
            )
        except Exception:
            logger.exception("video analysis call failed for user %s", user_id)
            return False, None, None
        usage = getattr(response, "usage", None)
        logger.info(
            "video analysis usage: prompt=%s (cached=%s) completion=%s (reasoning=%s) model=%s frames=%s",
            getattr(usage, "prompt_tokens", 0),
            getattr(getattr(usage, "prompt_tokens_details", None), "cached_tokens", 0),
            getattr(usage, "completion_tokens", 0),
            getattr(getattr(usage, "completion_tokens_details", None), "reasoning_tokens", 0),
            backend.model, len(frames),
        )
        parsed = _parse(response, user_id)
        if parsed is None:
            return True, None, None
        return True, parsed, _sanitize(parsed, frame_count=len(frames), exercise_hint=exercise_hint)

    logger.info(
        "video analysis: %s vote(s), %s frames over %ss → %s (effort %s, detail %s)",
        len(sets), [len(f) for f, _ in sets], sets[0][1], backend.model, backend.effort,
        config.VIDEO_FRAME_DETAIL,
    )
    runs = await asyncio.gather(*(one_vote(frames, duration) for frames, duration in sets))
    if not any(called for called, _, _ in runs):
        return None  # ни один вызов не состоялся — денег не ушло
    logger.info("video votes | %s", _votes_summary([raw for _, raw, _ in runs]))
    results = [res for _, _, res in runs if res is not None]
    if not results:
        await _count_attempt(user_id, ok=False)
        return None
    if len(results) == 1 and len(sets) > 1:
        # Второй голос пропал (сбой, мусор вместо JSON). Отдаём уцелевший,
        # чтобы сбой провайдера не делал тренера немым на реальной ошибке, —
        # но без сравнений повторов: это самый выдумываемый класс (живой
        # провал — «первый повтор ниже второго»), и без подтверждения ему веры нет.
        result = _drop_rep_comparisons(results[0])
    elif len(results) == 1:
        result = results[0]
    else:
        result = _consensus(results)
    result["votes"] = len(results)
    await _count_attempt(user_id, ok=True)
    return result


_VERDICT_LETTER = {"норма": "н", "отклонение": "О", "не видно": "?"}


def _votes_summary(raws: list[Optional[dict[str, Any]]]) -> str:
    """Одна строка на все голоса — сырые вердикты до чистки, чтобы владелец мог
    вставить её целиком: «#1 reps=2 спина=н траектория снаряда=О[3,9] … || #2 …»."""
    parts = []
    for n, raw in enumerate(raws, start=1):
        if not isinstance(raw, dict):
            parts.append(f"#{n} нет ответа")
            continue
        points = []
        for item in raw.get("checklist") or []:
            if not isinstance(item, dict):
                continue
            verdict = _VERDICT_LETTER.get(str(item.get("verdict") or ""), "?")
            frames = item.get("frames")
            mark = f"{verdict}{frames}" if verdict == "О" and frames else verdict
            points.append(f"{item.get('point')}={mark}")
        obs = [
            f"{o.get('point')}: {str(o.get('what') or '')[:80]}"
            for o in raw.get("observations") or [] if isinstance(o, dict)
        ]
        parts.append(
            f"#{n} reps={raw.get('reps_seen')} {' '.join(points)}"
            + (f" obs=[{'; '.join(obs)}]" if obs else "")
        )
    return " || ".join(parts)


def _drop_rep_comparisons(result: dict[str, Any]) -> dict[str, Any]:
    checklist = []
    for item in result["checklist"]:
        if item["point"] == "повторы между собой" and item["verdict"] == "отклонение":
            item = {**item, "verdict": "не видно",
                    "what_i_see": "второй прогон не состоялся — сравнение повторов не подтверждено"}
        checklist.append(item)
    observations = [o for o in result["observations"] if not _is_rep_comparison(o)]
    return {**result, "checklist": checklist, "observations": observations}


def _consensus(results: list[dict[str, Any]]) -> dict[str, Any]:
    """Отклонение остаётся, только если его отметили ВСЕ голоса.

    Точка: «отклонение» у всех → остаётся (описание первого голоса); иначе
    берётся «норма» того голоса, что её поставил (с его описанием), а если
    нормы нет ни у кого — «не видно». Наблюдение первого голоса остаётся,
    только если точка подтверждена и наблюдение по ней есть у каждого голоса.
    Остальное (упражнение, ракурс, повторы) — от первого голоса."""
    base = results[0]
    by_run = [{item["point"]: item for item in r["checklist"]} for r in results]
    checklist, confirmed = [], set()
    for item in base["checklist"]:
        point = item["point"]
        verdicts = [run.get(point, {}).get("verdict") for run in by_run]
        if all(v == "отклонение" for v in verdicts):
            checklist.append(item)
            if all(any(o.get("point") == point for o in r["observations"]) for r in results):
                confirmed.add(point)
            continue
        if "отклонение" in verdicts:
            logger.warning("video consensus: «%s» голоса разошлись %s → не отклонение", point, verdicts)
        normal = next((run[point] for run in by_run if run.get(point, {}).get("verdict") == "норма"), None)
        if normal is not None:
            checklist.append(dict(normal))
        elif item["verdict"] == "отклонение":
            checklist.append({**item, "verdict": "не видно",
                              "what_i_see": "голоса разошлись — по кадрам не судим"})
        else:
            checklist.append(item)
    observations = [o for o in base["observations"] if o.get("point") in confirmed]
    dropped = len(base["observations"]) - len(observations)
    if dropped:
        logger.warning("video consensus: снято неподтверждённых наблюдений: %s", dropped)
    reps = [r.get("reps_seen") for r in results]
    if len(set(map(str, reps))) > 1:
        logger.warning("video consensus: голоса разошлись в числе повторов %s", reps)
    return {**base, "checklist": checklist, "observations": observations}


async def _analyze_novita(
    video_bytes: bytes,
    user_id: Optional[int],
    mime_type: str,
    exercise_hint: Optional[str],
    pose_summary: Optional[str],
    *,
    count_failure: bool = True,
) -> Optional[dict[str, Any]]:
    """Путь "novita": ролик целиком в Qwen.

    count_failure=False — за этим вызовом стоит запасной разбор кадрами, и
    неудачу Qwen в счётчик неудач видео не пишем: исход решит запасной.

    mime_type берётся из самого апдейта, а не подставляется наугад: ролик без
    аудиодорожки Telegram отдаёт как animation, и там встречается и video/mp4, и
    image/gif. Соврать про тип в data: URL — значит отправить модели файл под
    чужой вывеской.
    """
    data_url = f"data:{mime_type};base64," + base64.b64encode(video_bytes).decode()
    user_prompt = _user_prompt(NOVITA_USER_PROMPT, exercise_hint, pose_summary)
    # response_format добавляется только по флагу: не всякая модель умеет строгий
    # JSON, и провайдер отвечает на неподдерживаемый параметр не мягким
    # игнорированием, а 400 — то есть разбор падает целиком (см.
    # config.VIDEO_ANALYSIS_JSON_MODE). Ответ мы всё равно разбираем руками.
    extra: dict[str, Any] = {}
    if config.VIDEO_ANALYSIS_JSON_MODE:
        extra["response_format"] = {"type": "json_object"}
    messages = [
        {"role": "system", "content": NOVITA_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": [
                {"type": "text", "text": user_prompt},
                {"type": "video_url", "video_url": {"url": data_url}},
            ],
        },
    ]
    response = None
    model = config.NOVITA_VIDEO_MODEL
    for model in _video_models():
        try:
            response = await _get_client().chat.completions.create(
                model=model,
                messages=messages,
                max_tokens=config.VIDEO_ANALYSIS_MAX_TOKENS,
                temperature=config.VIDEO_ANALYSIS_TEMPERATURE,
                **extra,
            )
            break
        except NotFoundError:
            # Провайдер снял модель (404 MODEL_NOT_FOUND) — так 9.10.2026 лёг
            # весь разбор видео. Запоминаем до перезапуска и идём к следующей:
            # повторять заведомый 404 на каждом ролике незачем.
            logger.error("video model %s is gone (404), trying the next one", model)
            _gone_models.add(model)
        except Exception as exc:
            if count_failure:
                logger.exception("video analysis call failed for user %s", user_id)
            else:
                # За Qwen стоит разбор кадрами: его сбой — ещё не сбой для
                # атлета, и тревогой (ERROR → ops_alerts) он не идёт. Ошибкой
                # кричит только запасной путь, если не справится и он. Так
                # 10.11 ревьюер Apple получил разбор, а в чат пришла 🚨.
                logger.warning("video analysis: novita call failed for user %s: %s", user_id, exc)
            return None
    if response is None:
        logger.error("video analysis: no video model left (all returned 404)")
        return None

    # Цену считает дневной отчёт по имени модели (config.LLM_PRICES_USD_PER_1K),
    # поэтому логируем настоящий usage тем же событием, что и вызовы тренера.
    # Своей оценке модели тут веры нет: на вопрос «сколько токенов ушло» она
    # выдумывает число, у неё нет доступа к счётчику.
    usage = getattr(response, "usage", None)
    prompt_tokens = getattr(usage, "prompt_tokens", 0) or 0
    completion_tokens = getattr(usage, "completion_tokens", 0) or 0
    details = getattr(usage, "prompt_tokens_details", None)
    reasoning_tokens = getattr(
        getattr(usage, "completion_tokens_details", None), "reasoning_tokens", 0
    ) or 0
    # Рассуждение отдельной цифрой: на thinking оно тарифицируется как выход и
    # обычно длиннее самого JSON, так что это главная статья расхода — и первое,
    # на что смотреть, если счёт окажется больше ожидаемого.
    logger.info(
        "video analysis usage: prompt=%s completion=%s (reasoning=%s) model=%s",
        prompt_tokens, completion_tokens, reasoning_tokens, model,
    )
    try:
        await db.log_cost_event(
            user_id,
            "llm_call",
            model=model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            cached_tokens=getattr(details, "cached_tokens", 0) or 0,
            reasoning_tokens=reasoning_tokens,
        )
    except Exception:
        logger.exception("failed to log video analysis cost event")
    return await _finish(
        response, user_id, frame_count=None, exercise_hint=exercise_hint, count_failure=count_failure
    )


async def _finish(
    response: Any,
    user_id: Optional[int],
    *,
    frame_count: Optional[int],
    exercise_hint: Optional[str],
    count_failure: bool = True,
) -> Optional[dict[str, Any]]:
    """Ответ модели (деньги уже ушли) → разобранная структура + учёт попытки."""
    parsed = _parse(response, user_id)
    if parsed is None:
        if count_failure:
            await _count_attempt(user_id, ok=False)
        return None
    result = _sanitize(parsed, frame_count=frame_count, exercise_hint=exercise_hint)
    if result is not None or count_failure:
        await _count_attempt(user_id, ok=result is not None)
    return result


def _parse(response: Any, user_id: Optional[int]) -> Optional[dict[str, Any]]:
    """Текст ответа → JSON-объект (или None), с сырыми строками в лог."""
    usage = getattr(response, "usage", None)
    completion_tokens = getattr(usage, "completion_tokens", 0) or 0
    try:
        raw = (response.choices[0].message.content or "").strip()
    except (AttributeError, IndexError, TypeError):
        raw = ""
    payload = _strip_reasoning(raw)
    try:
        parsed = json.loads(payload)
    except (ValueError, TypeError):
        # Оборванное рассуждение и мусор вместо JSON — разные поломки: первая
        # лечится потолком токенов (VIDEO_ANALYSIS_MAX_TOKENS), вторая промптом.
        truncated = bool(_UNCLOSED_THINK_RE.search(raw)) and "</think>" not in raw.lower()
        logger.warning(
            "video analysis returned non-JSON for user %s (%s, completion_tokens=%s): %r",
            user_id,
            "оборвано на рассуждении" if truncated else "не JSON",
            completion_tokens,
            raw[:300],
        )
        return None
    if not isinstance(parsed, dict):
        return None
    # Что модель на самом деле написала — до всякой чистки (исход чистки — в
    # строках «video sanitize: …»). Без этих строк нельзя отличить «не увидела
    # круглую спину» от «увидела и проштамповала норму учебной фразой»: наружу
    # оба случая выглядят одинаково (тренер молчит), а чинятся противоположным
    # — первое кадрами, второе промптом.
    view = parsed.get("view") if isinstance(parsed.get("view"), dict) else {}
    logger.info(
        "video raw | exercise=%r view=%s/%s head=%s feet=%s reps_seen=%s reps=%s bar_path=%s",
        parsed.get("exercise"), view.get("angle"), view.get("usable"),
        view.get("head_side"), view.get("feet_side"), parsed.get("reps_seen"),
        json.dumps(parsed.get("reps"), ensure_ascii=False)[:600] if parsed.get("reps") else None,
        parsed.get("bar_path"),
    )
    for item in parsed.get("checklist") or []:
        if isinstance(item, dict):
            logger.info(
                "video checkpoint (raw) | %s | %s | %s | frames %s",
                item.get("point"), item.get("verdict"),
                str(item.get("what_i_see") or "")[:200], item.get("frames"),
            )
    return parsed


def _shown_exercise(raw: Any) -> str:
    """Имя упражнения из протокола → на языке ответа.

    Модель зрения отвечает по русскому протоколу и пишет имя по-русски
    («становая тяга»). Тренер цитирует его жирным как есть, и французский
    атлет получал «Sur **Становая тяга**…» (живой кадр витрины). Имя из
    каталога переводим; незнакомое русское имя не на русском языке ответа
    помечаем, что его надо перевести, а не цитировать.
    """
    import seed_data

    name = str(raw or "").strip()
    lang = i18n.get_lang()
    if not name or lang == i18n.DEFAULT_LANG:
        return name
    needle = name.casefold()
    for _group, canonical in seed_data.EXERCISE_TEMPLATES:
        if canonical.casefold() == needle:
            return seed_data.localized_exercise_name(canonical, lang)
    if re.search("[а-яё]", needle):
        return f"{name} (название по-русски — назови упражнение на языке ответа, не цитируй)"
    return name


