# При равном месте в своей группе — какая группа ходовее: по «жим» жим лёжа
# (первый в «Груди») выше жима гантелей сидя (первого в «Плечах»).
_POPULAR_GROUP_ORDER = ("Грудь", "Спина", "Ноги", "Плечи", "Бицепс", "Трицепс", "Пресс", "Другое")


def _build_catalog_popularity() -> dict[str, int]:
    """Место в группе → общий ранг: сначала первые каждой группы (в порядке
    `_POPULAR_GROUP_ORDER`), потом вторые и так далее. Так и «Все» в
    приложении, и поиск по нескольким группам чередуют главное, а не идут
    группа за группой."""
    place: dict[str, int] = {}
    for names in CATALOG_POPULAR_FIRST.values():
        for index, name in enumerate(names):
            place[name] = index
    tail = {group: len(names) for group, names in CATALOG_POPULAR_FIRST.items()}
    group_of: dict[str, str] = {}
    for group, name in EXERCISE_TEMPLATES:
        group_of.setdefault(name, group)
        if name not in place:
            place[name] = tail.get(group, 0)
            tail[group] = place[name] + 1
    width = len(_POPULAR_GROUP_ORDER) + 1
    return {
        name: index * width + (
            _POPULAR_GROUP_ORDER.index(group_of[name])
            if group_of.get(name) in _POPULAR_GROUP_ORDER else width - 1
        )
        for name, index in place.items()
    }


_CATALOG_POPULARITY = _build_catalog_popularity()


def catalog_popularity(name: str) -> int:
    """Ранг шаблона по популярности (0 — самый ходовой во всём каталоге) по
    русскому имени-идентичности: внутри группы — порядок её топа, между
    группами — см. `_build_catalog_popularity`. Не из каталога — в конец."""
    return _CATALOG_POPULARITY.get(name, 10**6)


def canonical_muscle_group_name(shown_name: str) -> Optional[str]:
    """Обратный ход к localized_muscle_group_name: «Chest» → «Грудь».

    Идентичность группы в базе — русская строка навсегда (группы глобальные и
    не форкаются), а человек и модель видят её на языке аккаунта. Без обратного
    хода имя, которое бот сам же показал, обратно не принимается: тренер зовёт
    create_exercise с group="Chest", получает «такой группы нет» и списком
    русских имён — после чего называет по-русски и упражнение тоже. Так и
    появлялись «Приседания с собственным весом» в английском списке.
    """
    needle = (shown_name or "").strip().casefold()
    if not needle:
        return None
    for canonical in _MUSCLE_GROUP_SLUGS:
        for lang in i18n.SUPPORTED:
            if localized_muscle_group_name(canonical, lang).casefold() == needle:
                return canonical
    return None


def canonical_exercise_name(shown_name: str) -> Optional[str]:
    """Обратный ход к localized_exercise_name: «Push-Ups» → «Отжимания от пола».

    То же, что и у групп, только шаблонов сто двадцать: имя шаблона в базе русское
    навсегда (см. модульную докстрингу), и англоязычному атлету бот показывает
    перевод. Пока обратного хода не было, английское имя из каталога не
    резолвилось никуда — ни в состав программы, ни в подсчёт объёма по группам,
    и недельный объём у англоязычного считался по одним лишь своим упражнениям.
    """
    needle = (shown_name or "").strip().casefold()
    if not needle:
        return None
    for _group, canonical in EXERCISE_TEMPLATES:
        for lang in i18n.SUPPORTED:
            if lang == i18n.DEFAULT_LANG:
                continue
            if localized_exercise_name(canonical, lang).casefold() == needle:
                return canonical
    return None


def localized_exercise_name(canonical_name: str, lang: str) -> str:
    """Display name for an exercise template in `lang`.

    `canonical_name` is always the Russian name from EXERCISE_TEMPLATES — the
    identity `db.fork_exercise_from_template` writes into
    `exercises.original_name` forever, regardless of the forking user's
    language (see the module docstring). For `ru` that string already IS the
    display text; other languages resolve it through the locale catalog,
    keyed by the same free-exercise-db slug already used for demo photos
    (`exercise_media.EXERCISE_IMAGE_SLUGS`) so the two catalogs can't drift
    apart into separate spellings of the same lift.

    Falls back to `canonical_name` for a name with no slug (shouldn't happen
    for anything in EXERCISE_TEMPLATES — tests/test_catalog_language.py
    checks the full catalog — but a user's own hand-typed exercise can reach here
    too via `original_name`, and it has no English translation to offer).
    """
    if lang == i18n.DEFAULT_LANG:
        return canonical_name
    slug = exercise_media.EXERCISE_IMAGE_SLUGS.get(canonical_name)
    if slug is None:
        return canonical_name
    return i18n.t_in(lang, f"exercise.{slug}.name")


