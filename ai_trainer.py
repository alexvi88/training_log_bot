async def _training_overview(user_id: int) -> dict[str, Any]:
    user = await db.get_user(user_id)
    if user is None:
        return {"error": "user not found"}
    dates = [dt.date.fromisoformat(d) for d in await db.list_finished_workout_dates(user_id)]
    dash = analytics.compute_dashboard(dates, timeutil.user_today(user))
    exercises = await db.list_user_exercises(user_id)
    groups = await db.list_muscle_groups(user_id)
    group_name_by_id = {g["id"]: g["name"] for g in groups}
    bodyweight = await db.get_latest_bodyweight(user_id)
    equipment = None
    if user["equipment"]:
        try:
            equipment = json.loads(user["equipment"])
        except (TypeError, ValueError):
            equipment = None
    return {
        "unit": user["unit"],
        "e1rm_formula": user["e1rm_formula"],
        "latest_bodyweight": (
            {"weight": bodyweight["weight"], "date": bodyweight["logged_at"][:10]} if bodyweight else None
        ),
        # 3.3: то, что тренер и так каждый раз выпытывает (дни в неделю,
        # железо, опыт, цель, травмы) — раньше оседало только в
        # ai_chat_messages, откуда его надо было доставать отдельным
        # инструментом. null в поле значит «не знаем, спроси» — это НЕ то же
        # самое, что отсутствие поля вообще, поэтому отдаём все пять всегда.
        "profile": {
            "experience": user["experience"],
            "goal": user["goal"],
            "days_per_week": user["days_per_week"],
            "equipment": equipment,
            "limitations": user["limitations"],
        },
        "stats": {
            "total_workouts": dash.total_workouts,
            "this_week": dash.this_week,
            "last_30_days": dash.last_30_days,
            "days_since_last": dash.days_since_last,
            "week_streak": dash.week_streak,
        },
        "exercises": [
            {
                "name": ex["display_name"],
                "muscle_group": group_name_by_id.get(ex["primary_group_id"]),
                "times_used": ex["usage_count"],
                "last_used_at": ex["last_used_at"],
            }
            for ex in exercises
        ],
    }


def _stored_progression(raw: Any) -> Optional[dict[str, Any]]:
    """routine_exercises.progression — JSON-текст; на битой строке молчим и
    считаем, что правила не было: и превью, и выдача get_saved_programs
    сравнивают/показывают состав, и уронить их из-за неразобранной строки
    было бы хуже, чем показать «без прогрессии»."""
    if not raw:
        return None
    try:
        value = json.loads(raw)
    except (TypeError, ValueError):
        return None
    return value if isinstance(value, dict) else None


async def _saved_programs(user_id: int) -> dict[str, Any]:
    """Сохранённые программы пользователя с составом каждого дня.

    Нужны, чтобы тренер мог править то, что у человека уже есть, а не только
    предлагать новое: без этого «убери сведения из дня ног» ему просто не по
    чему выполнить. `id` дней здесь не отдаём — правка идёт по имени программы
    (см. propose_program.replaces_program), а имена пользователю и видны.

    `kind` — "program" (многодневка) или "routine" (одиночная программа из
    одного дня): без этой пометки список был плоским, а _resolve_replaced_program
    сначала проверял многодневки, потом одиночные — при совпадении имён между
    ними правилась не та программа, на которую рассчитывал пользователь, и по
    превью это было не понять (см. PROGRAMS_DEEP_DIVE §5.4).

    `progression` у каждого упражнения обязательна в выдаче: правка идёт через
    propose_program «программа ЦЕЛИКОМ», и всё, чего модель не пришлёт,
    стирается — пока она не видела сохранённые правила прогрессии, ей нечем
    было их перенести, и «замени приседания на жим ногами» молча сносил
    double_progression на нетронутом жиме лёжа.
    """

    async def _exercises(routine_id: int) -> list[dict[str, Any]]:
        return [
            {
                "name": ex["display_name"],
                "target": ex["target"],
                "progression": _stored_progression(ex["progression"]),
            }
            for ex in await db.list_routine_exercises(routine_id)
        ]

    programs: list[dict[str, Any]] = []
    for row in await db.list_programs(user_id):
        days = []
        for day in await db.list_program_days_by_id(row["id"]):
            days.append({"name": day["name"], "exercises": await _exercises(day["id"])})
        programs.append({"name": row["program_name"], "kind": "program", "days": days})
    for routine in await db.list_standalone_routines(user_id):
        programs.append(
            {
                "name": routine["name"],
                "kind": "routine",
                "days": [
                    {"name": routine["name"], "exercises": await _exercises(routine["id"])}
                ],
            }
        )
    return {
        "programs": programs,
        "note": (
            "Это то, что у пользователя уже сохранено. Чтобы поправить одну из "
            "этих программ, вызови propose_program целиком (со всеми днями, "
            "включая нетронутые) и передай её точное имя в replaces_program. "
            "Правила progression нетронутых упражнений тоже переноси как есть — "
            "чего не пришлёшь, у того сотрётся."
        )
        if programs
        else "У пользователя пока нет сохранённых программ.",
    }


async def _weekly_volume(user_id: int) -> dict[str, Any]:
    today = await _user_today(user_id)
    monday = today - dt.timedelta(days=today.weekday())
    sunday = monday + dt.timedelta(days=6)
    counts = await db.weekly_volume_by_group(user_id, monday.isoformat(), sunday.isoformat())
    groups = await db.list_muscle_groups(user_id)
    rows = []
    for g in groups:
        c = counts.get(g["id"], 0)
        rows.append({"group": g["name"], "sets": c, "status": analytics.classify_weekly_volume(c)})
    ungrouped = counts.get(None, 0)
    if ungrouped:
        rows.append({"group": "Без группы", "sets": ungrouped, "status": analytics.classify_weekly_volume(ungrouped)})
    return {
        "week": f"{monday.isoformat()}..{sunday.isoformat()}",
        "target_sets_per_group": f"{analytics.WEEKLY_VOLUME_MIN}-{analytics.WEEKLY_VOLUME_MAX}",
        "groups": rows,
    }


async def _muscle_recovery(user_id: int) -> dict[str, Any]:
    """Насколько отдохнула каждая группа мышц — то же, что видит человек на
    экране выбора («💤 Ещё не отдохнули: ноги — 40%»), но целиком.

    Ровно та же арифметика, что и в подсказке на экране (analytics.
    recovery_percent над db.last_session_by_group): бот не должен считать
    свежесть ног одним числом для экрана и другим для тренера.

    Тренер про восстановление раньше не знал вообще — при том что «что сегодня
    качать» это первый вопрос, с которым к нему приходят, и данные для ответа
    лежали в двух функциях рядом. Без них он либо переспрашивал, когда человек
    последний раз тренировал ноги, либо угадывал.

    Группы, в которых не было ни одной тренировки, отдаются отдельным списком,
    а не как «100% отдохнула»: это разные вещи — «свежая» и «ни разу не
    тронутая», и вторая обычно интереснее, потому что означает пробел.
    """
    last = await db.last_session_by_group(user_id)
    today = await _user_today(user_id)
    groups = await db.list_muscle_groups(user_id)

    rows, never = [], []
    for group in groups:
        entry = last.get(group["id"])
        if entry is None:
            never.append(group["name"])
            continue
        day, sets_done = entry
        rows.append(
            {
                "group": group["name"],
                "recovery_percent": analytics.recovery_percent(
                    dt.date.fromisoformat(day), sets_done, today
                ),
                "last_trained": day,
                "days_ago": (today - dt.date.fromisoformat(day)).days,
                "sets_that_session": sets_done,
            }
        )
    rows.sort(key=lambda r: r["recovery_percent"])
    return {
        "groups": rows,
        "never_trained": never,
        "note": (
            "100% — группа готова к тяжёлой работе, ниже 85% человек видит на "
            "экране выбора как «ещё не отдохнула». Это оценка по времени и "
            "объёму прошлой сессии, а не замер: спорить с самочувствием "
            "человека ей не стоит."
        ),
    }


