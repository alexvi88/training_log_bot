def _fmt_set(row: Any) -> str:
    """'100x8' or, when RPE was logged, '100x8@9' — as the model sees a set."""
    base = f"{row['weight']:g}x{row['reps']}"
    rpe = row["rpe"]
    return f"{base}@{rpe:g}" if rpe is not None else base


