async def _search_block(
    user_id: int, on_limit: Optional[Callable[[Any], Awaitable[None]]]
) -> Optional[ai_limits.Block]:
    """Что мешает поднять живой поиск — личная квота, общий потолок или деньги.

    Порядок проверок — от личного к общему: на «личный лимит» в логе смотреть
    незачем, а «упёрлись в ОБЩИЙ потолок» и «сутки дороже потолка» — это уже
    события, и путать их между собой нельзя.
    """
    for kind in (ai_limits.KIND_SEARCH, ai_limits.KIND_SEARCH_GLOBAL):
        block = await ai_limits.check(user_id, kind)
        if block is None:
            continue
        if block.preview:
            # Свой аккаунт, ещё не нажавший «Понятно» сегодня: показываем, что
            # увидел бы обычный атлет, но сам поиск не отменяем — иначе
            # «Понятно» снимало бы лимит только на будущее, а этот, уже
            # заданный вопрос всё равно ушёл бы без свежих данных.
            if on_limit is not None:
                await on_limit(block)
            continue
        return block
    # Прочитанные выше значения разрешают поиск, но общий потолок делят ВСЕ
    # пользователи разом, а от этой строки до сетевого похода в
    # _web_search_findings — секунды. Личную гонку (тот же человек спросил
    # дважды подряд) уже гасит busy-замок в handlers/ai_trainer.py, а вот
    # параллельный всплеск вопросов от РАЗНЫХ людей мог бы весь пройти мимо
    # read-проверки выше и провалиться сквозь потолок вместе. Тут гонка
    # опаснее контракта «квота списывается только за находку» — поэтому
    # резервируем место атомарно ДО вызова, а не после (см.
    # db.try_increment_ai_search_count_global).
    if not await db.try_increment_ai_search_count_global(config.AI_SEARCH_GLOBAL_DAILY_LIMIT):
        logger.warning(
            "AI global search cap: атомарная бронь не досталась — параллельный "
            "всплеск запросов забрал последний слот между чтением счётчика и этой строкой"
        )
        return ai_limits.Block(
            kind=ai_limits.KIND_SEARCH_GLOBAL,
            log="search_global: race lost at atomic reserve",
        )
    return None


async def ask(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    image_data_url: Optional[str] = None,
    on_status: StatusCallback = None,
    on_program: ProgramCallback = None,
    on_action: ActionCallback = None,
    on_questions: QuestionsCallback = None,
    on_chunk: ChunkCallback = None,
    video_context: Optional[str] = None,
    on_reasoning: Optional[Callable[[str], Awaitable[None]]] = None,
    on_wire: Optional[Callable[[list[dict[str, Any]]], Awaitable[None]]] = None,
    on_limit: Optional[Callable[[Any], Awaitable[None]]] = None,
) -> str:
    """Один вопрос пользователя → готовый текст ответа.

    history — то, что реально уехало модели в прошлый раз, включая её обращения к
    инструментам и их результаты. Раньше сюда шли только видимые реплики, а
    tool-сообщения выбрасывались как ненужные — но по документации xAI кэш живёт
    ровно на НЕИЗМЕННОМ префиксе, и выброшенное сообщение это переписанная
    история, то есть промах. В логах прода это выглядело так: внутри одного
    вопроса раунды дописываются и кэш растёт (10752 → 11776 → 14080), а каждый
    следующий вопрос начинается с 128.

    on_wire — колбэк, которому по завершении хода отдаётся ровно тот список
    сообщений, что уехал модели (без ведущего системного промпта — он не
    входит в историю и добавляется заново на каждый запрос, но теперь не
    зависит от даты и байт-в-байт одинаков у всех ходов, см. _system_prompt).
    Его и надо сохранить как историю для следующего вопроса — тогда следующий
    запрос ДОПИСЫВАЕТ, а не переписывает.

    image_data_url — опционально, фото, которое пользователь прислал вместе с этим
    вопросом (data: URL, base64). Передаётся только в текущий ход; в history фото
    не попадают — модель не сможет пересмотреть их позже, только вспомнить по тексту.

    video_context — опционально, наблюдения по присланному видео (см.
    video_analysis.to_context_block). Приезжает контекстом ровно как результаты
    веб-поиска: смотрит кадры отдельная модель, а говорит про них тренер —
    голос у продукта один. Само видео сюда не попадает и в history тоже, только
    текст наблюдений.

    on_status — опциональный колбэк, которому по ходу дела шлём текст того, что
    реально сейчас происходит (веб-поиск, конкретный tool-call), чтобы вызывающая
    сторона могла показать это пользователю вместо голого "думаю" (см.
    handlers/ai_trainer.py).

    on_limit — опциональный колбэк, которому отдаётся ai_limits.Block, когда
    поисковый шаг не состоялся из-за потолка. Обычный атлет об этом ничего не
    узнаёт (ответ просто идёт без свежести), а свой аккаунт получает
    предупреждение — ради него колбэк и заведён: изнутри ask() сообщение в чат
    не отправишь, здесь нет ни бота, ни экрана.

    on_program — опциональный колбэк с черновиком программы, если тренер за этот
    ход собрал её (см. propose_program). Текст ответа при этом обычный: черновик
    едет отдельно, потому что сохранить его должен тап пользователя, а не модель.

    on_action — то же самое для действия, которое тренер предложил, но не
    выполнил (удалить программу, объединить две, поделиться, заархивировать
    упражнение): колбэк получает подпись и callback_data будущей кнопки.

    on_questions — опросник перед сборкой программы (см. ask_setup_questions):
    весь список вопросов приезжает разом, а показывает их по одному и копит
    ответы уже вызывающая сторона, без единого обращения к модели между ними.

    Пока не исчерпана дневная квота поисковых ответов (config.AI_SEARCH_DAILY_LIMIT),
    перед основным ответом дешёвый гейт (см. _gate_verdict)
    решает, нужен ли вопросу живой веб/X-поиск, и только на «да» поднимается
    отдельный дорогой шаг multi-agent поиска (см. _web_search_findings). Найденное
    (если есть) добавляется контекстом к основному REST-вызову с обычными
    инструментами.
    """
    # Дешёвый гейт (_gate_verdict) решает, стоит ли вообще
    # поднимать дорогой multi-agent поиск, и только на «да» он запускается. Так
    # дорогая модель не дёргается на каждый вопрос (большинство — про личные данные,
    # поиска не требуют). Порядок в and важен: короткое замыкание не даёт вызвать
    # гейт при исчерпанной квоте.
    # Исход пишем словами, а не bool: «False» одинаково значил и «квота
    # кончилась», и «гейт сказал нет», и «поиск отработал, но ничего не
    # принёс». Сломанный гейт (см. _SEARCH_GATE_MAX_TOKENS) в этом логе был
    # неотличим от честного отказа — и потому прожил незамеченным.
    search_context = None
    # Гейт решает сразу два вопроса — поиск и доступ к данным (см. GateVerdict),
    # поэтому вызывается он и при исчерпанной поисковой квоте: инструменты нужны
    # независимо от поиска, и экономить на этом решении нечего — вердикт всё
    # равно стоит доли цента, а лишние 6900 токенов схем в каждом раунде дороже.
    # Гейту и поиску — только видимые реплики: полная история нужна ради кэша
    # основного вызова, а этим двум tool-сообщения стоили бы токенов ни за что.
    light = _light_history(history)
    # Гейт временно отключён (живой прогон, риск/выгода не в его пользу — см.
    # обсуждение с автором задачи): вместо вызова модели ради решения
    # «искать/не искать» и «нужны ли данные» — фиксированный вердикт. Поиск
    # выключен целиком (search=False, дальше по цепочке elif это просто «gate
    # says not needed», без единого сетевого похода), инструменты — всегда
    # (data=True). GateVerdict/_gate_verdict/_web_search_findings оставлены
    # нетронутыми, а не удалены: это осознанно обратимая правка на время
    # сравнения костов до/после, а не архитектурное решение.
    gate = GateVerdict(search=False, data=True, ok=True)
    if video_context:
        # Разбор ролика решается кадрами, а не сетью: наблюдения уже приехали от
        # модели, которая его смотрела. Гейт же судит по тексту вопроса, и на
        # «разбери технику приседа легенды Святослава» честно решает, что надо
        # выяснить, кто это, — поднимая multi-agent с четырьмя агентами и платой
        # $5 за 1000 вызовов инструментов за информацию, которая ответу не нужна.
        search_outcome = "skipped: видео разбирается по кадрам, сеть не нужна"
    elif gate.ok and not gate.search:
        # Гейт честно решил, что поиск не нужен — до резерва слота в общем
        # потолке дело даже не доходит: незачем списывать общую квоту за вопрос,
        # который никогда не пойдёт в сеть (см. gate = GateVerdict(search=False, ...)
        # выше — сейчас это вообще каждый вопрос).
        search_outcome = "skipped: gate says not needed"
    elif (search_block := await _search_block(user_id, on_limit)) is not None:
        # Личная квота, общий потолок поисков и суточный потолок по деньгам —
        # все три через ai_limits, чтобы решение о дорогом шаге принималось в
        # одном месте. Исход пишем словами: «упёрлись в общий потолок» — сигнал,
        # что сутки были дорогими, а «личный лимит» — обычное дело одного
        # активного атлета.
        search_outcome = f"skipped: {search_block.log}"
    elif not gate.ok and _looks_like_it_needs_fresh_web(question):
        # Гейт молчит, но вопрос сам говорит, что ему нужна свежесть. Дефолт «не
        # искать» тут стоил бы ответа по существу: на «что нового в мире
        # бодибилдинга» модель рассказала бы о мире, которого уже нет.
        search_context = await _web_search_findings(user_id, question, light, on_status)
        search_outcome = (
            "used (гейт сломался, но вопрос просит свежести)" if search_context
            else "ran but returned nothing (гейт сломался, искали по признакам)"
        )
    elif not gate.ok:
        # Гейт не отработал — и это НЕ «решил, что не надо». Раньше оба случая
        # писались одной фразой, и на вопросе «что нового в мире бодибилдинга»
        # лог уверял, что поиск не нужен, хотя гейт просто вернул пустоту.
        search_outcome = "skipped: ГЕЙТ СЛОМАЛСЯ, сработал дефолт (см. WARNING выше)"
    else:
        search_context = await _web_search_findings(user_id, question, light, on_status)
        # «Нашёл» и «упал» — разные исходы, и путать их дорого: на неподдерживаемом
        # agent_count поиск падал ValueError ещё в chat.create, а в логе это
        # читалось как «сходил и ничего не нашёл» — функция была выключена месяцами.
        search_outcome = "used" if search_context else "ran but returned nothing (см. ERROR выше, если был)"
    logger.info(
        "AI trainer question from user %s: %r (web search: %s; гейт про данные: %s)",
        user_id, question, search_outcome,
        "нужны" if gate.data else "не нужны",
    )
    # Схемы инструментов выбрасываем ТОЛЬКО на первом вопросе разговора. Дальше
    # стабильность префикса дороже: включи/выключи их посреди диалога — и всё, что
    # после системного промпта, перестаёт совпадать с закэшированным. Живые логи:
    #
    #     со схемами, кэш попал     30272 токенов (из кэша 29696)   $0.0105
    #     без схем, кэш промахнулся 17732 токенов (из кэша 128)     $0.0387
    #
    # Меньше токенов — втрое дороже. Экономия в шесть тысяч токенов на схемах не
    # стоит промаха по восемнадцати. А на первом вопросе кэшу терять нечего:
    # префикса там ещё нет.
    with_tools = gate.data or bool(history)
    logger.info(
        "AI trainer tools for user %s: %s",
        user_id,
        "отправлены" if with_tools
        else "НЕ отправлены (первый вопрос, гейт сказал данные не нужны)",
    )
    return await _ask_plain(
        user_id, question, history, image_data_url, search_context, on_status, on_program,
        on_action, on_chunk, video_context, with_tools=with_tools,
        on_reasoning=on_reasoning, on_questions=on_questions, on_wire=on_wire,
    )


def _plain_user_content(question: str, image_data_url: Optional[str]) -> Any:
    if not image_data_url:
        return question
    return [
        {"type": "text", "text": question},
        {"type": "image_url", "image_url": {"url": image_data_url}},
    ]


# Как часто отдаём накопленный текст наружу во время стрима — см.
# config.AI_STREAM_FLUSH_SECONDS (не на каждый токен: получатель шлёт его в
# Telegram, а там лимиты на частоту запросов).
STREAM_FLUSH_SECONDS = config.AI_STREAM_FLUSH_SECONDS

# Первый флаш ждёт не только тайминга, но и объёма: время до первого токена
# модели (thinking, network) само по себе часто больше STREAM_FLUSH_SECONDS,
# так что "прошло достаточно времени" на первой дельте почти всегда истинно —
# и наружу уходит одно слово или буква, которая потом висит без изменений ещё
# целый интервал. Порог по символам держит первый показ черновика содержательным.
MIN_FIRST_FLUSH_CHARS = 40


async def _completion_round(
    client: AsyncOpenAI,
    messages: list[dict[str, Any]],
    user_id: Optional[int],
    on_chunk: ChunkCallback = None,
    include_tools: bool = True,
) -> tuple[str, list[Any]]:
    """One chat-completion turn. Returns (content, tool_calls).

    `on_chunk` включает стриминг: текст отдаётся наружу по мере генерации, не
    чаще чем раз в STREAM_FLUSH_SECONDS. Стримить имеет смысл только тот раунд,
    который окажется финальным, — но какой из них финальный, заранее неизвестно,
    поэтому раунд с tool_calls просто ничего не отдаёт (там текста и нет, а
    происходящее показывают статусы).

    `include_tools=False` — принудительный текстовый раунд без единого tool:
    используется только на последней попытке _ask_plain, когда раунды с
    инструментами исчерпаны (см. MAX_TOOL_ROUNDS и A12) — без tools в самом
    запросе модели физически нечего вызвать, и она обязана ответить текстом.
    """
    tools_kwarg = {"tools": TOOLS} if include_tools else {}
    if on_chunk is None:
        response = await client.chat.completions.create(
            model=config.GROK_MODEL, max_tokens=2048, messages=messages,
            extra_body={"reasoning_effort": config.GROK_REASONING_EFFORT},
            extra_headers=_cache_headers(user_id),
            **tools_kwarg,
        )
        await _log_llm_cost(user_id, config.GROK_MODEL, getattr(response, "usage", None))
        m = response.choices[0].message
        return (m.content or ""), list(m.tool_calls or []), _reasoning_of(m)

    stream = await client.chat.completions.create(
        model=config.GROK_MODEL, max_tokens=2048, messages=messages,
        extra_body={"reasoning_effort": config.GROK_REASONING_EFFORT},
        extra_headers=_cache_headers(user_id),
        stream=True, stream_options={"include_usage": True},
        **tools_kwarg,
    )
    parts: list[str] = []
    reasoning_parts: list[str] = []
    tool_calls: dict[int, dict[str, Any]] = {}
    usage = None
    last_flush: Optional[float] = None
    # xAI sends `usage` only on the final chunk. A timeout/cancellation/network
    # drop partway through the `async for` used to leave `_log_llm_cost` never
    # called at all — tokens the provider already billed us for went unlogged.
    # `finished` tells the `finally` below whether the loop actually reached
    # that final chunk, so it only reaches for the fallback estimate on abort.
    finished = False
    try:
        async for event in stream:
            usage = getattr(event, "usage", None) or usage
            if not event.choices:
                continue
            delta = event.choices[0].delta
            reasoning_delta = _reasoning_of(delta)
            if reasoning_delta:
                reasoning_parts.append(reasoning_delta)
            for tc in getattr(delta, "tool_calls", None) or []:
                slot = tool_calls.setdefault(
                    tc.index, {"id": "", "name": "", "arguments": ""}
                )
                slot["id"] += tc.id or ""
                if tc.function:
                    slot["name"] += tc.function.name or ""
                    slot["arguments"] += tc.function.arguments or ""
            if delta.content:
                parts.append(delta.content)
                text = "".join(parts)
                now = asyncio.get_running_loop().time()
                # Before the first flush, time elapsed alone isn't a good signal —
                # the wait for the model's first token already eats into it — so
                # the first flush also needs enough text to be worth showing.
                ready = (
                    (last_flush is None and len(text) >= MIN_FIRST_FLUSH_CHARS)
                    or (last_flush is not None and now - last_flush >= STREAM_FLUSH_SECONDS)
                )
                if ready:
                    last_flush = now
                    await on_chunk(text)
        finished = True
    finally:
        if usage is None and not finished:
            # Aborted before the final chunk arrived, so there's no real usage
            # to report. Best available estimate: ~4 chars/token over the
            # prompt actually sent and whatever completion text streamed back
            # before the drop — better than silently losing the event, and the
            # only signal we have without the provider's own count.
            usage = SimpleNamespace(
                prompt_tokens=_estimate_tokens_from_messages(messages),
                completion_tokens=_estimate_tokens_from_text("".join(parts)),
            )
        await _log_llm_cost(user_id, config.GROK_MODEL, usage)
    return (
        "".join(parts),
        [_StreamedToolCall(slot) for slot in tool_calls.values()],
        "".join(reasoning_parts),
    )


class _StreamedToolCall:
    """Собранный из дельт tool-call в форме, которую ждёт остальной код
    (tc.id / tc.function.name / tc.function.arguments)."""

    def __init__(self, slot: dict[str, Any]) -> None:
        self.id = slot["id"]
        self.function = SimpleNamespace(name=slot["name"], arguments=slot["arguments"])


async def _ask_plain(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    image_data_url: Optional[str] = None,
    search_context: Optional[str] = None,
    on_status: StatusCallback = None,
    on_program: ProgramCallback = None,
    on_action: ActionCallback = None,
    on_chunk: ChunkCallback = None,
    video_context: Optional[str] = None,
    with_tools: bool = True,
    on_reasoning: Optional[Callable[[str], Awaitable[None]]] = None,
    on_questions: QuestionsCallback = None,
    on_wire: Optional[Callable[[list[dict[str, Any]]], Awaitable[None]]] = None,
) -> str:
    client = _get_client()
    messages: list[dict[str, Any]] = [
        {"role": "system", "content": _system_prompt()},
        *history,
    ]
    if video_context:
        messages.append({"role": "system", "content": video_context})
    if search_context:
        messages.append(
            {
                "role": "system",
                "content": f"Результаты живого веб/X-поиска по текущему вопросу пользователя:\n{search_context}",
            }
        )
    # Дата едет тут, в хвосте последнего user-сообщения, а не в системном
    # промпте (см. _system_prompt): так меняется только этот, самый последний
    # ход, а не общая для всех шапка запроса. Дальше эта же дата остаётся
    # вморожена в сохранённую историю — прошлые ходы честно помнят, каким
    # днём они были заданы, а следующий вопрос допишет уже свежую.
    today = await _user_today(user_id)
    question_with_date = f"{question}\n\nСегодня {today.isoformat()}."
    messages.append(
        {"role": "user", "content": _plain_user_content(question_with_date, image_data_url)}
    )

    content = ""
    for _ in range(MAX_TOOL_ROUNDS + 1):
        # with_tools=False — гейт решил, что данные пользователя вопросу не нужны
        # (общее знание вроде «креатин работает?»), и тогда схемы 27 инструментов
        # не уезжают вовсе: это около 6900 токенов из каждого раунда. Раунд тут
        # заведомо один — вызвать модели нечего, она отвечает текстом.
        content, tool_calls, reasoning = await _completion_round(
            client, messages, user_id, on_chunk, include_tools=with_tools
        )
        if not tool_calls:
            # Размышления ФИНАЛЬНОГО раунда — то, что должно уехать назад вместе
            # с ответом в истории (см. _reasoning_of и on_reasoning).
            if on_reasoning and reasoning:
                await on_reasoning(reasoning)
            break
        if on_status:
            variants = TOOL_STATUS_TEXTS.get(tool_calls[0].function.name, _DEFAULT_TOOL_STATUS)
            await on_status(random.choice(variants))
        messages.append(
            {
                "role": "assistant",
                "content": content,
                "tool_calls": [
                    {
                        "id": tc.id,
                        "type": "function",
                        "function": {"name": tc.function.name, "arguments": tc.function.arguments},
                    }
                    for tc in tool_calls
                ],
            }
        )
        for tc in tool_calls:
            try:
                args = json.loads(tc.function.arguments or "{}")
                tool_content = await execute_tool(
                    user_id, tc.function.name, args,
                    on_program=on_program, on_action=on_action, on_questions=on_questions,
                )
            except Exception:
                logger.exception("AI trainer tool %s failed", tc.function.name)
                tool_content = json.dumps(
                    {"error": "tool failed, answer from what you already have"}
                )
            messages.append({"role": "tool", "tool_call_id": tc.id, "content": tool_content})
    else:
        # Раунды с инструментами исчерпаны (см. MAX_TOOL_ROUNDS), а модель на
        # последней итерации всё ещё звала tools — их результаты уже дописаны
        # в messages выше, но текстового ответа на них никто не спросил. Без
        # этого ask() возвращал заглушку "не получилось сформулировать ответ"
        # притом что on_program мог уже сработать этим же ходом — пользователь
        # видел провал и живую кнопку программы под ним разом (см. A12).
        # tools здесь физически не передаются: без них отвечать нечем, кроме
        # текста.
        content, _, reasoning = await _completion_round(
            client, messages, user_id, on_chunk, include_tools=False
        )
        # Это тоже финальный ответ — значит и его размышления должны уехать в
        # историю, иначе следующий вопрос промахнётся мимо кэша.
        if on_reasoning and reasoning:
            await on_reasoning(reasoning)

    text = (content or "").strip()

    if on_wire:
        # Финальный ответ модели дописываем сами: в messages он не попадал, потому
        # что цикл на нём заканчивается. Без него следующий вопрос отдал бы
        # историю, где на последний вопрос нет ответа, — то есть снова НЕ тот
        # префикс, что закэширован.
        final: dict[str, Any] = {"role": "assistant", "content": text}
        if reasoning:
            final["reasoning_content"] = reasoning
        wire = messages[1:] + [final]  # без системного промпта: он собирается заново на каждый ход
        # Фото в историю не кладём: это база64 на мегабайты в FSM-файле и повторная
        # плата за image-токены на каждом следующем вопросе. Подменяем на текст
        # вопроса — префикс рвётся с этого сообщения, но всё, что до него (шапка на
        # одиннадцать тысяч токенов и прошлые ходы), продолжает попадать в кэш.
        if image_data_url:
            for m in wire:
                if m.get("role") == "user" and not isinstance(m.get("content"), str):
                    m["content"] = question_with_date
        await on_wire(_trim_wire_history(wire, config.AI_WIRE_HISTORY_MAX_CHARS))

    return text or "Не получилось сформулировать ответ, попробуй переспросить."


def _to_xai_messages(
    history: list[dict[str, Any]],
    question: str,
    image_data_url: Optional[str] = None,
    system_prompt: Optional[str] = None,
) -> list:
    if system_prompt is None:
        raise ValueError("system_prompt обязателен: он содержит дату пользователя")
    out = [xai_system(system_prompt)]
    for msg in history:
        content = msg.get("content", "")
        if msg.get("role") == "assistant":
            out.append(xai_assistant(content))
        else:
            out.append(xai_user(content))
    if image_data_url:
        out.append(xai_user(question, xai_image(image_data_url, detail="high")))
    else:
        out.append(xai_user(question))
    return out


# Гейт отвечает одним словом — но отвечает им ризонинговая модель, а
# reasoning-токены списываются из того же бюджета, что и ответ. На прежних
# max_tokens=3 бюджет заканчивался внутри размышления, наружу приходил ПУСТОЙ
# content, а пустой вердикт — это «не YES»: живой поиск не поднимался никогда,
# как бы вопрос его ни просил («что там по свежим исследованиям, со ссылками»
# — тоже нет). Потолок щедрый намеренно: платим за реально сгенерированное, а
# односложный ответ столько не сгенерирует ни при каком раскладе.
_SEARCH_GATE_MAX_TOKENS = 512


class GateVerdict(NamedTuple):
    """Что решил дешёвый гейт по вопросу: нужен ли поиск и нужны ли данные.

    Оба поля «по умолчанию безопасны» в разные стороны, и это не симметрия, а
    расчёт: не искать — дешевле и безопаснее (поиск дорогой, а без него ответ
    просто менее свежий), а данные наоборот — лучше дать зря, чем оставить
    тренера без доступа к истории, потому что тогда он ответит общими словами
    там, где от него ждут конкретику по человеку.

    ok=False означает, что гейт не отработал и значения — дефолтные. Флаг нужен,
    чтобы в логе не выдавать поломку за решение: «gate says not needed» на самом
    деле стояло и там, где гейт вернул пустоту, — то есть на вопрос «что нового в
    мире бодибилдинга» поиск не поднимался, а лог уверял, что он не нужен. Ровно
    от этой путаницы предупреждает комментарий в ask().
    """

    search: bool = False
    data: bool = True
    ok: bool = True


async def _gate_verdict(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
) -> GateVerdict:
    """Дешёвый гейт: решаем на config.GROK_MODEL, нужен ли вопросу живой
    веб/X-поиск и нужны ли тренеру данные пользователя.

    Второе решение экономит заметно больше первого. Схемы 27 инструментов — это
    около 6900 токенов, которые уезжают в КАЖДОМ раунде tool-call'ов, и на
    вопросе «креатин работает?» ни один из них не нужен: ответ пришёл одним
    вызовом, без единого обращения к базе. Отдать в таком случае ноль схем —
    минус две трети входа.

    Решение «искать или нет» — обычная классификация, ей не нужен веб-доступ,
    поэтому гонять на каждый вопрос отдельный шаг с config.GROK_SEARCH_MODEL
    только ради этого решения — пустой слив бюджета: большинство вопросов к
    боту-дневнику про личные данные пользователя и поиска не требуют. Шаг с
    поиском поднимаем только когда этот гейт сказал «да». Картинку в решение
    не передаём — тема поиска считывается по тексту, а фото у нас почти всегда
    личное (форма, еда), поиска не просит.

    При любой ошибке или неразборчивом ответе возвращаем значения по умолчанию
    (см. GateVerdict): не искать и данные всё-таки дать.
    """
    # Гейту нужна ТЕМА вопроса, а не всё задание целиком. Вопрос с ответами на
    # опросник программы приезжает на две тысячи токенов инструкций — и ровно на
    # таких входах гейт дважды в проде вернул НОЛЬ выходных токенов, то есть съел
    # бюджет и не решил ничего. Заодно экономия: гейт идёт на каждый вопрос.
    if len(question) > config.AI_GATE_QUESTION_MAX_CHARS:
        question = question[: config.AI_GATE_QUESTION_MAX_CHARS] + " […]"

    # В переменной, чтобы повтор при пустом вердикте отличался от первой попытки
    # РОВНО одним добавленным сообщением, а не случайно чем-то ещё.
    request_kwargs: dict[str, Any] = {
        "model": config.GROK_MODEL,
        "max_tokens": _SEARCH_GATE_MAX_TOKENS,
        "extra_body": {"reasoning_effort": config.GROK_QUICK_REASONING_EFFORT},
        # Свой слот кэша: у гейта системный промпт втрое короче основного и
        # общего с ним почти ничего, а под одним conv-id они вытесняли друг
        # друга — см. _cache_headers, там разобран лог прода.
        "extra_headers": _cache_headers(user_id, scope="gate"),
        # Схема, а не два слова текстом: на текстовом формате разбор зависел от
        # того, не обернёт ли модель ответ в markdown. Пустой content схема,
        # правда, не лечит — заставить ответить по схеме можно только того, кто
        # вообще отвечает; на это есть повтор ниже.
        "response_format": {
            "type": "json_schema",
            "json_schema": {
                "name": "gate_verdict",
                "strict": True,
                "schema": {
                    "type": "object",
                    "properties": {
                        "search": {"type": "boolean"},
                        "data": {"type": "boolean"},
                    },
                    "required": ["search", "data"],
                    "additionalProperties": False,
                },
            },
        },
        "messages": [
            {
                "role": "system",
                "content": _search_decision_system_prompt(await _user_today(user_id)),
            },
            *history,
            {"role": "user", "content": question},
        ],
    }
    try:
        client = _get_client()
        response = await client.chat.completions.create(**request_kwargs)
    except Exception:
        logger.exception("AI trainer gate step failed, falling back to defaults")
        return GateVerdict(ok=False)
    await _log_llm_cost(user_id, config.GROK_MODEL, getattr(response, "usage", None))
    # Без .upper(): регистр тут ломает разбор, потому что JSON требует именно
    # lowercase true/false. Наследие прежнего формата, где сравнивали с YES/NO.
    verdict = (response.choices[0].message.content or "").strip()
    if not verdict:
        # Ноль выходных токенов при непустых размышлениях: ризонинговая модель
        # иногда думает и не говорит. Бюджет тут не виноват (сотня размышлений
        # против потолка в 512), и strict-схема этого не лечит — заставить
        # ответить по схеме можно только того, кто вообще отвечает.
        #
        # Одна повторная попытка: стоит полцента, а без вердикта поиск не
        # поднимется на вопросе, который его прямо просит («что нового в мире
        # бодибилдинга»). Дважды подряд молчание — уже дефолты.
        # Повтор ДОЛЖЕН отличаться от первой попытки. Первая версия была точной
        # копией — ради того, чтобы не уехать в другой слот кэша, — и в логах
        # прода честно воспроизвела то же молчание токен в токен:
        #   gate: 696+0 (размышления 100)  → пусто
        #   gate: 696+0 (размышления 96)   → снова пусто
        # Детерминированную модель бессмысленно просить дважды об одном и том же.
        # Кэшем гейта тут жертвуем сознательно: его префикс — семь сотен токенов,
        # это дешевле, чем остаться без вердикта.
        logger.warning("AI trainer gate returned an empty verdict, retrying with a nudge")
        retry_kwargs = dict(request_kwargs)
        # Убираем ровно то, что подозревается в молчании: размышления и строгую
        # схему. Добавленной реплики оказалось мало — лог прода показал два
        # пустых ответа подряд уже с ней (1803 токена, потом 1835), то есть
        # модель послушно думала оба раза и оба раза ничего не сказала. Просить
        # то же самое третьим способом смысла нет: меняем сам режим запроса.
        retry_kwargs.pop("response_format", None)
        # extra_body убираем целиком, а не подменяем усилие: «none» xAI не
        # принимает вовсе («This model does not support reasoning_effort value
        # none», 400 на каждом повторе), а любое другое значение — это то же
        # самое, что уже промолчало. Без ключа модель идёт на своих дефолтах,
        # то есть повтор всё равно отличается от первой попытки.
        retry_kwargs.pop("extra_body", None)
        retry_kwargs["messages"] = [
            *request_kwargs["messages"],
            {
                "role": "user",
                "content": (
                    "Ты не ответил ничего. Не размышляй, ответь одной строкой "
                    "ровно в этом виде, без markdown: "
                    '{"search": true, "data": false}'
                ),
            },
        ]
        try:
            response = await client.chat.completions.create(**retry_kwargs)
        except Exception:
            logger.exception("AI trainer gate retry failed, falling back to defaults")
            return GateVerdict(ok=False)
        await _log_llm_cost(user_id, config.GROK_MODEL, getattr(response, "usage", None))
        verdict = (response.choices[0].message.content or "").strip()
    if not verdict:
        logger.warning("AI trainer gate returned an empty verdict twice, using defaults")
        return GateVerdict(ok=False)

    defaults = GateVerdict()
    try:
        # Повтор идёт уже без strict-схемы (см. выше), а без неё модель вполне
        # может обернуть ответ в ```json — вырезаем сам объект, иначе честный
        # вердикт со второй попытки всё равно уехал бы в дефолты.
        body = verdict[verdict.index("{") : verdict.rindex("}") + 1]
        parsed = json.loads(body)
        return GateVerdict(
            search=bool(parsed["search"]),
            data=bool(parsed["data"]),
        )
    except (ValueError, TypeError, KeyError):
        # Со strict-схемой сюда попасть не должно, но молча подставить дефолты
        # нельзя: на data это тихо отключило бы тренеру доступ к базе, а на search
        # выдало бы поломку за решение «искать не надо».
        logger.warning(
            "AI trainer gate verdict is not the expected JSON, using defaults (verdict: %r)",
            verdict[:200],
        )
        return defaults._replace(ok=False)


async def _web_search_findings(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    on_status: StatusCallback = None,
) -> Optional[str]:
    """Отдельный шаг перед основным ответом: чистый server-side веб/X-поиск, без
    наших DB-инструментов (см. модуль docstring, почему они разведены по разным
    вызовам). Возвращает найденное текстом или None, если поиск не нужен вопросу
    или сам шаг не удался — в обоих случаях основной ответ просто идёт без него.

    Одиночный линейный запрос (обычно 1 обращение в сеть на вопрос), а не
    параллельный research по многим источникам, поэтому agent_count держим на
    минимуме (config.GROK_SEARCH_AGENT_COUNT, дефолт 4) — раньше он вообще не
    передавался явно, а по докам xAI непереданный effort может отображаться в
    16 агентов, и биллятся токены (включая ризонинг и тул-коллы) всех агентов
    сразу, не только лидера. Если этот шаг когда-нибудь станет вопросом
    "прочесать много независимых источников параллельно" — тогда есть смысл
    поднять agent_count до 16, а не менять модель: grok-4.20-multi-agent
    дешевле grok-4.5 за токен и не в процессе вывода из эксплуатации.

    web_search/x_search — server-side: модель вызывает их и получает результаты
    в рамках одного sample(), без tool_calls, которые нужно было бы исполнять
    самим — поэтому реальное использование поиска видно только постфактум, по
    citations/server_side_tool_usage в ответе. Сам шаг занимает заметное время
    независимо от исхода, поэтому статус про поиск шлём заранее, а не постфактум.

    Фото пользователя в этот шаг НЕ передаём: оно почти всегда личное (форма,
    тело, еда), а тему поиска модель считывает по тексту — незачем форвардить
    личную картинку во внешний веб/X-поиск (тот же довод, что и в _gate_verdict).
    """
    if on_status:
        await on_status("🔎 ищу свежую информацию в сети...")
    started = asyncio.get_running_loop().time()
    try:
        sdk_client = await _get_sdk_client()
        chat_session = sdk_client.chat.create(
            model=config.GROK_SEARCH_MODEL,
            messages=_to_xai_messages(
                history, question,
                system_prompt=_search_system_prompt(await _user_today(user_id)),
            ),
            tools=[xai_web_search(), xai_x_search()],
            max_tokens=1024,
            # agent_count — параметр multi-agent-моделей, обычной он не нужен и
            # SDK его для неё не ждёт. Передаём только когда модель правда
            # multi-agent: см. config.GROK_SEARCH_MODEL, где разобрано, почему мы
            # с него ушли.
            **(
                {"agent_count": config.GROK_SEARCH_AGENT_COUNT}
                if "multi-agent" in config.GROK_SEARCH_MODEL
                else {}
            ),
        )
        response = await chat_session.sample()
    except Exception:
        # Сколько именно ждали до обрыва — то, по чему потом и подбирается
        # бюджет: без этой цифры «поиск отвалился» не отличить от «поиск
        # отвалился, не дотянув пары секунд».
        logger.exception(
            "AI trainer web search step failed after %.1fs (budget %.0fs), "
            "answering without live search",
            asyncio.get_running_loop().time() - started,
            config.AI_SEARCH_TIMEOUT_SECONDS,
        )
        return None
    logger.info(
        "AI trainer web search step took %.1fs (budget %.0fs)",
        asyncio.get_running_loop().time() - started,
        config.AI_SEARCH_TIMEOUT_SECONDS,
    )

    await _log_llm_cost(user_id, config.GROK_SEARCH_MODEL, getattr(response, "usage", None))
    await _log_server_tool_calls(user_id, response)
    if not (response.citations or response.server_side_tool_usage):
        return None
    # Личный счётчик — единственное, что двигается тут: общий потолок уже
    # зарезервирован раньше, в _search_block, атомарно и ДО этого сетевого
    # похода (см. db.try_increment_ai_search_count_global).
    await db.increment_ai_search_count(user_id)
    return (response.content or "").strip() or None
