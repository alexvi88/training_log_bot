def legacy_program_texts(key: str, field: str) -> set[str]:
    """Все прежние написания поля `field` ("name"/"description"/"day.<i>")
    программы `key` на любом языке — см. LEGACY_PROGRAM_TEXTS."""
    return {
        text
        for (legacy_key, _lang), fields in LEGACY_PROGRAM_TEXTS.items()
        if legacy_key == key
        for text in fields.get(field, ())
    }


# Схема подходов («3×8–12») почти везде language-neutral: цифры, «×» и тире
# читаются одинаково. Исключение — планка и прочее «на время», где к схеме
# приписана единица: «3×30–60 сек».
_TARGET_SECONDS_SUFFIX = " сек"


def localized_target(target: str | None, lang: str) -> str | None:
    """Схема подходов на языке пользователя.

    Возвращает строку как есть во всех случаях, кроме единственного, где в схеме
    есть слово: секунды. Подменять цифры и «×» нечем и незачем, а «сек» рядом с
    английским названием упражнения — та же протечка, что и русская группа мышц
    в теге, только незаметнее: глаз пропускает три буквы в конце строки.
    """
    if not target or lang == i18n.DEFAULT_LANG:
        return target
    if target.endswith(_TARGET_SECONDS_SUFFIX):
        base = target[: -len(_TARGET_SECONDS_SUFFIX)]
        return f"{base} {i18n.t_in(lang, 'program.target.seconds')}"
    return target


async def instantiate_program(
    user_id: int, key: str, name: str, revived: list[int] | None = None
) -> int:
    """Каталожная программа → своя копия в аккаунте пользователя.

    Общая для бота (handlers/routines.py, «➕ Добавить себе») и REST `/v1`
    (api_v1_programs.add_catalog_program) — вторая реализация каталога
    развелась бы точно так же, как чуть не развелись переводы упражнений.

    Имена дней и описание пишутся В БАЗУ на языке, который активен сейчас
    (i18n.get_lang() — ContextVar, выставленный вызывающей стороной), — это
    снимок, как и у названия сфорканного упражнения: дальше это данные
    пользователя, он их сам переименовывает. Перевод — только при смене языка
    аккаунта и только нетронутого (db.relocalize_catalog_copies).
    Состав дней передаётся КАНОНИЧЕСКИМИ именами шаблонов, а не переведёнными:
    db.create_routine_from_program по ним ищет упражнение и форкает шаблон, и
    английское имя он бы не нашёл.

    `revived` — куда сложить id упражнений, которые программа достала из
    архива (см. db.create_routine_from_program): и бот, и `/v1` говорят о
    них атлету, а не теряют упражнение из дня молча.
    """
    lang = i18n.get_lang()
    if revived is None:
        revived = []  # из архива достаём всегда; список нужен только тому, кто о нём скажет
    program_id = await db.create_program(
        user_id, name, source="catalog", source_ref=key,
        description=localized_program_description(key, lang),
    )
    for i, (_day_name, exercises) in enumerate(PROGRAM_BY_KEY[key]["days"]):
        localized_exercises = [
            (ex, localized_target(target, lang)) for ex, target in exercises
        ]
        await db.create_routine_from_program(
            user_id,
            localized_program_day_name(key, i, lang),
            localized_exercises,
            program_id=program_id,
            revived=revived,
        )
    return program_id


