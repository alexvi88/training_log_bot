# Сколько тренировок из истории показывать модели по упражнениям с наибольшим
# числом тренировок — за годы в Hevy их может быть по паре десятков, а сводка
# должна остаться сводкой, а не всей историей заново.
_IMPORT_OVERVIEW_TOP_EXERCISES = 20
# «Давно не было» — сколько дней без упражнения, которое раньше делали
# регулярно, чтобы не путать это с обычным перерывом между подходами одной и
# той же программы.
_IMPORT_OVERVIEW_QUIET_DAYS = 60
# Меньше и уже привычек не разглядеть — только что записанные тренировки
# сегодняшнего дня выглядели бы как «вся история».
_IMPORT_OVERVIEW_MIN_WORKOUTS = 3
# Сколько упражнений называть по имени в короткой реплике ниже порога —
# больше двух-трёх превращает «вижу жим и тягу» обратно в конспект.
_SMALL_OVERVIEW_TOP_EXERCISES = 3


def _join_ru(names: list[str]) -> str:
    """«жим», «жим и тяга», «жим, тяга и присед» — без Оксфордской запятой,
    как в обычной русской речи тренера, а не в списке через точку с запятой."""
    if len(names) == 1:
        return names[0]
    return f"{', '.join(names[:-1])} и {names[-1]}"


async def _small_import_overview(user_id: int, dates: list[str]) -> str:
    """Детерминированная реплика вместо тишины ниже `_IMPORT_OVERVIEW_MIN_WORKOUTS`:
    моделью тут разбирать нечего (1-2 тренировки — не привычка), но человек
    только что явно нажал «Загрузить» и заслуживает подтверждения, что перенос
    правда сработал, а не завис. Никакого completion — считаем то же самое,
    что и остальная сводка (db.exercise_history_spans), просто говорим об этом
    сами, без модели.
    """
    word = formatting.plural_ru(len(dates), ("тренировку", "тренировки", "тренировок"))
    spans = await db.exercise_history_spans(user_id)
    # Список — именительным падежом («жим, тяга»), не винительным: имя
    # упражнения приходит от пользователя произвольным и непредсказуемо
    # склоняемым текстом, а «среди них — …» не требует согласования с глаголом,
    # как потребовало бы «вижу жим и тягу».
    names = _join_ru([row["display_name"].lower() for row in spans[:_SMALL_OVERVIEW_TOP_EXERCISES]])
    seen = f" — среди них {names}" if names else ""
    return (
        f"Перенёс {len(dates)} {word}{seen}. Продолжай, с третьей начну "
        "разбирать твои привычки."
    )


async def import_history_overview(user_id: int) -> Optional[str]:
    """Разбор всей перенесённой истории сразу после CSV/Hevy-импорта — то самое
    «вижу два года жима, присед бросил в марте», а не тишина, в которую
    сейчас утыкается перебежчик из другого приложения.

    Один completion без инструментов и истории чата: вся нужная модели сводка
    уже посчитана кодом (db.exercise_history_spans) — что бросилось в глаза,
    решает модель, а какие упражнения и даты существуют — решают факты, не
    догадка модели по сырым подходам.

    Ниже порога (`_IMPORT_OVERVIEW_MIN_WORKOUTS`) модель вообще не зовём: 1-2
    тренировки — не история, там разбирать нечего, а тишина после явного
    импорта хуже короткой детерминированной реплики. Пустая история (0
    тренировок — файл целиком дублировал уже существующие даты) не получает
    даже её: там перенести нечего, а не рассказать разбор.
    """
    dates = await db.list_finished_workout_dates(user_id)
    if not dates:
        return None
    if len(dates) < _IMPORT_OVERVIEW_MIN_WORKOUTS:
        return await _small_import_overview(user_id, dates)
    if not is_configured():
        return None
    spans = await db.exercise_history_spans(user_id)
    if not spans:
        return None

    overall_last = dt.date.fromisoformat(dates[-1])
    lines = [
        f"Всего тренировок в истории: {len(dates)}.",
        f"Первая: {dates[0]}. Последняя: {dates[-1]}.",
        "Упражнения по числу тренировок, где встречались:",
    ]
    for row in spans[:_IMPORT_OVERVIEW_TOP_EXERCISES]:
        group = f" [{row['group_name']}]" if row["group_name"] else ""
        lines.append(
            f"- {row['display_name']}{group}: {row['sessions']} раз, "
            f"с {row['first_at']} по {row['last_at']}"
        )

    # Упражнение попадает в «давно не было», только если раньше было привычкой
    # (иначе это не бросил, а один раз попробовал), и сортируется по частоте —
    # тренер называет модели самые заметные пропуски, а не первые попавшиеся.
    quiet = sorted(
        (
            row for row in spans
            if row["sessions"] >= 3
            and (overall_last - dt.date.fromisoformat(row["last_at"])).days > _IMPORT_OVERVIEW_QUIET_DAYS
        ),
        key=lambda row: row["sessions"], reverse=True,
    )
    if quiet:
        lines.append("Давно не встречались (последний раз задолго до конца истории):")
        for row in quiet[:5]:
            lines.append(f"- {row['display_name']}: последний раз {row['last_at']}, было {row['sessions']} раз")

    client = _get_client()
    try:
        response = await paid_call(
            user_id, None,
            lambda: client.chat.completions.create(
                model=config.GROK_MODEL,
                max_tokens=500,
                extra_body={"reasoning_effort": config.GROK_QUICK_REASONING_EFFORT},
                extra_headers=_cache_headers(user_id, scope="import_overview"),
                messages=[
                    # Вызывается синхронно из хендлера импорта (handlers/csv_import.py) —
                    # middleware уже выставил язык, отдельный поход в базу не нужен.
                    {"role": "system", "content": _with_language_tail(IMPORT_OVERVIEW_SYSTEM_PROMPT)},
                    {"role": "user", "content": "\n".join(lines)},
                ],
            ),
        )
    except Exception:
        logger.exception("AI import overview generation failed for user %s", user_id)
        return None
    text = (response.choices[0].message.content or "").strip()
    return text or None


async def _weekly_food_summary(user_id: int) -> str:
    """"Питание: записи за 5 дн. из 7, в среднем 2150 ккал и 118 г белка в день."
    Empty string when the diary has nothing this week.

    Averaged over the days actually logged, not over seven: a diary kept on five
    days out of seven describes those five, and dividing by seven would invent a
    deficit that isn't there. Days logged is reported alongside so the coach can
    see how much the average is worth.
    """
    days = (await _food_diary(user_id, days=7))["days"]
    with_calories = [d for d in days if d["calories"]]
    if not with_calories:
        return ""
    avg_kcal = sum(d["calories"] for d in with_calories) / len(with_calories)
    protein_days = [d for d in with_calories if d["protein"]]
    parts = [f"записи за {len(with_calories)} дн. из 7", f"в среднем {avg_kcal:.0f} ккал"]
    if protein_days:
        avg_protein = sum(d["protein"] for d in protein_days) / len(protein_days)
        parts.append(f"{avg_protein:.0f} г белка в день")
    return "Питание: " + ", ".join(parts) + "."


