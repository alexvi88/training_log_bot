"""Сброс потока FSM без потери каркаса незакрытой тренировки.

Общий вход для разделов, в которые уходят прямо посреди тренировки: дневник еды,
история/достижения, отзыв, /mcp. Голый `state.clear()` в них стирал ключи
открытой тренировки (открытые упражнения и их блоки, остаток плана программы,
переписка с AI-тренером) — и человек, вернувшийся в трекер, видел пустой экран
вместо своих подходов: по базе восстанавливается лишь последнее упражнение
(см. handlers.workout._reopen_exercises), а плана и переписки в базе нет вовсе.

Список сохраняемых ключей и сама логика остаются в handlers/workout.py
(`_WORKOUT_SCAFFOLD_KEYS`, `_clear_state_keep_workout`) — они единственное место
правды: продублировать перечисление ключей значит разъехаться с ним на первом же
новом ключе. Здесь только публичное имя, которое можно импортировать откуда
угодно, — приватное из workout.py по всем хендлерам не растащишь.

Импорт отложен внутрь функции нарочно: workout.py и сам тянет handlers.history,
handlers.exercises и handlers.settings из тел функций ровно по этой причине, так
что модуль остаётся импортируемым из любого хендлера при любом порядке сборки
роутеров.
"""

from aiogram.fsm.context import FSMContext


async def clear_state_keep_workout(state: FSMContext) -> None:
    """То же, что `state.clear()`, но каркас незакрытой тренировки уцелеет."""
    from handlers.workout import _clear_state_keep_workout

    await _clear_state_keep_workout(state)
