# То, что не видно ни на одном видео в принципе. Промпт это запрещает прямым
# текстом, и модель всё равно вписывала сюда «напряжение мышц кора и ягодиц»,
# сама же поясняя в why: «это не ограничение ракурса, а принципиальная
# невозможность оценить по видео». Процитировала запрет и нарушила его — значит
# добивать промптом бесполезно, дешевле фильтр в коде.
_UNOBSERVABLE_MARKERS = (
    "напряжен", "кор", "ягодич", "мышц", "дыхан", "намерен",
    "усили", "боль", "пульс", "самочувств",
)

_SEVERITY_ORDER = {"мешает": 0, "стоит поправить": 1, "мелочь": 2}

_VERDICTS = ("норма", "отклонение", "не видно")

# Thinking-модель печатает цепочку рассуждений в тот же content, что и ответ, и
# заворачивает её в <think>…</think>. json.loads на таком тексте падает, и весь
# разбор уходит в None — то есть переключение на thinking без этой чистки просто
# выключило бы фичу целиком.
_THINK_BLOCK_RE = re.compile(r"<think>.*?</think>", re.DOTALL | re.IGNORECASE)
# Незакрытый <think> — обрыв по потолку токенов посреди рассуждения. JSON в этом
# случае не начинался, спасать нечего, но отличать это в логах нужно.
_UNCLOSED_THINK_RE = re.compile(r"<think>", re.IGNORECASE)


def _strip_reasoning(raw: str) -> str:
    """Убрать цепочку рассуждений, оставив JSON.

    Модель иногда печатает <think> вокруг рассуждения, иногда обрамляет ответ
    ```json … ```, а иногда делает и то и другое. Режем оба слоя и на всякий
    случай берём текст от первой { до последней } — лишняя болтовня до или
    после объекта встречается и без всяких маркеров.
    """
    text = _THINK_BLOCK_RE.sub("", raw).strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[-1] if "\n" in text else text
        text = text.rsplit("```", 1)[0]
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        return text[start : end + 1]
    return text.strip()


def _is_unobservable(text: str) -> bool:
    low = text.lower()
    return any(marker in low for marker in _UNOBSERVABLE_MARKERS)


def _clean_checklist(raw: Any) -> list[dict[str, Any]]:
    """Контрольные точки от модели → то, за что она отчиталась на самом деле.

    Одно правило и одна причина. «Норма» без описания увиденного — это не
    результат осмотра, а проставленная галочка, и стоит она дороже любой другой
    ошибки: тренер поверит и посоветует грузить кривой паттерн (ровно так он и
    сказал «наращивай нагрузку» на круглой спине). Поэтому такая точка
    понижается до «не видно» — честного «мы не знаем», — а не выбрасывается:
    исчезнувшая точка выглядела бы как непройденная, и мы бы не отличили её от
    той, что модель забыла вовсе.
    """
    cleaned: list[dict[str, Any]] = []
    for item in raw or []:
        if not isinstance(item, dict):
            continue
        point = str(item.get("point") or "").strip().lower()
        if point not in CHECKPOINTS:
            continue
        verdict = str(item.get("verdict") or "").strip().lower()
        if verdict not in _VERDICTS:
            verdict = "не видно"
        seen = str(item.get("what_i_see") or "").strip()
        if verdict != "не видно" and not seen:
            logger.info("video sanitize: точка «%s» без описания → «не видно»", point)
            verdict = "не видно"
        cleaned.append(
            {"point": point, "verdict": verdict, "what_i_see": seen, "when": item.get("when")}
        )

    by_point = {item["point"]: item for item in cleaned}
    missing = [p for p in CHECKPOINTS if p not in by_point]
    if missing:
        # Не достраиваем: пункт, который модель не прошла, так и остаётся
        # непройденным. Тренеру он приедет как «не смотрели» — это правда, а
        # выдуманная за модель «норма» была бы той самой галочкой.
        logger.warning("video sanitize: модель пропустила точки %s", missing)
    return [by_point[p] for p in CHECKPOINTS if p in by_point]


def _sanitize(data: dict[str, Any]) -> dict[str, Any]:
    """Убрать из ответа модели то, что она обещала не писать.

    Чинит ровно те отклонения, которые видели живьём, и ничего не достраивает:
    пустой разбор так и остаётся пустым — это честный исход.
    """
    view = data.get("view") or {}
    usable = bool(view.get("usable", True))
    problem = (view.get("problem") or "").strip()

    # Наблюдение без доказательства — то самое «дописал, а не увидел», ради
    # чего поле evidence и заведено. Нет его — нет наблюдения.
    raw_observations = data.get("observations") or []
    observations = [
        obs for obs in raw_observations
        if isinstance(obs, dict) and (obs.get("evidence") or "").strip()
    ]
    # Логируем, что модель нашла и что из этого выжило. Без этой строки нельзя
    # отличить «Qwen не увидел ошибок» от «Qwen увидел, а фильтр выбросил», а
    # разница принципиальная: первое — честный разбор, второе — наш баг, из-за
    # которого тренер молчит о реальных косяках.
    dropped = [
        (obs.get("what") if isinstance(obs, dict) else repr(obs)[:60])
        for obs in raw_observations
        if not (isinstance(obs, dict) and (obs.get("evidence") or "").strip())
    ]
    logger.info(
        "video sanitize: наблюдений от модели %s, осталось %s%s",
        len(raw_observations), len(observations),
        f", выброшено без evidence: {dropped}" if dropped else "",
    )
    observations.sort(key=lambda o: _SEVERITY_ORDER.get(o.get("severity"), 3))

    raw_not_visible = data.get("not_visible") or []
    not_visible = [
        item for item in raw_not_visible
        if isinstance(item, dict) and not _is_unobservable(str(item.get("what", "")))
    ]
    if len(not_visible) != len(raw_not_visible):
        logger.info(
            "video sanitize: «не видно» %s → %s (убрано ненаблюдаемое в принципе)",
            len(raw_not_visible), len(not_visible),
        )
    # Непротиворечивость, которую промпт просит, а модель соблюдает не всегда:
    # «ракурс хороший, помех нет» и длинный список «судить нельзя» вместе не
    # живут. Верим первому — оно проверяемо, а список был отпиской.
    if usable and not problem:
        not_visible = not_visible[:2]

    checklist = _clean_checklist(data.get("checklist"))
    # Точка помечена отклонением, а в observations его нет — модель потеряла своё
    # же наблюдение по дороге со шага 1 на шаг 2. Ничего не достраиваем: весь
    # checklist едет тренеру целиком (см. to_context_block), так что отклонение
    # до него доедет и так. Но в лог это надо, иначе молчание тренера про
    # реальный косяк снова будет неотличимо от честного «не нашли».
    lost = [
        item["point"] for item in checklist
        if item["verdict"] == "отклонение"
        and not any(item["point"] in f"{o.get('what')} {o.get('evidence')}".lower()
                    for o in observations)
    ]
    if lost:
        logger.info("video sanitize: отклонение по точкам %s не попало в observations", lost)

    return {
        "exercise": (data.get("exercise") or "не определил"),
        "reps_seen": data.get("reps_seen"),
        "view": {"angle": view.get("angle"), "usable": usable, "problem": problem},
        "checklist": checklist,
        "observations": observations,
        "not_visible": not_visible,
        "camera_advice": (data.get("camera_advice") or "").strip(),
    }


async def analyze(
    video_bytes: bytes,
    user_id: Optional[int],
    mime_type: str = "video/mp4",
) -> Optional[dict[str, Any]]:
    """Видео → структура наблюдений, или None если разобрать не удалось.

    None означает ровно «наблюдений нет»: тренер в этом случае отвечает без
    видео, а не извиняется за чужую поломку.

    mime_type берётся из самого апдейта, а не подставляется наугад: ролик без
    аудиодорожки Telegram отдаёт как animation, и там встречается и video/mp4, и
    image/gif. Соврать про тип в data: URL — значит отправить модели файл под
    чужой вывеской.
    """
    data_url = f"data:{mime_type};base64," + base64.b64encode(video_bytes).decode()
    try:
        response = await _get_client().chat.completions.create(
            model=config.NOVITA_VIDEO_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": [
                        {"type": "text", "text": USER_PROMPT},
                        {"type": "video_url", "video_url": {"url": data_url}},
                    ],
                },
            ],
            max_tokens=config.VIDEO_ANALYSIS_MAX_TOKENS,
            temperature=config.VIDEO_ANALYSIS_TEMPERATURE,
            response_format={"type": "json_object"},
        )
    except Exception:
        logger.exception("video analysis call failed for user %s", user_id)
        return None

    # Цену считает дневной отчёт по имени модели (config.LLM_PRICES_USD_PER_1K),
    # поэтому логируем настоящий usage тем же событием, что и вызовы Grok.
    # Своей оценке модели тут веры нет: на вопрос «сколько токенов ушло» она
    # выдумывает число, у неё нет доступа к счётчику.
    usage = getattr(response, "usage", None)
    prompt_tokens = getattr(usage, "prompt_tokens", 0) or 0
    completion_tokens = getattr(usage, "completion_tokens", 0) or 0
    details = getattr(usage, "prompt_tokens_details", None)
    reasoning_tokens = getattr(
        getattr(usage, "completion_tokens_details", None), "reasoning_tokens", 0
    ) or 0
    # Рассуждение отдельной цифрой: на thinking оно тарифицируется как выход и
    # обычно длиннее самого JSON, так что это главная статья расхода — и первое,
    # на что смотреть, если счёт окажется больше ожидаемого.
    logger.info(
        "video analysis usage: prompt=%s completion=%s (reasoning=%s) model=%s",
        prompt_tokens, completion_tokens, reasoning_tokens, config.NOVITA_VIDEO_MODEL,
    )
    try:
        await db.log_cost_event(
            user_id,
            "llm_call",
            model=config.NOVITA_VIDEO_MODEL,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            cached_tokens=getattr(details, "cached_tokens", 0) or 0,
            reasoning_tokens=reasoning_tokens,
        )
    except Exception:
        logger.exception("failed to log video analysis cost event")

    raw = (response.choices[0].message.content or "").strip()
    payload = _strip_reasoning(raw)
    try:
        parsed = json.loads(payload)
    except (ValueError, TypeError):
        # Оборванное рассуждение и мусор вместо JSON — разные поломки: первая
        # лечится потолком токенов (VIDEO_ANALYSIS_MAX_TOKENS), вторая промптом.
        truncated = bool(_UNCLOSED_THINK_RE.search(raw)) and "</think>" not in raw.lower()
        logger.warning(
            "video analysis returned non-JSON for user %s (%s, completion_tokens=%s): %r",
            user_id,
            "оборвано на рассуждении" if truncated else "не JSON",
            completion_tokens,
            raw[:300],
        )
        return None
    if not isinstance(parsed, dict):
        return None
    # Что модель на самом деле написала по каждой точке — до всякой чистки.
    # Без этой строки нельзя отличить «не увидела круглую спину» от «увидела и
    # проштамповала норму учебной фразой»: наружу оба случая выглядят одинаково
    # (тренер молчит), а чинятся противоположным — первое кадрами, второе
    # промптом. Раньше в логах были только счётчики, и выбирать приходилось
    # наугад.
    for item in parsed.get("checklist") or []:
        if isinstance(item, dict):
            logger.info(
                "video checkpoint | %s | %s | %s",
                item.get("point"), item.get("verdict"),
                str(item.get("what_i_see") or "")[:200],
            )
    return _sanitize(parsed)


def to_context_block(analysis: dict[str, Any]) -> str:
    """Наблюдения → текст, который получает Grok.

    Пишется как показания свидетеля, а не как готовый ответ: явно сказано, что
    смотрела другая модель и что уверенность у наблюдений разная. Иначе тренер
    озвучит догадку как факт — а по CLAUDE.md утверждать про данные атлета
    можно только то, что данные подтверждают.
    """
    view = analysis.get("view") or {}
    lines = [
        "Разбор присланного видео. Смотрела отдельная модель по кадрам — она не "
        "знает ни истории атлета, ни его весов, и может ошибаться. Своих "
        "наблюдений не добавляй: чего нет в списке, того на видео не видели.\n"
        "Про уверенность: наблюдение с ВЫСОКОЙ уверенностью говори прямо, как "
        "факт, без «похоже», «возможно» и «мне кажется» — оно видно в кадре, и "
        "мяться тут значит не помочь. Смягчай только НИЗКУЮ уверенность — вот её "
        "подавай предположением.",
        f"Упражнение на видео: {analysis.get('exercise')}.",
    ]
    if analysis.get("reps_seen"):
        lines.append(f"Повторов видно: {analysis['reps_seen']}.")
    lines.append(f"Ракурс: {view.get('angle')}, годен для разбора: {view.get('usable')}.")
    if view.get("problem"):
        lines.append(f"Помеха на съёмке: {view['problem']}.")

    checklist = analysis.get("checklist") or []
    if checklist:
        lines.append(
            "\nСемь контрольных точек — по каждой сказано, что видно в кадре. "
            "«не смотрели» значит именно это: модель туда не заглянула, и "
            "выдавать такую точку за порядок нельзя."
        )
        for item in checklist:
            verdict = item.get("verdict")
            seen = item.get("what_i_see") or "модель не описала, что видит"
            when = item.get("when")
            mark = {"норма": "чисто", "отклонение": "ОТКЛОНЕНИЕ"}.get(verdict, "не смотрели")
            lines.append(
                f"- {item.get('point')} [{mark}]: {seen}"
                + (f" ({when})" if when else "")
            )
        skipped = [p for p in CHECKPOINTS if p not in {i.get("point") for i in checklist}]
        if skipped:
            lines.append(f"- не смотрели вовсе: {', '.join(skipped)}")

    if analysis.get("observations"):
        lines.append("\nОтклонения:")
        for obs in analysis["observations"]:
            reps = obs.get("reps")
            lines.append(
                f"- [{obs.get('severity')}, уверенность {obs.get('confidence')}] "
                f"{obs.get('what')} — фаза: {obs.get('phase')}, {obs.get('when')}"
                + (f", повторы {reps}" if reps else "")
                + f". Из чего следует: {obs.get('evidence')}"
            )
    else:
        # Самый опасный исход, и на нём тренер уже обжигался: на пустом списке он
        # сказал «чинить нечего, оставляй такой рисунок и наращивай нагрузку» —
        # то есть похвалил технику и велел грузить её сильнее, имея на руках
        # ровно ничего. Отсутствие находок это не данные о технике, и по CLAUDE.md
        # утверждать по нему нельзя ничего.
        lines.append(
            "\nОтклонений не нашли. Это НЕ значит «техника хорошая» — значит, по "
            "этому ролику заметного не увидели, а половина картины на видео и не "
            "видна. Не выдумывай ошибку, чтобы было что сказать, но и не хвали "
            "технику, не называй рисунок движения правильным и не советуй на этом "
            "основании добавлять вес. Скажи честно: по этим точкам чисто, "
            "уверенного разбора по одному ролику не выходит — и позови снять "
            "ещё, с другого ракурса или на рабочем весе."
        )

    if analysis.get("not_visible"):
        lines.append("\nПо этому видео оценить нельзя:")
        for item in analysis["not_visible"]:
            lines.append(f"- {item.get('what')} ({item.get('why')})")

    if analysis.get("camera_advice"):
        lines.append(f"\nКак переснять: {analysis['camera_advice']}")
    return "\n".join(lines)
