_COMPARE_TOP = 8


async def _compare_periods(user_id: int, tool_input: dict[str, Any]) -> dict[str, Any]:
    """«Что изменилось за N дней» по всем упражнениям разом.

    Раньше на такой вопрос приходилось звать get_exercise_progress по одному
    движению за раз и складывать в уме — по десятку упражнений это либо
    десяток вызовов, либо ответ наугад. Считаем то же, что и карточка
    упражнения (e1RM по формуле пользователя, тоннаж, подходы), но за два
    соседних окна одинаковой длины: последние N дней против предыдущих N.

    Упражнения, которых нет ни в одном окне, не попадают вообще; появившиеся
    только в свежем окне идут с `before: null` — «начал делать» это тоже
    ответ на «что изменилось».
    """
    days = _clean_int(tool_input.get("days"), 7, 365) or 90
    user = await db.get_user(user_id)
    today = timeutil.user_today(user)
    recent_from = today - dt.timedelta(days=days)
    prior_from = today - dt.timedelta(days=days * 2)
    formula = user["e1rm_formula"]

    rows = []
    for ex in await db.list_user_exercises(user_id):
        windows: dict[str, list[analytics.SetRow]] = {"before": [], "after": []}
        for row in await db.list_sets_for_exercise(ex["id"]):
            day = dt.datetime.fromisoformat(row["started_at"]).date()
            if day >= recent_from:
                windows["after"].append(analytics.SetRow(db.load_of(row), row["reps"], row["workout_id"], row["started_at"]))
            elif day >= prior_from:
                windows["before"].append(analytics.SetRow(db.load_of(row), row["reps"], row["workout_id"], row["started_at"]))
        if not windows["after"] and not windows["before"]:
            continue

        def _summary(sets: list[analytics.SetRow]) -> Optional[dict[str, Any]]:
            if not sets:
                return None
            sessions = analytics.group_sets_by_session(sets)
            for session in sessions:
                session.formula = formula
            return {
                "workouts": len(sessions),
                "sets": len(sets),
                "top_e1rm": round(max(s.top_e1rm for s in sessions), 1),
                "tonnage": round(sum(s.tonnage for s in sessions)),
            }

        before, after = _summary(windows["before"]), _summary(windows["after"])
        rows.append(
            {
                "exercise": ex["display_name"],
                "before": before,
                "after": after,
                "e1rm_delta": (
                    round(after["top_e1rm"] - before["top_e1rm"], 1)
                    if before and after else None
                ),
            }
        )

    # Сверху — где движение сильнее всего, в любую сторону: и «+12кг в приседе»,
    # и «−8кг в жиме» стоят того, чтобы тренер о них сказал.
    rows.sort(key=lambda r: abs(r["e1rm_delta"]) if r["e1rm_delta"] is not None else 0, reverse=True)
    dropped = [r["exercise"] for r in rows if r["after"] is None]
    started = [r["exercise"] for r in rows if r["before"] is None]
    return {
        "window_days": days,
        "recent": {"from": recent_from.isoformat(), "to": today.isoformat()},
        "previous": {"from": prior_from.isoformat(), "to": recent_from.isoformat()},
        "exercises": rows[:_COMPARE_TOP],
        "stopped_doing": dropped,
        "started_doing": started,
        "note": (
            f"Показаны {min(len(rows), _COMPARE_TOP)} из {len(rows)} упражнений — те, "
            "где e1RM сдвинулся сильнее всего. «before: null» — начал делать в этом "
            "окне, «after: null» — перестал."
        ),
    }


async def _weekly_sets_by_group(user_id: int, days: list[dict[str, Any]]) -> dict[str, int]:
    """Сколько рабочих подходов на группу мышц набирает предложенная программа.

    По всем дням сразу — это и есть недельный объём, с которым сравнивают норму
    6-12. Не считаются упражнения без группы (её не нашлось ни у своих, ни у
    шаблонов) и без числа подходов — лучше не назвать объём, чем назвать неверный.

    Ключи — имена групп на языке атлета: числа отсюда тренер называет ему прямо
    в ответе (промпт это прямо предписывает), а идентичность группы в базе
    русская навсегда. Считаем по идентичности, показываем локализованное — то же
    правило, что и у названий упражнений.
    """
    totals: dict[str, int] = {}
    cache: dict[str, Optional[str]] = {}
    lang = i18n.get_lang()
    for day in days:
        for item in day["items"]:
            if item.get("sets") is None:
                continue
            name = item["name"]
            if name not in cache:
                cache[name] = await db.exercise_group_name(user_id, name)
            group = cache[name]
            if group:
                shown = seed_data.localized_muscle_group_name(group, lang)
                totals[shown] = totals.get(shown, 0) + int(item["sets"])
    return totals


async def _ask_setup_questions(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[list[dict[str, Any]]]]:
    """Разобрать опросник, который тренер хочет задать перед сборкой программы.

    Возвращает (payload для модели, вопросы для показа). Второе — None, если
    спрашивать в итоге нечего.

    ПОЧЕМУ ОПРОСНИК ЛОКАЛЬНЫЙ. Модель отдаёт весь опросник ОДНИМ вызовом, а
    дальше бот сам раскладывает его по одному сообщению, копит ответы и уходит
    к модели ровно один раз — уже за программой. Итого те же два обращения к
    модели, что и у стены из четырёх пронумерованных вопросов одним сообщением:
    ноль ожидания «печатает…» между вопросами и ноль лишних списаний дневной
    квоты. Цена — вопрос №4 не может зависеть от ответа на №1; для этого домена
    терпимо (опыт, травмы, время и сплит почти независимы), а финальная сборка
    всё равно видит все ответы разом. Это НЕ баг и не «недоделанный диалог» —
    чинить это вызовом модели между вопросами не надо.

    Срезанное (лишние вопросы, лишние варианты, длинные строки) возвращается
    модели в payload — тем же приёмом, что у _propose_program: молча урезанный
    опросник модель пересказала бы пользователю в исходном виде.
    """
    raw_questions = tool_input.get("questions")
    if not isinstance(raw_questions, list) or not raw_questions:
        return {"asked": False, "error": "questions пустой — пользователю ничего не задано"}, None

    questions: list[dict[str, Any]] = []
    clamped: list[str] = []
    dropped_choices = 0
    for raw_question in raw_questions[:SETUP_MAX_QUESTIONS]:
        if not isinstance(raw_question, dict):
            continue
        text = str(raw_question.get("question") or "").strip()
        if not text:
            continue
        if len(text) > SETUP_QUESTION_LIMIT:
            text = formatting.shorten(text, SETUP_QUESTION_LIMIT)
            clamped.append(f"вопрос обрезан до {SETUP_QUESTION_LIMIT} символов: «{text}»")

        raw_choices = raw_question.get("choices")
        choices: list[str] = []
        if isinstance(raw_choices, list):
            if len(raw_choices) > SETUP_MAX_CHOICES:
                dropped_choices += len(raw_choices) - SETUP_MAX_CHOICES
            for raw_choice in raw_choices[:SETUP_MAX_CHOICES]:
                choice = str(raw_choice or "").strip()
                if not choice:
                    continue
                if len(choice) > SETUP_CHOICE_LIMIT:
                    choice = formatting.shorten(choice, SETUP_CHOICE_LIMIT)
                    clamped.append(f"вариант обрезан до {SETUP_CHOICE_LIMIT} символов: «{choice}»")
                # Одинаковые подписи — две неотличимые кнопки подряд, тап по
                # любой из которых записывает одно и то же.
                if choice not in choices:
                    choices.append(choice)
        questions.append({"question": text, "choices": choices})

    if not questions:
        return (
            {
                "asked": False,
                "error": (
                    "ни одного пригодного вопроса не пришло (пустые строки или не тот "
                    "формат) — пользователю ничего не задано. Либо вызови инструмент "
                    "заново с нормальными вопросами, либо собирай программу на "
                    "разумных дефолтах и назови их."
                ),
            },
            None,
        )

    payload: dict[str, Any] = {
        "asked": True,
        "questions": [q["question"] for q in questions],
        "note": (
            "Вопросы отправлены пользователю по одному, отдельными сообщениями. "
            "Ответы придут тебе следующим сообщением все разом. Сейчас в тексте "
            "ответа напиши ТОЛЬКО короткое резюме того, что ты уже знаешь из "
            "истории — сами вопросы не повторяй."
        ),
    }
    if len(raw_questions) > SETUP_MAX_QUESTIONS:
        payload["truncated_questions"] = (
            f"вопросов было больше {SETUP_MAX_QUESTIONS}, лишние не заданы"
        )
    if dropped_choices:
        payload["truncated_choices"] = (
            f"вариантов ответа больше {SETUP_MAX_CHOICES} на вопрос не влезает — "
            f"лишние ({dropped_choices}) не показаны"
        )
    if clamped:
        payload["clamped"] = clamped
    return payload, questions


async def _propose_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Разобрать предложенную моделью программу — и ничего не сохранить.

    Возвращает (payload для модели, черновик для показа пользователю). Черновик
    None, если сохранять в итоге нечего. Названия упражнений резолвятся
    read-only (db.resolve_exercise_name): предложение, от которого пользователь
    откажется, не должно оставить у него в каталоге форкнутых упражнений —
    форк случится при сохранении, в db.create_routine_from_program.
    """
    raw_days = tool_input.get("days")
    if not isinstance(raw_days, list) or not raw_days:
        return {"error": "days пустой — программа не показана пользователю"}, None

    program_name, program_name_truncated = _clean_program_name(tool_input.get("name"), "Программа")
    # description объявлено обязательным в схеме, но обязательность у модели —
    # не гарантия: пропущенное поле не должно ронять предложение, иначе человек
    # не увидит собранную программу из-за отсутствующей пары фраз. Программу
    # показываем, а модели говорим, чего не хватает — тем же способом, что и про
    # урезанные дни: пусть допишет вызовом заново.
    description = db.clean_program_description(tool_input.get("description"))
    replaces, replaces_error = await _resolve_replaced_program(
        user_id, tool_input.get("replaces_program")
    )
    truncated_days = len(raw_days) > PROGRAM_MAX_DAYS

    days: list[dict[str, Any]] = []
    report: list[dict[str, Any]] = []
    # Дни, у которых ни одно упражнение не срезолвилось — они не попадают в
    # `days` (в превью пустой день незачем показывать), но раньше пропадали и
    # из ответа модели молча: report держал их с resolved: [], а payload всё
    # равно говорил shown_to_user=True с общей формулировкой, так что модель
    # рассказывала пользователю, например, про 3 дня, когда превью показывало
    # только 2 (см. A10). Собираем их отдельно, чтобы явно сказать модели, что
    # именно пропало и почему.
    dropped_days: list[dict[str, Any]] = []
    seen_day_names: set[str] = set()
    for index, raw_day in enumerate(raw_days[:PROGRAM_MAX_DAYS], start=1):
        if not isinstance(raw_day, dict):
            continue
        raw_exercises = raw_day.get("exercises")
        if not isinstance(raw_exercises, list):
            continue
        day_name, day_name_truncated = _clean_program_name(raw_day.get("name"), f"День {index}")
        day_name = _unique_day_name(day_name, seen_day_names)

        items: list[dict[str, Any]] = []
        unresolved: list[str] = []
        seen: set[str] = set()
        clamped: list[str] = []
        for raw_item in raw_exercises[:PROGRAM_MAX_EXERCISES_PER_DAY]:
            item = _clean_program_item(raw_item)
            if item is None:
                continue
            source, display_name = await db.resolve_exercise_name(user_id, item["name"])
            if source is None:
                unresolved.append(item["name"])
                continue
            key = display_name.lower()
            if key in seen:
                continue
            seen.add(key)
            # target — та же строка, что у готовых программ (routine_exercises.target):
            # схему собираем здесь, чтобы дальше — и в превью, и в тренировке —
            # программа тренера ничем не отличалась от каталожной.
            target = formatting.build_routine_target(
                item["sets"], item["reps_min"], item["reps_max"]
            )
            if item["clamped"]:
                clamped.append(f"{display_name}: {', '.join(item['clamped'])}")
            items.append({**item, "name": display_name, "source": source, "target": target})

        dropped = False
        if items:
            days.append({"name": day_name, "items": items})
        elif raw_exercises:
            # raw_exercises непустой, но ничего из него не срезолвилось (или
            # всё оказалось мусором в _clean_program_item) — весь день исчезнет
            # из превью, и это надо явно назвать, а не молча потерять.
            dropped_days.append({"day": day_name, "unresolved": unresolved})
            dropped = True
        report.append(
            {
                "day": day_name,
                "resolved": [item["name"] for item in items],
                "unresolved": unresolved,
                "truncated_exercises": len(raw_exercises) > PROGRAM_MAX_EXERCISES_PER_DAY,
                # A11: раньше зажатые sets/reps и обрезанное имя дня были видны
                # только в самих числах (10×50 вместо честных 25×100-200) — тут
                # они называются прямо, чтобы модель могла поправиться сама.
                **({"clamped": clamped} if clamped else {}),
                **({"name_truncated": True} if day_name_truncated else {}),
                **({"dropped": True} if dropped else {}),
            }
        )

    if not days:
        return (
            {
                "saved": False,
                "shown_to_user": False,
                "days": report,
                "error": (
                    "ни одно упражнение не совпало с каталогом или упражнениями "
                    "пользователя — программа не показана. Возьми названия точно "
                    "из list_exercise_catalog и вызови инструмент ещё раз."
                ),
            },
            None,
        )

    existing = await db.count_routines(user_id)
    payload: dict[str, Any] = {
        "saved": False,
        "shown_to_user": True,
        "program_name": program_name,
        "days": report,
        # Считаем сами: модель называла это число по своему же черновику и
        # ошибалась — обещала «~12 подходов на грудь» в программе, где их 19,
        # при том что бот в других экранах меряет норму теми же 6-12.
        "weekly_sets_by_group": await _weekly_sets_by_group(user_id, days),
        "note": (
            "Программа показана пользователю кнопкой под твоим ответом. Он ещё "
            "НЕ сохранил её — не пиши, что программа уже добавлена, скажи, что "
            "она ждёт его подтверждения под сообщением. Объём по группам называй "
            "только числами из weekly_sets_by_group — своих не считай."
        ),
    }
    if replaces is not None:
        payload["replaces_program"] = replaces["name"]
        payload["note"] = (
            f"Правка программы «{replaces['name']}» показана пользователю кнопкой под "
            "твоим ответом. Она ещё НЕ применена — не пиши, что уже поправил, скажи, "
            "что правка ждёт подтверждения под сообщением. По тапу старые дни этой "
            "программы заменятся новыми."
        )
    if replaces_error:
        payload["replaces_program_error"] = replaces_error
    if truncated_days:
        payload["truncated_days"] = (
            f"дней было больше {PROGRAM_MAX_DAYS}, лишние отброшены"
        )
    if program_name_truncated:
        payload["program_name_truncated"] = f"имя программы обрезано до {PROGRAM_NAME_LIMIT} символов"
    if not description:
        payload["description_missing"] = (
            "description не прислан — программа сохранится без описания, и на её "
            "экране останутся одни списки упражнений. Вызови propose_program "
            "заново с тем же составом и парой фраз о программе."
        )
    if dropped_days:
        payload["dropped_days"] = dropped_days
        payload["dropped_days_note"] = (
            "Эти дни целиком пропали из превью — ни одно упражнение внутри них "
            "не совпало с каталогом или списком пользователя (см. unresolved у "
            "каждого). Либо вызови propose_program заново, взяв названия точно "
            "из list_exercise_catalog для этих дней, либо явно скажи "
            "пользователю, что эти дни не вошли в предложение и почему."
        )
    # Заменяемые дни освобождают свои места — правка программы того же размера
    # не должна упираться в лимит только потому, что старая версия ещё цела.
    freed = len(replaces["routine_ids"]) if replaces else 0
    if existing - freed + len(days) > MAX_ROUTINES_PER_USER:
        payload["warning"] = (
            f"у пользователя уже {existing} программ при лимите {MAX_ROUTINES_PER_USER} — "
            "при сохранении поместятся не все, предупреди его, что старые стоит удалить"
        )

    # 5.3: те же клампы и потери, что уже уходят модели построчно выше
    # (truncated_days/truncated_exercises/unresolved/name_truncated), собраны
    # тут же человеческими фразами для самого превью — раньше это было видно
    # только модели, и молчаливо урезанная программа («попросил 7 дней, получил
    # 6») зависела от того, упомянет ли модель это в ответе. См.
    # formatting.build_ai_program_preview(notes=...).
    notes: list[str] = []
    if truncated_days:
        notes.append(f"Дней получилось больше {PROGRAM_MAX_DAYS} — показал только первые {PROGRAM_MAX_DAYS}.")
    if program_name_truncated:
        notes.append(f"Имя программы длиннее {PROGRAM_NAME_LIMIT} символов — обрезал.")
    for entry in report:
        if entry.get("name_truncated"):
            notes.append(f"Название дня «{entry['day']}» длиннее {PROGRAM_NAME_LIMIT} символов — обрезал.")
        if entry.get("truncated_exercises"):
            notes.append(
                f"«{entry['day']}»: упражнений было больше {PROGRAM_MAX_EXERCISES_PER_DAY} — лишние не вошли."
            )
        # День, пропавший целиком, назван одной строкой ниже — вместе с тем, что
        # в нём не нашлось. Раньше о таком дне было две заметки подряд («не
        # нашёл в боте — …» и «целиком пропал»), и блок читался как повтор.
        if entry.get("unresolved") and not entry.get("dropped"):
            notes.append(f"«{entry['day']}»: не нашёл в боте — {', '.join(entry['unresolved'])}.")
    for dd in dropped_days:
        lost = ", ".join(dd["unresolved"])
        notes.append(
            f"День «{dd['day']}» не вошёл — не нашёл в боте: {lost}." if lost
            else f"День «{dd['day']}» не вошёл — ни одно упражнение из него не нашлось."
        )

    return payload, {
        "name": program_name,
        # Описание едет в черновике и ложится в programs.description при
        # сохранении: то, что модель рассказывает о программе в чате, живёт
        # ровно до следующего сообщения, а экран программы человек открывает
        # перед каждой тренировкой.
        "description": description,
        "days": days,
        "replaces": replaces,
        "notes": notes,
    }


async def _program_adherence(user_id: int) -> dict[str, Any]:
    """5.5: сколько раз реально тренировались по каждой сохранённой программе.

    get_saved_programs отдаёт только состав; workouts.routine_id записывается с
    самого начала, но до сих пор читался ровно в одном месте бота (экран
    «начать тренировку» → недавние программы). Здесь — по каждой многодневке:
    сколько всего тренировок и по каждому дню — сколько раз и сколько дней с
    последнего (null — ни разу). Одиночные (однодневные) программы сюда
    сознательно не попадают: адхеренс интересен там, где есть выбор между
    днями («ноги забросил, а грудь качаешь через день») — у одного дня выбора
    нет, а его собственная свежесть и так видна в get_saved_programs/истории.
    """
    programs = await db.list_programs(user_id)
    if not programs:
        return {
            "programs": [],
            "note": "У пользователя пока нет ни одной сохранённой многодневной программы.",
        }
    today = await _user_today(user_id)
    out = []
    for p in programs:
        days = await db.list_program_days_by_id(p["id"])
        history = await db.program_day_history(p["id"])
        total_sessions = sum(times for _, times in history.values())
        day_rows = []
        for d in days:
            last_started, times = history.get(d["id"], (None, 0))
            days_since_last = None
            if last_started:
                days_since_last = (today - dt.date.fromisoformat(last_started[:10])).days
            day_rows.append({"day": d["name"], "sessions": times, "days_since_last": days_since_last})
        out.append(
            {
                "program": p["program_name"],
                "created_at": p["created_at"][:10],
                "total_sessions": total_sessions,
                "days": day_rows,
            }
        )
    return {
        "programs": out,
        "note": (
            "sessions — сколько раз реально начинали тренировку по этому дню; "
            "days_since_last — сколько дней прошло с последнего раза, null значит "
            "ни разу не тренировался по этому дню. Хороший состав программы и "
            "реальное следование ей — разные вещи, суди по обоим."
        ),
    }


PROFILE_FIELDS = ("days_per_week", "equipment", "experience", "goal", "limitations")

# Человеческие имена полей профиля — и для кнопки отката, и для экрана
# «🧬 Обо мне» (см. handlers/settings): без них откат читался бы как
# «↩️ Вернуть limitations».
PROFILE_LABELS = {
    "days_per_week": "дни в неделю",
    "equipment": "оборудование",
    "experience": "опыт",
    "goal": "цель",
    "limitations": "ограничения",
}


# Голое отрицание в «ограничениях» — не ответ, а его отсутствие. Живой прогон
# показал, как это ломается: опросник спросил про дни, время, железо, опыт и
# цель — про травмы не спрашивал вовсе, — а тренер отчитался «травм нет» и
# записал это в профиль. Экран «Обо мне» подписан «Записал с твоих слов», и
# человек с больным коленом получал там «Ограничения: нет», которого не
# говорил. На подбор программы это не влияет — «нет ограничений» и «не знаю»
# дают одинаковые программы, — так что терять тут нечего, а спросить ещё раз
# честнее, чем придумать за человека.
_EMPTY_LIMITATIONS = {
    "нет", "неа", "нету", "никаких", "никаких нет", "без ограничений",
    "ограничений нет", "травм нет", "нет травм", "все ок", "всё ок",
    "всё в порядке", "все в порядке", "-", "—", "no", "none",
    # Ровно та кнопка, которую опросник предлагает на вопросе про травмы (см.
    # системный промпт): нажатие на неё не должно записывать человеку
    # «Ограничения: ничего не беспокоит» — это не ограничение, а его отсутствие.
    "ничего не беспокоит", "ничего не болит",
}


def _is_blank_limitation(value: str) -> bool:
    return value.strip().strip(".!,").lower() in _EMPTY_LIMITATIONS


async def _save_athlete_profile(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], None]:
    """3.3: частичная запись профиля тренирующегося в users.* — только те поля,
    что реально прислали этим вызовом (см. db.update_user).

    Раньше дни в неделю/оборудование/опыт/цель/травмы оседали только в
    ai_chat_messages, откуда их надо было доставать get_full_chat_history —
    поэтому тренер переспрашивал одно и то же в каждом новом разговоре.

    Дней в неделю тут нет нарочно, хотя колонка в базе осталась. Это
    единственное поле профиля, которое человек называет не как факт о себе, а
    как параметр запроса: «собери на 2 дня» — это про одну программу, а не про
    то, как он живёт. Запомненная двойка потом молча определяла все следующие
    программы. Сколько дней собирать — спрашивается каждый раз заново, в
    опроснике (см. ask_setup_questions).

    Кнопок под этой записью нет — ни отката, ни подтверждения. Обе прошлые
    попытки провалились об одно и то же: сборка программы зовёт инструмент
    несколько раз за ход, и любая кнопка от него встаёт рядом с «🗂 Забрать:
    <программа>» — то есть ровно там, где человек ищет главное действие, и
    отодвигает его непонятной надписью про профиль.

    Поэтому память тут живая, а не согласованная: пишем сразу, тренер вслух
    говорит, что записал, и правит по первому возражению — новое значение
    перезаписывает старое, а `forget` стирает поле совсем. Плюс раз в неделю
    тренер сам показывает, что о человеке помнит (см. handlers.ai_trainer
    ._memory_reminder), чтобы неверная строчка не жила в профиле годами.
    Постоянный экран — ⚙️ Настройки → 🤖 Что тренер про тебя знает.
    """
    fields: dict[str, Any] = {}
    for key, limit in (("experience", 200), ("goal", 200), ("limitations", 500)):
        value = str(tool_input.get(key) or "").strip()
        if key == "limitations" and _is_blank_limitation(value):
            continue
        if value:
            fields[key] = value[:limit]
    raw_equipment = tool_input.get("equipment")
    if isinstance(raw_equipment, list):
        items = [str(x).strip() for x in raw_equipment if str(x).strip()][:20]
        if items:
            fields["equipment"] = json.dumps(items, ensure_ascii=False)
    # Стирание — часть той же записи, а не отдельный инструмент: человек
    # возражает («да не болит уже ничего», «я не новичок») теми же словами, что
    # и рассказывает о себе, и модели проще попасть в один вызов, чем выбрать
    # между двумя похожими. Стираем ПОСЛЕ разбора присланных полей и только то,
    # что этим же вызовом не записали, — иначе «forget: опыт» вместе с новым
    # опытом затёрло бы как раз то, что человек сейчас сказал.
    raw_forget = tool_input.get("forget")
    forgotten: list[str] = []
    if isinstance(raw_forget, list):
        for key in raw_forget:
            key = str(key).strip()
            if key in PROFILE_LABELS and key not in fields:
                fields[key] = None
                forgotten.append(key)

    if not fields:
        return {"saved": False, "error": "ничего не прислано — профиль не изменился"}, None

    await db.update_user(user_id, **fields)
    written = [key for key in fields if key not in forgotten]
    note_parts = []
    if written:
        note_parts.append(
            "Записано: " + ", ".join(PROFILE_LABELS[key] for key in written)
        )
    if forgotten:
        note_parts.append(
            "Стёрто: " + ", ".join(PROFILE_LABELS[key] for key in forgotten)
        )
    return (
        {
            "saved": True,
            "fields": {key: value for key, value in fields.items() if value is not None},
            "forgotten": forgotten,
            "note": (
                ". ".join(note_parts)
                + ". Скажи об этом человеку одной короткой фразой. Кнопки под "
                "ответом не будет — если он возразит, просто вызови этот "
                "инструмент ещё раз с новым значением или с forget."
            ),
        },
        None,
    )


