def _light_history(history: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Только видимые реплики: без tool-вызовов, их результатов и системных вставок.

    Полную историю (с tool-сообщениями) храним ради кэша, но дешёвому гейту и шагу
    поиска она не нужна и стоила бы токенов на каждый вопрос: им хватает того, о
    чём говорили словами.
    """
    return [
        m for m in history
        if m.get("role") in ("user", "assistant")
        and not m.get("tool_calls")
        and (m.get("content") or "")
    ]


def _trim_wire_history(
    history: list[dict[str, Any]], max_chars: int
) -> list[dict[str, Any]]:
    """Обрезать историю с начала, не сломав структуру запроса.

    Резать где попало нельзя: сообщение role="tool" без своего
    assistant(tool_calls) выше — невалидный запрос, и API отвергнет его целиком.
    Поэтому режем ТОЛЬКО по границам, где следующее сообщение — user: там
    начинается новый ход, и всё, что от него идёт, самодостаточно.

    Любая обрезка ломает префикс и стоит одного промаха кэша, поэтому она редкая:
    порог держим высоким (config.AI_WIRE_HISTORY_MAX_CHARS).
    """
    def size(msgs: list[dict[str, Any]]) -> int:
        return len(json.dumps(msgs, ensure_ascii=False))

    if size(history) <= max_chars:
        return history
    # Границы ходов — индексы user-сообщений, кроме нулевого: срезать до самого
    # начала бессмысленно, это уже пустая история.
    starts = [i for i, m in enumerate(history) if m.get("role") == "user" and i > 0]
    for start in starts:
        candidate = history[start:]
        if size(candidate) <= max_chars:
            logger.info(
                "AI trainer wire history trimmed: %s сообщений → %s (лимит %s символов)",
                len(history), len(candidate), max_chars,
            )
            return candidate
    # Даже последний ход не влезает — оставляем его одного: обрезать внутрь хода
    # нельзя, а отдать пустую историю значит потерять контекст разговора совсем.
    last = history[starts[-1]:] if starts else history
    logger.warning(
        "AI trainer wire history: даже последний ход больше лимита (%s символов), оставляю как есть",
        size(last),
    )
    return last


async def _log_server_tool_calls(user_id: Optional[int], response: Any) -> None:
    """Вызовы серверных инструментов xAI — отдельная строка счёта, помимо токенов.

    web_search и x_search стоят $5 за 1000 вызовов СВЕРХ токенов, и в usage по
    токенам их нет вовсе. В консоли за неделю это было видно как «Web searches:
    136 calls — $0.68», то есть 15% текстового счёта, полностью невидимые у нас.

    Считаем по response.server_side_tool_usage: SDK отдаёт Counter по списку
    использованных инструментов, то есть настоящее число вызовов, а не «был или
    не был». Пишем по строке на вызов — так дневной отчёт считает их простым
    COUNT, как расшифровки голосовых, и новая колонка не нужна.
    """
    usage = getattr(response, "server_side_tool_usage", None) or {}
    for tool_name, calls in usage.items():
        for _ in range(max(0, int(calls))):
            try:
                await db.log_cost_event(user_id, "server_tool", model=tool_name)
            except Exception:
                logger.exception("failed to log server tool cost event")


def _reasoning_of(message_or_delta: Any) -> str:
    """reasoning_content из ответа xAI, если он там есть.

    Поле нестандартное для OpenAI-схемы, поэтому SDK кладёт его в model_extra, а
    не в атрибут — читаем оба места. Нужно оно не для показа (пользователю
    размышления не идут), а для КЭША: по документации xAI отсутствие
    reasoning_content в отправленной назад истории — причина промахов номер один
    у ризонинговых моделей, а промах по нашей шапке в одиннадцать тысяч токенов
    стоит вчетверо дороже попадания.
    """
    direct = getattr(message_or_delta, "reasoning_content", None)
    if direct:
        return direct
    extra = getattr(message_or_delta, "model_extra", None) or {}
    return extra.get("reasoning_content") or ""


def _estimate_tokens_from_text(text: str) -> int:
    """Грубая прикидка токенов, когда провайдер их не прислал (см. _completion_round).

    ~4 символа на токен — не точная ставка ни для английского, ни тем более для
    русского текста, но это не финальная цифра в отчёте, а fallback на случай
    оборванного стрима: лучше приблизительно посчитанные деньги, чем молча
    потерянное cost-событие.
    """
    return max(0, len(text) // 4)


def _estimate_tokens_from_messages(messages: list[dict[str, Any]]) -> int:
    return _estimate_tokens_from_text(json.dumps(messages, ensure_ascii=False))


async def _log_llm_cost(user_id: Optional[int], model: str, usage: Any, *, source: str = "bot") -> None:
    """Fire-and-forget cost_events row for a chat-completion call (see
    db.get_llm_cost_breakdown / admin_tasks.py's daily report).

    Цена того же вызова уходит и в лог: ночной отчёт показывает сумму за сутки, а
    в логе видно каждый запрос отдельно — можно смотреть расход сразу, пока
    помнишь, что именно спрашивали.
    """
    prompt_tokens = usage.prompt_tokens if usage else 0
    completion_tokens = usage.completion_tokens if usage else 0
    # Сколько входа приехало из кэша, если провайдер это сообщает: у xAI совпавший
    # префикс (system + схемы инструментов, около десяти тысяч токенов — см.
    # _cache_headers) стоит сильно дешевле полной ставки. Строку с ценой печатает
    # db.log_cost_event — там сходятся все платные вызовы.
    details = getattr(usage, "prompt_tokens_details", None)
    # У xAI кэш и размышления лежат в разных полях usage, и какие из них приезжают
    # через OpenAI-совместимый эндпоинт — вопрос открытый, поэтому читаем и те, и
    # другие защитно, из обоих возможных мест (SamplingUsage в gRPC зовёт их
    # cached_prompt_text_tokens и reasoning_tokens).
    out_details = getattr(usage, "completion_tokens_details", None)
    cached = (
        getattr(details, "cached_tokens", None)
        or getattr(usage, "cached_prompt_text_tokens", None)
        or 0
    )
    reasoning = (
        getattr(out_details, "reasoning_tokens", None)
        or getattr(usage, "reasoning_tokens", None)
        or 0
    )
    try:
        await db.log_cost_event(
            user_id,
            "llm_call",
            model=model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            cached_tokens=cached,
            reasoning_tokens=reasoning,
            source=source,
        )
    except Exception:
        logger.exception("failed to log llm cost event")


class LimitBlocked(Exception):
    """Настоящий (не preview) отказ ai_limits.check внутри paid_call.

    block несёт всё, что нужно вызывающей стороне, чтобы показать отказ
    голосом тренера (block.user_text) — так же, как она делает это сегодня
    после ручного `ai_limits.check` в хендлерах.
    """

    def __init__(self, block: ai_limits.Block) -> None:
        super().__init__(block.log)
        self.block = block


async def paid_call(
    user_id: Optional[int],
    kind: Optional[str],
    coro_factory: Callable[[], Awaitable[Any]],
    *,
    model: str = config.GROK_MODEL,
    source: str = "bot",
    on_block: Optional[Callable[[ai_limits.Block], Awaitable[None]]] = None,
) -> Any:
    """Единая обёртка «проверить лимит → вызвать модель → залогировать цену»
    для НЕстримящих платных вызовов (`client.chat.completions.create`, один
    ответ, без чанков). Основной агентный `ask()`/`_completion_round` сюда не
    входит — у стрима свой preview и своя раздача чанков по ходу генерации.

    Раньше эти три шага собирались руками в каждом месте вызова, и часть
    новых платных вызовов регулярно забывала кусок: то `ai_limits.check`
    вообще не звался (`comment_on_workout`, `weekly_digest` — до этой правки),
    то cost-событие терялось, если код после ответа модели падал раньше
    `_log_llm_cost`. Следующий платный вызов через `paid_call` написать
    ПРОЩЕ, чем мимо неё: `await paid_call(user_id, kind, lambda: client.chat.
    completions.create(...))` — check, сам вызов и cost-событие уже внутри.

    kind — вид лимита (`ai_limits.KIND_*`) для проверки ПЕРЕД вызовом.
    `None` — у шага нет своей персональной квоты (он не то, что просит
    пользователь и что можно исчерпать за день, а системный шаг: комментарий
    к тренировке, недельный дайджест, разбор импорта — их квота — количество
    тренировок/дней, а не число обращений к модели). Тогда `ai_limits.check`
    не зовётся вовсе, вместо того чтобы придумывать для него кем-то не
    заведённый `kind`.

    Настоящий (не preview) блок поднимает `LimitBlocked` ДО вызова —
    `coro_factory` в этом случае не вызывается ни разу. preview (свой
    аккаунт, ещё не нажавший «Понятно» сегодня) не отменяет шаг нигде в
    проекте — тут так же: `coro_factory` вызывается как обычно, а `on_block`
    получает `Block`, чтобы вызывающая сторона могла показать предупреждение
    (см. `warn_about_limit` в handlers/ai_trainer.py).

    Cost-событие пишется в `finally`, а не после успешной обработки ответа:
    `analyze_food` кидает `ValueError` на битом JSON уже ПОСЛЕ того, как
    деньги потрачены, и без `finally` такой вызов остался бы невидим и в
    логе, и в дневном отчёте.
    """
    if kind is not None:
        block = await ai_limits.check(user_id, kind)
        if block is not None:
            if block.preview:
                if on_block is not None:
                    await on_block(block)
            else:
                raise LimitBlocked(block)
    response = None
    try:
        response = await coro_factory()
        return response
    finally:
        if response is not None:
            await _log_llm_cost(user_id, model, getattr(response, "usage", None), source=source)


def is_configured() -> bool:
    return bool(config.XAI_API_KEY)


def _get_client() -> AsyncOpenAI:
    global _client
    if _client is None:
        _client = AsyncOpenAI(
            api_key=config.XAI_API_KEY,
            base_url=config.GROK_BASE_URL,
            timeout=config.AI_REQUEST_TIMEOUT_SECONDS,
            # SDK's default (2 retries) silently re-fires a paid completion on
            # timeout/5xx — up to three billed generations for one user tap.
            # Retrying that ourselves, on purpose, is a separate decision.
            max_retries=0,
        )
    return _client


