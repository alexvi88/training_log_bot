def muscle_target_group(target: str) -> Optional[str]:
    """Каноническое имя группы, которой принадлежит мишень."""
    for group, targets in MUSCLE_TARGETS_BY_GROUP.items():
        if target in targets:
            return group
    return None


def localized_muscle_target_name(target: str, lang: str) -> str:
    """Имя мишени («Средняя дельта» / «Side delts») на языке `lang`.

    Резолвится на каждом вызове, а не на импорте: процесс один на всех
    (см. tests/test_no_frozen_language.py).
    """
    return i18n.t_in(lang, f"muscle_target.{target}.name")
