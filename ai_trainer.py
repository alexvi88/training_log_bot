def _clean_program_name(raw: Any, fallback: str) -> str:
    name = str(raw or "").strip()
    return name[:PROGRAM_NAME_LIMIT] if name else fallback


def _clean_int(raw: Any, low: int, high: int) -> Optional[int]:
    """Целое из того, что прислала модель, зажатое в границы; None на мусоре."""
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return None
    return max(low, min(value, high))


def _clean_program_item(raw: Any) -> Optional[dict[str, Any]]:
    """Одно упражнение из предложенной программы: имя плюс схема подходов.

    Схема необязательна — тренер может задать только подходы или только
    повторы. Перевёрнутый диапазон («10-5») разворачиваем, а не отбрасываем:
    смысл его очевиден, а терять из-за этого упражнение незачем.
    """
    if isinstance(raw, str):
        raw = {"name": raw}
    if not isinstance(raw, dict):
        return None
    name = str(raw.get("name") or "").strip()
    if not name:
        return None
    reps_min = _clean_int(raw.get("reps_min"), 1, PROGRAM_MAX_REPS)
    reps_max = _clean_int(raw.get("reps_max"), 1, PROGRAM_MAX_REPS)
    if reps_min and reps_max and reps_min > reps_max:
        reps_min, reps_max = reps_max, reps_min
    return {
        "name": name,
        "sets": _clean_int(raw.get("sets"), 1, PROGRAM_MAX_SETS),
        "reps_min": reps_min,
        "reps_max": reps_max,
    }


async def _propose_program(
    user_id: int, tool_input: dict[str, Any]
) -> tuple[dict[str, Any], Optional[dict[str, Any]]]:
    """Разобрать предложенную моделью программу — и ничего не сохранить.

    Возвращает (payload для модели, черновик для показа пользователю). Черновик
    None, если сохранять в итоге нечего. Названия упражнений резолвятся
    read-only (db.resolve_exercise_name): предложение, от которого пользователь
    откажется, не должно оставить у него в каталоге форкнутых упражнений —
    форк случится при сохранении, в db.create_routine_from_program.
    """
    raw_days = tool_input.get("days")
    if not isinstance(raw_days, list) or not raw_days:
        return {"error": "days пустой — программа не показана пользователю"}, None

    program_name = _clean_program_name(tool_input.get("name"), "Программа")
    truncated_days = len(raw_days) > PROGRAM_MAX_DAYS

    days: list[dict[str, Any]] = []
    report: list[dict[str, Any]] = []
    for index, raw_day in enumerate(raw_days[:PROGRAM_MAX_DAYS], start=1):
        if not isinstance(raw_day, dict):
            continue
        raw_exercises = raw_day.get("exercises")
        if not isinstance(raw_exercises, list):
            continue
        day_name = _clean_program_name(raw_day.get("name"), f"День {index}")

        items: list[dict[str, Any]] = []
        unresolved: list[str] = []
        seen: set[str] = set()
        for raw_item in raw_exercises[:PROGRAM_MAX_EXERCISES_PER_DAY]:
            item = _clean_program_item(raw_item)
            if item is None:
                continue
            source, display_name = await db.resolve_exercise_name(user_id, item["name"])
            if source is None:
                unresolved.append(item["name"])
                continue
            key = display_name.lower()
            if key in seen:
                continue
            seen.add(key)
            # target — та же строка, что у готовых программ (routine_exercises.target):
            # схему собираем здесь, чтобы дальше — и в превью, и в тренировке —
            # программа тренера ничем не отличалась от каталожной.
            target = formatting.build_routine_target(
                item["sets"], item["reps_min"], item["reps_max"]
            )
            items.append({**item, "name": display_name, "source": source, "target": target})

        if items:
            days.append({"name": day_name, "items": items})
        report.append(
            {
                "day": day_name,
                "resolved": [item["name"] for item in items],
                "unresolved": unresolved,
                "truncated_exercises": len(raw_exercises) > PROGRAM_MAX_EXERCISES_PER_DAY,
            }
        )

    if not days:
        return (
            {
                "saved": False,
                "shown_to_user": False,
                "days": report,
                "error": (
                    "ни одно упражнение не совпало с каталогом или упражнениями "
                    "пользователя — программа не показана. Возьми названия точно "
                    "из list_exercise_catalog и вызови инструмент ещё раз."
                ),
            },
            None,
        )

    existing = await db.count_routines(user_id)
    payload: dict[str, Any] = {
        "saved": False,
        "shown_to_user": True,
        "program_name": program_name,
        "days": report,
        "note": (
            "Программа показана пользователю кнопкой под твоим ответом. Он ещё "
            "НЕ сохранил её — не пиши, что программа уже добавлена, скажи, что "
            "она ждёт его подтверждения под сообщением."
        ),
    }
    if truncated_days:
        payload["truncated_days"] = (
            f"дней было больше {PROGRAM_MAX_DAYS}, лишние отброшены"
        )
    if existing + len(days) > MAX_ROUTINES_PER_USER:
        payload["warning"] = (
            f"у пользователя уже {existing} программ при лимите {MAX_ROUTINES_PER_USER} — "
            "при сохранении поместятся не все, предупреди его, что старые стоит удалить"
        )
    return payload, {"name": program_name, "days": days}


async def execute_tool(
    user_id: int,
    name: str,
    tool_input: dict[str, Any],
    on_program: ProgramCallback = None,
) -> str:
    if name == "get_training_overview":
        payload = await _training_overview(user_id)
    elif name == "get_active_workout":
        payload = await _active_workout(user_id)
    elif name == "list_recent_workouts":
        limit = tool_input.get("limit") or 5
        limit = max(1, min(int(limit), 10))
        payload = await _recent_workouts(user_id, limit)
    elif name == "get_full_workout_history":
        payload = await _recent_workouts(user_id, FULL_WORKOUT_HISTORY_LIMIT)
    elif name == "get_weekly_volume_by_group":
        payload = await _weekly_volume(user_id)
    elif name == "get_exercise_progress":
        payload = await _exercise_progress(user_id, tool_input.get("exercise_name", ""))
    elif name == "list_exercise_catalog":
        payload = {"catalog": _CATALOG_BY_GROUP}
    elif name == "get_bodyweight_history":
        payload = await _bodyweight_history(user_id)
    elif name == "get_food_diary":
        payload = await _food_diary(user_id, int(tool_input.get("days") or 14))
    elif name == "get_full_chat_history":
        payload = await _full_chat_history(user_id)
    elif name == "propose_program":
        payload, draft = await _propose_program(user_id, tool_input)
        if draft is not None and on_program is not None:
            await on_program(draft)
    else:
        payload = {"error": f"unknown tool: {name}"}
    return json.dumps(payload, ensure_ascii=False)


# ---------- agentic loop ----------

async def ask(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    image_data_url: Optional[str] = None,
    on_status: StatusCallback = None,
    on_program: ProgramCallback = None,
    on_chunk: ChunkCallback = None,
) -> str:
    """Один вопрос пользователя → готовый текст ответа.

    history — прошлые реплики диалога в виде [{"role": ..., "content": <str>}]
    (только видимый текст, без tool-сообщений — их таскать между ходами незачем).

    image_data_url — опционально, фото, которое пользователь прислал вместе с этим
    вопросом (data: URL, base64). Передаётся только в текущий ход; в history фото
    не попадают — модель не сможет пересмотреть их позже, только вспомнить по тексту.

    on_status — опциональный колбэк, которому по ходу дела шлём текст того, что
    реально сейчас происходит (веб-поиск, конкретный tool-call), чтобы вызывающая
    сторона могла показать это пользователю вместо голого "думаю" (см.
    handlers/ai_trainer.py).

    on_program — опциональный колбэк с черновиком программы, если тренер за этот
    ход собрал её (см. propose_program). Текст ответа при этом обычный: черновик
    едет отдельно, потому что сохранить его должен тап пользователя, а не модель.

    Пока не исчерпана дневная квота поисковых ответов (config.AI_SEARCH_DAILY_LIMIT),
    перед основным ответом дешёвый гейт на быстрой модели (см. _search_worth_it)
    решает, нужен ли вопросу живой веб/X-поиск, и только на «да» поднимается
    отдельный дорогой шаг multi-agent поиска (см. _web_search_findings). Найденное
    (если есть) добавляется контекстом к основному REST-вызову с обычными
    инструментами.
    """
    # Дешёвый гейт на быстрой модели (_search_worth_it) решает, стоит ли вообще
    # поднимать дорогой multi-agent поиск, и только на «да» он запускается. Так
    # дорогая модель не дёргается на каждый вопрос (большинство — про личные данные,
    # поиска не требуют). Порядок в and важен: короткое замыкание не даёт вызвать
    # гейт при исчерпанной квоте.
    search_context = None
    if (
        await db.get_ai_search_count_today(user_id) < config.AI_SEARCH_DAILY_LIMIT
        and await _search_worth_it(user_id, question, history)
    ):
        search_context = await _web_search_findings(user_id, question, history, on_status)
    logger.info(
        "AI trainer question from user %s: %r (web search used: %s)",
        user_id, question, bool(search_context),
    )
    return await _ask_plain(
        user_id, question, history, image_data_url, search_context, on_status, on_program,
        on_chunk,
    )


def _plain_user_content(question: str, image_data_url: Optional[str]) -> Any:
    if not image_data_url:
        return question
    return [
        {"type": "text", "text": question},
        {"type": "image_url", "image_url": {"url": image_data_url}},
    ]


# Как часто отдаём накопленный текст наружу во время стрима — см.
# config.AI_STREAM_FLUSH_SECONDS (не на каждый токен: получатель шлёт его в
# Telegram, а там лимиты на частоту запросов).
STREAM_FLUSH_SECONDS = config.AI_STREAM_FLUSH_SECONDS


async def _completion_round(
    client: AsyncOpenAI,
    messages: list[dict[str, Any]],
    user_id: Optional[int],
    on_chunk: ChunkCallback = None,
) -> tuple[str, list[Any]]:
    """One chat-completion turn. Returns (content, tool_calls).

    `on_chunk` включает стриминг: текст отдаётся наружу по мере генерации, не
    чаще чем раз в STREAM_FLUSH_SECONDS. Стримить имеет смысл только тот раунд,
    который окажется финальным, — но какой из них финальный, заранее неизвестно,
    поэтому раунд с tool_calls просто ничего не отдаёт (там текста и нет, а
    происходящее показывают статусы).
    """
    if on_chunk is None:
        response = await client.chat.completions.create(
            model=config.GROK_MODEL, max_tokens=2048, tools=TOOLS, messages=messages,
            extra_body={"reasoning_effort": config.GROK_REASONING_EFFORT},
        )
        await _log_llm_cost(user_id, config.GROK_MODEL, getattr(response, "usage", None))
        m = response.choices[0].message
        return (m.content or ""), list(m.tool_calls or [])

    stream = await client.chat.completions.create(
        model=config.GROK_MODEL, max_tokens=2048, tools=TOOLS, messages=messages,
        extra_body={"reasoning_effort": config.GROK_REASONING_EFFORT},
        stream=True, stream_options={"include_usage": True},
    )
    parts: list[str] = []
    tool_calls: dict[int, dict[str, Any]] = {}
    usage = None
    # Started at "now", not 0: otherwise the first content token always clears
    # the "now - last_flush >= STREAM_FLUSH_SECONDS" check instantly, flashing a
    # single character on screen that then sits unchanged for a full interval.
    last_flush = asyncio.get_running_loop().time()
    async for event in stream:
        usage = getattr(event, "usage", None) or usage
        if not event.choices:
            continue
        delta = event.choices[0].delta
        for tc in getattr(delta, "tool_calls", None) or []:
            slot = tool_calls.setdefault(
                tc.index, {"id": "", "name": "", "arguments": ""}
            )
            slot["id"] += tc.id or ""
            if tc.function:
                slot["name"] += tc.function.name or ""
                slot["arguments"] += tc.function.arguments or ""
        if delta.content:
            parts.append(delta.content)
            now = asyncio.get_running_loop().time()
            if now - last_flush >= STREAM_FLUSH_SECONDS:
                last_flush = now
                await on_chunk("".join(parts))
    await _log_llm_cost(user_id, config.GROK_MODEL, usage)
    return "".join(parts), [_StreamedToolCall(slot) for slot in tool_calls.values()]


class _StreamedToolCall:
    """Собранный из дельт tool-call в форме, которую ждёт остальной код
    (tc.id / tc.function.name / tc.function.arguments)."""

    def __init__(self, slot: dict[str, Any]) -> None:
        self.id = slot["id"]
        self.function = SimpleNamespace(name=slot["name"], arguments=slot["arguments"])


async def _ask_plain(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    image_data_url: Optional[str] = None,
    search_context: Optional[str] = None,
    on_status: StatusCallback = None,
    on_program: ProgramCallback = None,
    on_chunk: ChunkCallback = None,
) -> str:
    client = _get_client()
    messages: list[dict[str, Any]] = [
        {"role": "system", "content": _system_prompt()},
        *history,
    ]
    if search_context:
        messages.append(
            {
                "role": "system",
                "content": f"Результаты живого веб/X-поиска по текущему вопросу пользователя:\n{search_context}",
            }
        )
    messages.append({"role": "user", "content": _plain_user_content(question, image_data_url)})

    content = ""
    for _ in range(MAX_TOOL_ROUNDS + 1):
        content, tool_calls = await _completion_round(client, messages, user_id, on_chunk)
        if not tool_calls:
            break
        if on_status:
            status_text = TOOL_STATUS_TEXTS.get(
                tool_calls[0].function.name, "🔍 копаюсь в данных..."
            )
            await on_status(status_text)
        messages.append(
            {
                "role": "assistant",
                "content": content,
                "tool_calls": [
                    {
                        "id": tc.id,
                        "type": "function",
                        "function": {"name": tc.function.name, "arguments": tc.function.arguments},
                    }
                    for tc in tool_calls
                ],
            }
        )
        for tc in tool_calls:
            try:
                args = json.loads(tc.function.arguments or "{}")
                tool_content = await execute_tool(
                    user_id, tc.function.name, args, on_program=on_program
                )
            except Exception:
                logger.exception("AI trainer tool %s failed", tc.function.name)
                tool_content = json.dumps(
                    {"error": "tool failed, answer from what you already have"}
                )
            messages.append({"role": "tool", "tool_call_id": tc.id, "content": tool_content})

    text = (content or "").strip()
    return text or "Не получилось сформулировать ответ, попробуй переспросить."


def _to_xai_messages(
    history: list[dict[str, Any]],
    question: str,
    image_data_url: Optional[str] = None,
    system_prompt: Optional[str] = None,
) -> list:
    out = [xai_system(system_prompt if system_prompt is not None else _system_prompt())]
    for msg in history:
        content = msg.get("content", "")
        if msg.get("role") == "assistant":
            out.append(xai_assistant(content))
        else:
            out.append(xai_user(content))
    if image_data_url:
        out.append(xai_user(question, xai_image(image_data_url, detail="high")))
    else:
        out.append(xai_user(question))
    return out


async def _search_worth_it(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
) -> bool:
    """Дешёвый гейт перед поиском: решаем на config.GROK_MODEL, нужен ли вопросу
    живой веб/X-поиск вообще.

    Решение «искать или нет» — обычная классификация, ей не нужен веб-доступ,
    поэтому гонять на каждый вопрос отдельный шаг с config.GROK_SEARCH_MODEL
    только ради этого решения — пустой слив бюджета: большинство вопросов к
    боту-дневнику про личные данные пользователя и поиска не требуют. Шаг с
    поиском поднимаем только когда этот гейт сказал «да». Картинку в решение
    не передаём — тема поиска считывается по тексту, а фото у нас почти всегда
    личное (форма, еда), поиска не просит.

    При любой ошибке/неоднозначности возвращаем False: не искать безопаснее и
    дешевле, чем впустую дёргать дорогую модель.
    """
    try:
        client = _get_client()
        response = await client.chat.completions.create(
            model=config.GROK_MODEL,
            max_tokens=3,
            extra_body={"reasoning_effort": config.GROK_QUICK_REASONING_EFFORT},
            messages=[
                {"role": "system", "content": _search_decision_system_prompt()},
                *history,
                {"role": "user", "content": question},
            ],
        )
    except Exception:
        logger.exception("AI trainer search-decision step failed, skipping live search")
        return False
    await _log_llm_cost(user_id, config.GROK_MODEL, getattr(response, "usage", None))
    verdict = (response.choices[0].message.content or "").strip().upper()
    return verdict.startswith("YES")


async def _web_search_findings(
    user_id: int,
    question: str,
    history: list[dict[str, Any]],
    on_status: StatusCallback = None,
) -> Optional[str]:
    """Отдельный шаг перед основным ответом: чистый server-side веб/X-поиск, без
    наших DB-инструментов (см. модуль docstring, почему они разведены по разным
    вызовам). Возвращает найденное текстом или None, если поиск не нужен вопросу
    или сам шаг не удался — в обоих случаях основной ответ просто идёт без него.

    Одиночный линейный запрос (обычно 1 обращение в сеть на вопрос), а не
    параллельный research по многим источникам, поэтому agent_count держим на
    минимуме (config.GROK_SEARCH_AGENT_COUNT, дефолт 4) — раньше он вообще не
    передавался явно, а по докам xAI непереданный effort может отображаться в
    16 агентов, и биллятся токены (включая ризонинг и тул-коллы) всех агентов
    сразу, не только лидера. Если этот шаг когда-нибудь станет вопросом
    "прочесать много независимых источников параллельно" — тогда есть смысл
    поднять agent_count до 16, а не менять модель: grok-4.20-multi-agent
    дешевле grok-4.5 за токен и не в процессе вывода из эксплуатации.

    web_search/x_search — server-side: модель вызывает их и получает результаты
    в рамках одного sample(), без tool_calls, которые нужно было бы исполнять
    самим — поэтому реальное использование поиска видно только постфактум, по
    citations/server_side_tool_usage в ответе. Сам шаг занимает заметное время
    независимо от исхода, поэтому статус про поиск шлём заранее, а не постфактум.

    Фото пользователя в этот шаг НЕ передаём: оно почти всегда личное (форма,
    тело, еда), а тему поиска модель считывает по тексту — незачем форвардить
    личную картинку во внешний веб/X-поиск (тот же довод, что и в _search_worth_it).
    """
    if on_status:
        await on_status("🔎 ищу свежую информацию в сети...")
    try:
        sdk_client = await _get_sdk_client()
        chat_session = sdk_client.chat.create(
            model=config.GROK_SEARCH_MODEL,
            messages=_to_xai_messages(history, question, system_prompt=_search_system_prompt()),
            tools=[xai_web_search(), xai_x_search()],
            max_tokens=1024,
            agent_count=config.GROK_SEARCH_AGENT_COUNT,
        )
        response = await chat_session.sample()
    except Exception:
        logger.exception("AI trainer web search step failed, answering without live search")
        return None

    await _log_llm_cost(user_id, config.GROK_SEARCH_MODEL, getattr(response, "usage", None))
    if not (response.citations or response.server_side_tool_usage):
        return None
    await db.increment_ai_search_count(user_id)
    return (response.content or "").strip() or None
