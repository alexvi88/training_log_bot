async def execute_tool(
    user_id: int,
    name: str,
    tool_input: dict[str, Any],
    on_program: ProgramCallback = None,
    on_action: ActionCallback = None,
    on_questions: QuestionsCallback = None,
    *,
    source: str = "ai_chat",
) -> str:
    if name == "get_training_overview":
        payload = await _training_overview(user_id)
    elif name == "get_active_workout":
        payload = await _active_workout(user_id)
    elif name == "list_recent_workouts":
        limit = tool_input.get("limit") or 5
        limit = max(1, min(int(limit), 10))
        payload = await _recent_workouts(user_id, limit)
    elif name == "get_full_workout_history":
        payload = await _recent_workouts(user_id, FULL_WORKOUT_HISTORY_LIMIT)
    elif name == "get_muscle_recovery":
        payload = await _muscle_recovery(user_id)
    elif name == "get_weekly_volume_by_group":
        payload = await _weekly_volume(user_id)
    elif name == "get_exercise_progress":
        payload = await _exercise_progress(user_id, tool_input.get("exercise_name", ""))
    elif name == "list_exercise_catalog":
        payload = {"catalog": _CATALOG_BY_GROUP}
    elif name == "get_bodyweight_history":
        payload = await _bodyweight_history(user_id)
    elif name == "get_food_diary":
        payload = await _food_diary(user_id, int(tool_input.get("days") or 14))
    elif name == "get_full_chat_history":
        payload = await _full_chat_history(user_id)
    elif name == "get_saved_programs":
        payload = await _saved_programs(user_id)
    elif name == "get_program_adherence":
        payload = await _program_adherence(user_id)
    elif name == "ask_setup_questions":
        payload, questions = await _ask_setup_questions(user_id, tool_input)
        if questions is not None and on_questions is not None:
            await on_questions(questions)
    elif name == "propose_program":
        payload, draft = await _propose_program(user_id, tool_input)
        if draft is not None and on_program is not None:
            await on_program(draft)
    elif name == "save_athlete_profile":
        # Единственная запись без кнопки под ответом: см. _save_athlete_profile.
        payload, _ = await _save_athlete_profile(user_id, tool_input)
    elif name == "compare_periods":
        payload = await _compare_periods(user_id, tool_input)
    elif name in _ACTION_TOOLS or name in _UNDOABLE_TOOLS:
        # Обе категории отдают (payload, действие для кнопки) и обрабатываются
        # одинаково — различаются они только тем, что кнопка означает: у
        # _ACTION_TOOLS она делает дело, у _UNDOABLE_TOOLS отменяет уже сделанное.
        tool = _ACTION_TOOLS.get(name) or _UNDOABLE_TOOLS[name]
        if name == "log_food":
            payload, action = await tool(user_id, tool_input, source=source)
        else:
            payload, action = await tool(user_id, tool_input)
        if action is not None and on_action is not None:
            await on_action(action)
            # Запись веса — единственное действие тут, у которого есть свой
            # постоянный экран (⚖️ Дневник веса): даём прямую ссылку на него,
            # а не только откат — человек мог захотеть глянуть график, а не
            # передумать про саму запись.
            if name == "log_bodyweight":
                await on_action(
                    {"label": i18n.t("ai.action.bodyweight_diary"), "callback": "menu:bodyweight"}
                )
    else:
        payload = {"error": f"unknown tool: {name}"}
    return json.dumps(payload, ensure_ascii=False)


