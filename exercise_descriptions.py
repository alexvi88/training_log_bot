def get_description(exercise_name: str, lang: str | None = None) -> str | None:
    """Built-in technique text for a canonical (Russian) template name.

    `lang` defaults to i18n.get_lang() — the current request's language —
    rather than requiring callers to pass it explicitly. English falls back
    to the Russian text for a template not yet in EXERCISE_DESCRIPTIONS_EN
    (shouldn't happen for anything in seed_data.EXERCISE_TEMPLATES today —
    tests/test_exercise_descriptions.py checks parity between the two dicts —
    but a user's own hand-typed exercise has no catalog entry in either
    language, which is exactly what `None` already covers)."""
    if (lang or i18n.get_lang()) == i18n.DEFAULT_LANG:
        return EXERCISE_DESCRIPTIONS.get(exercise_name)
    return EXERCISE_DESCRIPTIONS_EN.get(exercise_name) or EXERCISE_DESCRIPTIONS.get(exercise_name)


def catalog_description(ex, lang: str | None = None) -> str | None:
    """The built-in description for this exercise, ignoring any personal one.

    Keyed by exercise_media.catalog_key (i.e. `original_name`) rather than the
    live name — see that docstring: renaming a fork used to take the catalog
    text and the demo photos with it.
    """
    return get_description(exercise_media.catalog_key(ex), lang)


def effective_description(ex, lang: str | None = None) -> str | None:
    """The description to actually show for an exercise row: the user's own
    text if they wrote one, else the built-in one for the template it came
    from."""
    return ex["description"] or catalog_description(ex, lang)
