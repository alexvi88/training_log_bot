# Тайм-коды в ответе — «0:04», «0:00.2», «0:12-0:16», иногда просто «12».
_TIMECODE_RE = re.compile(r"\b(?:(\d{1,2}):)?(\d{1,2}(?:\.\d+)?)\b")

# Что с какого ракурса физически видно. Не вкусовщина, а геометрия: вальгус
# коленей — расстояние между коленями во ФРОНТАЛЬНОЙ плоскости, с профиля его
# не измерить; изгиб позвоночника — линия спины В ПРОФИЛЬ, спереди её не видно.
_FRONTAL = ("спереди", "сзади")
_KNEES_INWARD_MARKERS = ("внутрь", "вальгус", "к центру", "сваливают", "заваливают")


def _timecodes(text: str) -> list[float]:
    """Все моменты из текста в секундах. Пустой список — цифр не было."""
    found = []
    for minutes, seconds in _TIMECODE_RE.findall(text or ""):
        try:
            found.append(int(minutes or 0) * 60 + float(seconds))
        except ValueError:
            continue
    return found


